print("")
print("  ★ **答え：等価です。ただし『どちらも物理』ではなく『どちらも記法』の意味で。**")
print("  ★ そして ── **記法の話に見えたものの中に、本物の質問が一つ埋まっていた。**")
print("     それは c でも α 単独でもなく、**どの無次元量が一緒に動くか**。")

print("")
print("=== ⑩ 正直な線 ===")
print("  ・⑧の R ≈ 38 は模型依存で、20〜50 の幅がある。")
print("    R が 10 でも %.0f 倍超過なので結論は変わらないが、" % (10 * webb / mu_bound))
print("    **R をほぼゼロにする模型を作れば逃げられる**（その模型はまだ無い）。")
print("  ・Webb の双極子は、**そもそも系統誤差の議論が決着していない**。")
print("    別の望遠鏡での追試は、有意な変動を見ていない。")
print("  ・④の K の値は計算値（多体計算）で、数 % の不確かさがある。")
print("  ・⑥の GW170817 の上限は伝播距離の仮定に依る。")
print("  ・そして最大の留保 ── **『c が動く』を無意味と言えるのは、**")
print("    **c が一つしか無いと仮定したとき**。二つある理論では意味を持つ。")
print("    無意味なのは c ではなく、**『どの c か言わずに c と言うこと』**。")
