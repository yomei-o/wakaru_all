# -*- coding: utf-8 -*-
# 深掘り⑥：定数どうしの縮退 ──「こっちを変えるのは、あっちを変えるのと同じ」
import math

ln2 = math.log(2)
bic = 0.5 * math.log2(1701)

print("=== ① まず、三つに分ける ===")
kinds = [
    ("A 完全な縮退", "**原理的に**区別できない", "記法の冗長性", "**記法についての発見**"),
    ("B 観測上の縮退", "いまの装置では分けられない", "道具の限界", "**道具についての発見**"),
    ("C 隠れた関係", "独立だと思っていたら関係があった", "自然の構造", "**自然についての発見**"),
]
print("  %-16s %-26s %-20s %s" % ("型", "中身", "正体", "見つけたら何が分かるか"))
for a, b, c, d in kinds:
    print("  %-16s %-26s %-20s %s" % (a, b, c, d))
print("  ★ 質問はこの三つをまたいでいる。**分けないと答えが混ざる。**")

print("")
print("=== ② 型 A ── 完全な縮退は、実際にたくさんある（あった）===")
exact = [
    ("CKM 行列", 9, 4, 5, "クォーク場の位相の付け替え", "5 方向は**まったく観測にかからない**"),
    ("PMNS（ディラック型）", 9, 4, 5, "同上", "同じ"),
    ("PMNS（マヨラナ型）", 9, 6, 3, "位相を 2 個は消せない", "型で個数が変わる"),
]
print("  %-22s %-8s %-8s %-8s %-24s %s" % ("対象", "素の数", "物理", "消える", "消す操作", "意味"))
for a, n0, n1, nd, op, mean in exact:
    print("  %-22s %-8d %-8d %-8d %-24s %s" % (a, n0, n1, nd, op, mean))
print("  → CKM だけで **%.1f ビット**ぶんが記法だった（第5回の値段）。" % (5 * bic))
print("")
print("  もう一つ、もっと深いのがある ── **θ とクォーク質量の位相**：")
print("    物理に効くのは θ̄ = θ + arg det(M_q) という**組み合わせだけ**。")
print("    θ を動かして、同時にクォークの位相を回せば、**何も起きない**。")
print("  ★ **これはまさに質問そのもの。『こっちを変えるのはあっちを変えるのと同じ』。**")

print("")
print("=== ③ 型 A の帰結 ── 標準模型の 19 個には、もう残っていない ===")
print("  第47回で数えた 19 個は、**これらを消したあとの数**。")
print("  → **『完全な縮退はもう無いのか』の答えは、無い。ただし構成上そうしただけ。**")
print("     見つけたら数から引く、という約束で数えているので、残っていたら数え間違い。")
print("  ★ つまり型 A を見つけることは、**自然についてではなく、自分の記法について**")
print("     知ることだった ── 第1回・第3回そのもの。")

print("")
print("=== ④ ところが θ̄ には、まだ続きがある ===")
mu_val, mu_err = 2.16, 0.11      # m_u [MeV]（格子 QCD の代表値）
nsig = mu_val / mu_err
print("  θ̄ が物理的でいられるのは、**クォーク質量がどれもゼロでないから**。")
print("  もし m_u = 0 なら、θ̄ はまるごと回して消せる ── **強い CP 問題が消滅する**。")
print("  実測：m_u = %.2f ± %.2f MeV → ゼロから **%.1f σ**、%.0f ビット" %
      (mu_val, mu_err, nsig, nsig * nsig / 2 / ln2))
print("  ★ **19 個のパラメータは、完全に独立ではない。**")
print("     湯川がひとつ消えれば、θ̄ というパラメータも一緒に消える。")
print("     ── **『定数の個数』そのものが、定数の値に依存している。**")

print("")
print("=== ⑤ 型 B ── 観測上の縮退（番外編①で見つけたもの）===")
obsdeg = [
    ("分光での m_q 方向", "Δμ/μ = 0.048·x₃ − x₂ しか測れない", "条件数 1196 倍", "番外編①"),
    ("CMB での α と m_e", "再結合は結合エネルギー ∝ α²m_e で決まる", "縦長の等高線", "文献でよく知られる"),
    ("原子スペクトルの α と m_e", "総体 ∝ α²m_e、微細構造 ∝ α⁴m_e", "比を取ると α² だけ残る", "**破れる**"),
]
print("  %-28s %-40s %-18s %s" % ("場面", "何が測れるか", "縮退の強さ", "出典"))
for a, b, c, d in obsdeg:
    print("  %-28s %-40s %-18s %s" % (a, b, c, d))
print("")
print("  ★ 三つめが大事：**原子物理での α と m_e の『縮退』は、見かけだけ**。")
print("     微細構造 ÷ 総体 = α² を取れば m_e は落ちる。")
print("  ★ **もっと言えば、m_e は無次元の観測量に最初から現れない。**")
print("     同じ原子の二つの遷移の**比**を取れば、m_e は必ず消える ──")
print("     m_e が顔を出すのは μ = m_p/m_e のような**比**のときだけ。")
print("     → **『α と m_e の縮退』は、次元付きで書いたせいで生まれた幻**（第3回）。")

print("")
print("=== ⑥ 型 C ── 本当に面白いのはここ。隠れた関係＝大統一 ===")
mb, mtau = 4.18, 1.77686     # GeV
ratio = mb / mtau
print("  『こっちを変えるとあっちも変わる』を**理論として主張する**のが大統一。")
print("  SU(5) の予言：大統一スケールで **m_b = m_τ**（b–τ 統一）。")
print("    → 低エネルギーへ走らせると QCD が m_b を持ち上げ、比は 2〜3 になるはず。")
print("    実測： m_b/m_τ = %.3f / %.3f = **%.3f**" % (mb, mtau, ratio))
print("  第19回の作法で驚きを測る：")
lo, hi = 0.1, 10.0
prior_dec = math.log10(hi / lo)
hit_dec = math.log10(1.3)      # 予言 2〜3 の幅に対する命中幅の目安
s = math.log2(prior_dec / hit_dec)
print("    事前を m_b/m_τ ∈ [%.1f, %.0f]（対数一様、%.1f 桁）と取り、" % (lo, hi, prior_dec))
print("    命中幅を係数 1.3 とすると 驚き = **%.1f ビット**" % s)
print("  ★ **4 ビット級 ── 第36回の偶然の帯の、下のほう。**")
print("     『示唆的だが決定的ではない』── 実際、b–τ 統一はまさにそう扱われている。")
print("")
print("  ジョージ–ヤルスコグはさらに 3 対を関係づける（m_s/m_μ = 1/3、m_d/m_e = 3）：")
print("    → パラメータが 3 個減る = **%.1f ビットの圧縮**" % (3 * bic))
print("    ただし関係式の係数（1/3、3）を手で入れるので、そのぶん払う。")

print("")
print("=== ⑦ 核心 ── 三つの型は、見つけたときに意味が違う ===")
mean = [
    ("A 完全な縮退", "パラメータの数を**減らす**", "自然は変わらない", "**記法の掃除**"),
    ("B 観測上の縮退", "パラメータの数は**変わらない**", "自然は変わらない", "**装置の限界の発見**"),
    ("C 隠れた関係", "パラメータの数を**減らす**", "**自然についての主張**", "**物理の発見**"),
]
print("  %-16s %-26s %-22s %s" % ("型", "パラメータ数への効き", "自然についてか", "正体"))
for a, b, c, d in mean:
    print("  %-16s %-26s %-22s %s" % (a, b, c, d))
print("")
print("  ★ **A と C はどちらも数を減らすのに、意味がまったく違う。**")
print("     A は『同じものを二度数えていた』── 掃除。")
print("     C は『二つは本当に繋がっている』── 主張。反証されうる。")
print("  ★ 見分け方：**その関係は、観測で破れうるか。**")
print("     A は破れない（定義上）。C は破れる（b–τ が外れたら SU(5) が死ぬ）。")
print("     ── 第36回の (A)/(B) が、ここにも同じ形で出てくる。")

print("")
print("=== ⑧ このシリーズが見つけてきた『同じことの言い換え』を並べる ===")
same = [
    ("VSL ≡ α が変わる（第28回）", "A", "c を変えるのと α を変えるのは同じ"),
    ("膨張 ≡ 質量が増える（番外編①）", "A", "共形変換の二つの読み方"),
    ("ジョーダン系 ≡ アインシュタイン系", "A", "重力の frame の取り替え"),
    ("θ ≡ クォーク位相（今回②）", "A", "θ̄ だけが物理"),
    ("CKM の 5 方向（今回②）", "A", "位相の付け替え"),
    ("m_b = m_τ at M_GUT（今回⑥）", "C", "**これだけが自然についての主張**"),
]
print("  %-38s %-6s %s" % ("言い換え", "型", "中身"))
for a, t, b in same:
    print("  %-38s %-6s %s" % (a, t, b))
print("")
print("  ★ **このシリーズが 50 回で見つけたものは、ほぼ全部が型 A だった。**")
print("     ── だから『判定は動かない』と言い続けられた。記法の話だったから。")
print("  ★ 型 C（隠れた関係）は、**まだ一つも確立していない**。")
print("     大統一は候補だが 4 ビット級で、決定的ではない。")

print("")
print("=== ⑨ まとめ ===")
print("  ・『こっちを変えるのはあっちを変えるのと同じ』は **三種類ある**。")
print("  ・完全な縮退（A）は**たくさんあった**が、19 個を数える前に全部消してある。")
print("    CKM で 5 方向（%.1f ビット）、θ とクォーク位相で 1 方向。" % (5 * bic))
print("  ・観測上の縮退（B）は**いまも残っている** ── 番外編①の m_q 方向がそれ。")
print("  ・原子物理の α–m_e は**幻**。無次元で書けば m_e は最初から現れない。")
print("  ・隠れた関係（C）を主張するのが大統一。b–τ は **%.1f ビット**、示唆的だが決定的でない。" % s)
print("  ・**19 個は独立ではない**：m_u = 0 なら θ̄ が消える。")
print("    ── 定数の**個数そのものが、定数の値に依存している**。")
