# -*- coding: utf-8 -*-
# 第29回：MOND ── 加速度に隠れた比較相手
import math

c = 299792458.0
H0 = 2.1842e-18            # 67.4 km/s/Mpc
tP = 5.391247e-44
a0 = 1.2e-10               # MOND の加速度スケール [m/s^2]
OmL = 0.685

print("=== ① a_0 は次元付き ── 何と比べて小さいのか ===")
print("  MOND：加速度が a_0 = %.1e m/s² より小さいところでニュートン則が変わる" % a0)
print("  a_0 の次元は L/T²。ウェイトは (+1) − 2(+1) = −1 ── **次元付き＝帳簿**。")
print("  → 第3回の手術がそのまま当たる：『小さい』は比較相手を言うまで文になっていない。")

print("")
print("=== ② 比較相手を探すと、すぐ隣に cH₀ がいる ===")
cH0 = c * H0
cands = [
    ("cH₀", cH0),
    ("cH₀/2π", cH0 / (2 * math.pi)),
    ("c²√(Λ/3) = cH₀√Ω_Λ", cH0 * math.sqrt(OmL)),
    ("cH₀/6", cH0 / 6.0),
]
print("  %-24s %-14s %s" % ("候補", "値 [m/s²]", "a_0 との比"))
for n, v in cands:
    print("  %-24s %-14.4e %.4f" % (n, v, a0 / v))
print("  → どれも O(1)。a_0 は【宇宙の地平面スケールの加速度】と同じ桁にいる。")
print("     ミルグロム自身が最初から指摘している一致（宇宙論的偶然）。")

print("")
print("=== ③ この一致は、共形変換で動くか ===")
print("  加速度 a のウェイト = −1（×a で育つ）")
print("  cH₀ = c/t のウェイト = 0 − (+1) = −1  ← 同じ")
print("  → 比 a_0/cH₀ は無次元＝**共形不変**。第16回のウェイトの地図で 0 の列。")
print("     絵を取り替えても、この一致は一ミリも動かない。")

print("")
print("=== ④ 驚きをビットで測る（第19回の手続き）===")
aP = c / tP
span = math.log10(aP / cH0)
print("  自然界の加速度スケールの幅：")
print("    プランク加速度 c/t_P = %.3e m/s²" % aP)
print("    地平面の加速度  cH₀   = %.3e m/s²" % cH0)
print("    → %.1f 桁" % span)
for w, lab in [(1.0, "係数 10 以内"), (0.5, "係数 3 以内")]:
    s = -math.log2(w / span)
    print("  『%s で一致』の驚き = −log2(%.1f/%.1f) = %.1f bit" % (lab, w, span, s))
print("  → 5〜6 ビット。第19回の目盛りでは【偶然】の帯（ρ_Λ^(1/4) と m_ν の 4.7 bit と同じ層）。")
print("     ただし説明を与える理論（地平面が境界条件を与える型）はあり、その場合は【物理】へ移る。")

print("")
print("=== ⑤ 手術の結果 ── MOND が実際に主張していること ===")
print("  (A) 『加速度が小さい』        … a_0 を天下りで置くだけなら、比較相手を持ち込んだだけ")
print("  (B) 『力学が無次元比 g/a_0 だけで決まる』 … これは観測にかかる主張")
print("  → (B) が本体。そして (B) は実際に強い予言を持つ：")
print("     バリオンの分布だけから回転曲線が決まる（動径加速度関係 RAR）。")

print("")
print("=== ⑥ 記述長で測る（第5回の天秤）── 銀河の回転曲線 ===")
NG = 175          # SPARC の銀河数
ND = 2693         # SPARC の回転曲線データ点数
bic = 0.5 * math.log2(ND)
print("  データ：SPARC（%d 銀河、%d 点）" % (NG, ND))
print("  パラメータ 1 個の値段 = ½log2(%d) = %.2f bit" % (ND, bic))
print("")
rows = [
    ("MOND", 1 + 3, "a_0（全銀河で共通）＋ 内挿関数の形（3 個ぶんと数える）"),
    ("ハロー模型", 2 * NG, "銀河ごとに 2 個（例：NFW の M200 と集中度）"),
]
print("  %-14s %-10s %-14s %s" % ("模型", "パラメータ", "記述長 [bit]", "内訳"))
for n, k, note in rows:
    print("  %-14s %-10d %-14.1f %s" % (n, k, k * bic, note))
d = (2 * NG - 4) * bic
print("  → 差 %.0f ビット、MOND の勝ち（この一つのデータセットに限れば）" % d)
print("  ※ 質量光度比 M/L は両方が銀河ごとに持つので相殺する。")

print("")
print("=== ⑦ ところが、データセットを変えると逆転する ===")
tab = [
    ("銀河の回転曲線", "MOND 圧勝", "パラメータ 4 対 350（上の %.0f ビット）" % d),
    ("銀河団", "ΛCDM", "MOND でも 2 倍程度の未検出質量が残る"),
    ("弾丸銀河団", "ΛCDM", "質量分布とガスが分離している"),
    ("CMB の音響ピーク", "ΛCDM", "6 パラメータで 1701 点、χ²/dof≈1"),
    ("大規模構造の成長", "ΛCDM", "相対論的完成形ごとに結果が違う"),
]
print("  %-20s %-12s %s" % ("データセット", "勝つのは", "理由"))
for a, b, cc in tab:
    print("  %-20s %-12s %s" % (a, b, cc))
print("  ★ 『暗黒物質か MOND か』は一つの問いではない。")
print("     第5回の天秤で測ると、**答えがデータセットごとに違う**ことが露わになる。")

print("")
print("=== ⑧ 検証可能な方向：a_0 は時間変化するか ===")
print("  もし a_0 = cH/2π が【動的な関係】なら、a_0 は H とともに減ってきたことになる。")
for z in (0.0, 0.5, 1.0, 2.0):
    Hz = H0 * math.sqrt(0.315 * (1 + z) ** 3 + OmL)
    print("    z=%.1f: H(z)/H₀ = %.2f → a_0(z)/a_0 = %.2f" % (z, Hz / H0, Hz / H0))
print("  → z=2 で 3.0 倍。高赤方偏移の回転曲線で原理的に判定できる。")
print("     逆に a_0 が【定数】なら、この予言は無い ── 同じ『一致』でも中身が別。")
print("     （観測は現在進行形で、本稿は判定しない）")
