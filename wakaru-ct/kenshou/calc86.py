# ---- 1 ループの RG 方程式 ----
def betas(g1, g2, g3, yt, lam):
    k = 1.0 / (16 * math.pi ** 2)
    b1, b2, b3 = 41 / 10., -19 / 6., -7.
    dg1 = k * b1 * g1 ** 3
    dg2 = k * b2 * g2 ** 3
    dg3 = k * b3 * g3 ** 3
    dyt = k * yt * (4.5 * yt ** 2 - 8 * g3 ** 2 - 2.25 * g2 ** 2 - 0.85 * g1 ** 2)
    dlam = k * (24 * lam ** 2 - 6 * yt ** 4
                + 0.375 * (2 * g2 ** 4 + (g2 ** 2 + 0.6 * g1 ** 2) ** 2)
                + lam * (12 * yt ** 2 - 9 * g2 ** 2 - 1.8 * g1 ** 2))
    return dg1, dg2, dg3, dyt, dlam


def step(y, h):
    def add(a, b, s):
        return [x + s * z for x, z in zip(a, b)]
    k1 = betas(*y)
    k2 = betas(*add(y, k1, h / 2))
    k3 = betas(*add(y, k2, h / 2))
    k4 = betas(*add(y, k3, h))
    return [y[i] + h / 6 * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i]) for i in range(5)]


