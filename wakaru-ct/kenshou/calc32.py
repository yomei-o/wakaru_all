# -*- coding: utf-8 -*-
# 第28回：VSL（光速可変理論）── どこで手術に失敗したのか
import math

print("=== ① 『光速が変わる』の中に、いくつの主張が入っているか ===")
cs = [
    ("マクスウェル方程式の c", "電磁波の伝播速度"),
    ("ローレンツ変換の c", "因果構造・光円錐の傾き"),
    ("E=mc² の c", "質量とエネルギーの換算係数"),
    ("アインシュタイン方程式の c", "曲率と物質の結合 8πG/c⁴"),
]
for n, w in cs:
    print("  %-26s %s" % (n, w))
print("  → この 4 つは別々の量。『c が変わる』はどれが変わるかを言っていない")
print("     （Ellis & Uzan 2005 の指摘）。手術の対象は 2 つではなく 4 つ以上ある。")

print("")
print("=== ② VSL が実際に主張しているのは α の変化 ===")
print("  α = e²/(4πε₀ħc)。VSL は e と ħ を固定して c を動かすので")
print("    Δα/α = −Δc/c")
print("  → 『光速が変わる』の観測にかかる中身は、まるごと『α が変わる』。")

print("")
print("=== ③ α はどれだけ縛られているか（ビットで数える） ===")
BOUNDS = [
    ("実験室（CODATA 2022）", 0.0, 1.6e-10, "α⁻¹=137.035999177(21)"),
    ("原子時計 13.8 Gyr 外挿", 0.0, 1.4e-8, "|α̇/α|<1.0e-18/yr (Lange 2021)"),
    ("オクロ天然原子炉 (1.8 Gyr)", 0.14, 1.1e-8, "Np/Sm 共鳴"),
    ("クエーサー吸収線 (z~2)", 2.0, 1.0e-5, "保守的にまとめた上限"),
    ("CMB (z=1100)", 1100.0, 4.0e-3, "Planck による制約"),
    ("元素合成 (z=4e8)", 4.0e8, 1.0e-2, "⁴He 収量から"),
]
print("  %-28s %-10s %-12s %s" % ("測定", "赤方偏移", "|Δα/α| 上限", "縛られたビット数"))
for n, z, b, note in BOUNDS:
    bits = -math.log2(b)
    print("  %-28s %-10s %-12.1e %.1f bit" % (n, ("%.1e" % z if z > 10 else "%.2f" % z), b, bits))
print("  → 直近の宇宙では 26 ビット、元素合成でも 6.6 ビットが押さえられている。")

print("")
print("=== ④ 地平線問題を解く VSL には、どれだけの c の変化が要るか ===")
print("  共動の粒子的地平線 χ = ∫ c dt/a。c = c₀(a/a₀)^n として輻射期（a∝t^(1/2)）で積むと")
print("    χ ∝ ∫ a^n da = a^(n+1)/(n+1)")
print("  a→0 で発散する条件は  n < −1  （n=0 の標準では χ∝a で発散しない＝地平線問題あり）")
print("  つまり VSL は『過去にさかのぼると c が少なくとも 1/a で増える』ことを要求する。")
print("")
print("  そのとき α は α ∝ 1/c ∝ a^(−n) なので、赤方偏移 z では")
print("    α(z)/α₀ ≥ 1+z")
print("")
print("  %-24s %-14s %-14s %s" % ("時代", "1+z", "要求される Δα/α", "観測上限との比"))
for n, z, b, note in BOUNDS[2:]:
    req = z          # Δα/α ≈ (1+z) − 1 ≈ z （z≫1 のとき）
    if req < 1:
        req = z
    print("  %-24s %-14.1e %-14.1e %.1e 倍" % (n, 1 + z, req, req / b))
print("  ★ 元素合成のところで、要求 4e8 に対し上限 1e-2 ── 10 桁の超過。")
print("     滑らかな冪の VSL で地平線問題を解くことは、元素合成が排除する。")

print("")
print("=== ⑤ 生き残る VSL ── 相転移型 ===")
print("  Albrecht & Magueijo (1999) の VSL は冪ではなく『相転移』：")
print("    ある時刻に c が一気に落ち、以後は一定")
print("  地平線問題を解くには、その時刻より前で c が十分大きければよい。")
print("  元素合成（z=4e8）より前に相転移を置けば、③ の上限には一切かからない。")
zt = 4.0e8
print("  必要な c の落差（プランク期 z=1e32 に置くなら）: %.0e 倍" % 1e32)
print("  → 排除されないが、同時に **元素合成より後には一切の予言を持たない**。")
print("     観測できる時代には α が完全に一定なので、標準宇宙論と区別がつかない。")

print("")
print("=== ⑥ 帳簿：VSL と c・t=一定 を並べる ===")
bic = 0.5 * math.log2(1701)
print("  %-22s %-22s %-22s %s" % ("", "α は動くか", "観測との衝突", "予言"))
print("  %-22s %-22s %-22s %s" % ("冪型 VSL", "動く（O(1)）", "元素合成で 10 桁超過", "反証済み"))
print("  %-22s %-22s %-22s %s" % ("相転移型 VSL", "元素合成より前だけ", "なし", "観測可能な時代にゼロ"))
print("  %-22s %-22s %-22s %s" % ("c・t=一定（共形変換）", "厳密に不変", "なし", "記法。それ自体はゼロ"))
print("  ★ 同じ『光速が変わる』でも、何を固定するかで運命が三つに分かれる。")

print("")
print("=== ⑦ 手術の結果 ===")
print("  『光速が変わる』の中身：")
print("    (A) 単位の取り替え（c だけを動かす）        … 何も言わない")
print("    (B) 無次元量が動くという主張（α が動く）    … 観測にかかる")
print("  VSL は (B) を選んだのに、名前は (A) のまま残した。")
print("  → 名前が中身を隠している。正しい名前は『α 可変理論』。")
print("  c・t=一定 は (A) を選び、(B) を持たない ── だから安全で、だから何も買わない。")
print("  ★ 手術の失敗は『c を動かしたこと』ではなく『c と呼び続けたこと』。")

print("")
print("=== ⑧ 参考：α の走りと混同しないこと ===")
a_low = 137.035999177
a_mz = 127.951
print("  α⁻¹(0) = %.6f、α⁻¹(M_Z) = %.3f（繰り込み群による走り）" % (a_low, a_mz))
print("  差は %.1f%%。これは【エネルギースケール依存】であって【時間変化】ではない。" %
      (100 * (a_low - a_mz) / a_low))
print("  第14回で見た異常次元と同じ軸の話で、③ の上限とは別物。")
