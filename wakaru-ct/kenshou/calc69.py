# 深掘り⑭：情報理論は「クォークは在るのか」に答えられるのか
#           ── 静的な MDL では答えられない。時間順にすると答えが変わる。
import math

bic = 0.5 * math.log2(1701)


def bits(range_dex, rel):
    """事前範囲（桁）と達成相対精度から、稼いだビット数"""
    width_dex = 0.869 * rel
    return math.log2(range_dex / width_dex)


print("=== ① まず、疑いは正しい ── 静的な MDL では区別できない ===")
print("  第5回の天秤が測るのは **記述長 ＋ ずれ** だけ。")
print("  『符号が短い』ことは、**その符号の記号が何かを指している証拠にならない**。")
print("")
print("  歴史的な証拠：1964 年、同じデータに**クォーク抜きの符号**が存在した。")
rivals = [
    ("クォーク模型", "3 種類の構成子がある", "**同程度に短い**"),
    ("S 行列（核民主主義）", "構成子は無い。どれも基本でない", "**同程度に短い**"),
    ("レッジェ極", "質量とスピンの直線関係だけ", "**同程度に短い**"),
]
print("  %-26s %-34s %s" % ("符号", "存在論", "1964 年の記述長"))
for a, b, c in rivals:
    print("  %-26s %-34s %s" % (a, b, c))
print("")
print("  ★ **1964 年のデータだけでは、三つは区別できなかった。**")
print("     しかも当時の主流は S 行列の側で、クォークは少数派だった。")
print("  ★ → **この時点で『クォークは在る』と言うのは、根拠がなかった。**")
print("     情報理論から見て怪しい、という感覚は **1964 年については正しい**。")

print("")
print("=== ② 直し方 ── 符号を時間順に使わせる（prequential）===")
print("  規則：**時刻 t のデータを符号化するとき、t より前のデータしか使ってよくない。**")
print("  すると二つが分かれる：")
split = [
    ("ただの記法", "既にあるデータを短く書き直しただけ", "**事後の利得は厳密に 0**"),
    ("世界についての主張", "まだ無いデータも短く書ける", "**利得が累積し続ける**"),
]
print("  %-22s %-38s %s" % ("種類", "何をしているか", "事後（prequential）利得"))
for a, b, c in split:
    print("  %-22s %-38s %s" % (a, b, c))
print("")
print("  ★ **『在る』を、この利得が正であることと定義してみる。**")
print("     記法は未来を圧縮できない。物は圧縮できる。")

print("")
print("=== ③ クォークの事後利得を、1964 年より後だけで数える ===")
post = [
    ("1968 スケーリング（点状）", bits(1.5, 0.15), "SLAC"),
    ("1973 ⟨Q²⟩ = 5/18（分数電荷）", bits(1.0, 0.07), "Gargamelle"),
    ("1974 チャームの質量（予言済み）", bits(2.0, 0.25), "J/ψ"),
    ("1976 π⁰ → γγ の幅（N_c²）", bits(1.5, 0.015), "色 = 3"),
    ("1978 R 比（色 = 3）", bits(1.0, 0.10), "e⁺e⁻"),
    ("1979 グルーオン（運動量の 46 %）", bits(1.0, 0.20), "3 ジェット"),
    ("1980s〜 スケーリング違反の形（DGLAP）", bits(1.0, 0.05), "HERA"),
]
tot = 0.0
print("  %-38s %-10s %s" % ("1964 年より後に当たったもの", "ビット", "どこで"))
for a, b, c in post:
    tot += b
    print("  %-38s %-10.1f %s" % (a, b, c))
pay = 3 * bic
print("  %-38s **%.1f**" % ("合計（事後のみ）", tot))
print("")
print("  払い（u, d, s の 3 種類）＝ %.1f ビット" % pay)
print("  ★ **事後利得 %.1f / 払い %.1f = %.1f 倍。**" % (tot, pay, tot / pay))
print("  ★ 記法なら、この列は**全部 0** でなければならない。")

print("")
print("=== ④ さらに強い証拠 ── 別の理論が同じ数を要求した ===")
print("  電弱理論が数学的に無矛盾であるためには、")
print("  **1 世代の電荷の和がゼロ**でなければならない（重力アノマリーの相殺）。")
print("")
print("  和 = N_c × (2/3) + N_c × (−1/3) + 0 + (−1) = **N_c/3 − 1**")
print("")
print("  %-14s %-16s %s" % ("N_c", "電荷の和", "電弱理論は"))
for nc in [1, 2, 3, 4, 5]:
    ssum = nc / 3.0 - 1.0
    ok = "**無矛盾**" if abs(ssum) < 1e-12 else "壊れる"
    print("  %-14d %-16.4f %s" % (nc, ssum, ok))
print("")
print("  ★ **N_c = 3 と 2/3, −1/3 が、ハドロンと何の関係も無い条件から出てくる。**")
print("     ハドロン分光のための記帳装置に、")
print("     **電弱理論を無矛盾にする義理は無い**。")
print("  ★ 整数電荷（1, 0）だと和 = N_c − 1 → N_c = 1 が要求され、")
print("     それは π⁰ の幅でも R 比でも**桁で外れる**。三つが同時には立たない。")
print("  ★ MDL の言葉では ── **独立な二つのデータ集合が、同じパラメータを共有した**。")

print("")
print("=== ⑤ これは実在論の古典的な判定法そのもの（ペランの原子）===")
print("  1908〜13 年、ペランはアボガドロ数を**13 通りの無関係な方法**で測った：")
methods = ["ブラウン運動（変位）", "ブラウン運動（回転）", "沈降平衡", "気体の粘性",
           "黒体輻射", "α 崩壊の計数", "臨界タンパク光", "空の青さ",
           "電気素量", "誘電率", "希薄溶液", "液体の圧縮率", "X 線回折"]
nm = len(methods)
print("    " + "、".join(methods[:6]))
print("    " + "、".join(methods[6:]))
p_one = 0.13          # 一致窓 0.13 桁（±15 %）
p_range = 2.0         # 事前範囲 2 桁
b_atom = (nm - 1) * math.log2(p_range / p_one)
print("")
print("  ★ **13 個が同じ値に落ちた。** もし原子が無ければ、")
print("     これは 13 個の無関係な定数が偶然そろったことになる。")
print("    偶然の確率 = (%.2f/%.1f)^%d → **%.1f ビット**" %
      (p_one, p_range, nm - 1, b_atom))
print("  ★ 払いは **パラメータ 1 個（N_A）＝ %.2f ビット**。" % bic)
print("  ★ **原子は、この物差しで史上いちばんきれいな『実在』の事例。**")
print("     オストヴァルトが 1909 年に原子論に転向したのは、まさにこれを見て。")

