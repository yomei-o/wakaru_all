import math

alpha0 = 7.2973525693e-3
inv0 = 1.0 / alpha0
MZ = 91.1876
me = 0.51099895e-3

print("=== ① 『数え上げ』であるための条件を、先に決めておく ===")
cond = [
    ("(1) 整数が先に指定されている", "後から探した数は log₂M を払う（深掘り㉑）",
     "エディントンは 136→137 と**変更した**"),
    ("(2) どのスケールの α かが決まっている", "**α は走る。数は走らない**", "②で見る"),
    ("(3) 別のことも予言する", "一点を当てるだけでは足りない", "第66回の帳簿"),
]
print("  %-34s %-38s %s" % ("条件", "理由", "例"))
for a, b, c in cond:
    print("  %-34s %-38s %s" % (a, b, c))

print("")
print("=== ② 決定的な障害 ── α は走る ===")


scales = [("零運動量（トムソン極限）", 0.0), ("m_μ", 0.1057), ("M_Z", MZ),
          ("1 TeV", 1000.0), ("10 TeV", 1e4)]
print("  %-28s %-16s %s" % ("スケール", "1/α", ""))
for nm, mu in scales:
    if mu == 0.0:
        v = inv0
        note = "**ここだけが 137**"
    else:
        s = sum(2 * math.log(mu / m) - 5.0 / 3.0
                for m in [me, 0.1056583755, 1.77686] if mu > m)
        dal = alpha0 / (3 * math.pi) * s
        # ハドロン寄与を M_Z で 0.0276 として対数で近似的に足す
        had = 0.0276 * (math.log(mu / 0.3) / math.log(MZ / 0.3)) if mu > 0.3 else 0.0
        v = inv0 * (1 - dal - had)
        note = "レプトン＋ハドロン（粗い）"
    print("  %-28s %-16.3f %s" % (nm, v, note))
print("")
print("  ★ **『137』が出るのは零運動量極限だけ。** M_Z では 129 前後、1 TeV では 127 台。")
print("  ★ **整数は走りません。** だから数え上げの主張は、")
print("     **「どのスケールの α が整数なのか」を言わなければ意味を持ちません**。")

print("")
print("=== ③ そして零運動量の α には、電子質量が入っている ===")
e_term = (2 * math.log(MZ / me) - 5.0 / 3.0) / (3 * math.pi)
print("  1/α(0) − 1/α(M_Z) のうち、電子ループの寄与：")
print("    (1/3π)[2 ln(M_Z/m_e) − 5/3] = **%.3f**" % e_term)
print("  もし m_e が 2 倍だったら、この項は %.3f 減る → 1/α(0) ≈ **%.3f**" %
      (2 * math.log(2) / (3 * math.pi), inv0 - 2 * math.log(2) / (3 * math.pi)))
print("")
print("  ★ **137.036 は「電磁気だけの数」ではありません。**")
print("     湯川結合（電子質量）が対数で混ざっている。")
print("  ★ 数え上げで出すなら、**その数え上げは電子質量も含まなければならない**。")
print("     ── 結合定数の数え上げに、質量が入るのは不自然。")
print("  ※ ただし依存は対数なので弱い（2 倍で 0.15 しか動かない）。**致命傷ではない**。")

print("")
print("=== ④ 歴史上ただ一つ、まともな数え上げの試み ── エディントン ===")
print("  1929 年、エディントンは 1/α を**自由度の数え上げ**で出そうとした：")
print("    16 成分の波動関数 → 16×16 = 256 の行列")
print("    独立な成分 (256−16)/2 + 16 = **136**")
print("    のちに 1 を足して **137**")
n = 16
v136 = (n * n - n) // 2 + n
print("")
print("  計算し直すと： (%d² − %d)/2 + %d = **%d**" % (n, n, n, v136))
print("  実測 1/α = **%.6f**" % inv0)
print("")
print("  ★ **これは本物の数え上げ論法でした。** 条件 (1) と (3) は満たしている。")
print("  ★ 落ちた理由は二つ：")
print("     ・**136 が外れたので 137 に変えた** → 探索の値段を払っていない")
print("     ・**α は整数ではない**（.036 のずれは測定誤差の %.0e 倍）" %
      (0.036 / (inv0 * 1.5e-10)))
print("  ★ 現代の測定精度では、**137 との差は 2 億 σ**。整数説は完全に死んでいます。")

print("")
print("=== ⑤ ところが ── α の「まわり」は数え上げだらけ ===")
print("  α 自身は数え上げでなくても、隣は全部そうです。")
around = [
    ("色の数 N_c = 3", "**数え上げ**", "群の次元"),
    ("クォーク電荷の 1/3", "**数え上げ**", "N_c で割る"),
    ("β 関数の係数", "**数え上げ**", "荷電粒子の Σ N_c Q²"),
    ("アノマリー係数", "**整数**", "位相"),
    ("主量子数 n", "**整数**", "閉じた道に入る波"),
    ("**α 自身**", "**数え上げでない**", "**境界条件**"),
]
print("  %-26s %-20s %s" % ("量", "型", "出どころ"))
for a, b, c in around:
    print("  %-26s %-20s %s" % (a, b, c))

print("")
print("=== ⑥ 本物の整数関係が一つある ── ディラックの量子化 ===")
print("  磁気単極子が一つでも存在すれば、電荷は量子化される：")
print("      **e · g = n · ħc/2**  （n は整数）")
print("  両辺を二乗して ħc で割ると：")
print("      **α · α_g = n²/4**    （α_g = g²/4πħc）")
print("")
for n_ in [1, 2, 3]:
    ag = n_ ** 2 / (4 * alpha0)
    print("    n = %d → α_g = %d²/(4α) = **%.2f**" % (n_, n_, ag))
print("")
print("  ★ **α が入った、厳密な整数関係です。** そして n は**巻きつき数**（数え上げ）。")
print("  ★ ただし ── **決まるのは α と α_g の「積」だけ**。α 単独は決まりません。")
print("  ★ 帰結：n = 1 でも α_g = **%.1f ≫ 1**。" % (1 / (4 * alpha0)))
print("     **磁気単極子は必ず強結合**。摂動論が使えない。")
print("     ── これは実際に知られている結論で、**予言になっています**（条件 (3) を満たす）。")

print("")
print("=== ⑦ 大統一 ── 数え上げが α の一部を実際に説明する ===")
print("  ワインバーグ角は、統一点では**表現のトレース比**で決まります：")
print("      sin²θ_W = Tr(T₃²) / Tr(Q²)")
print("")
print("  SU(5) の 5̄ ＝ (d^c × 3 色、Q=+1/3) ＋ (ν, e) で数えると：")
tr_t3 = 0.5 ** 2 + 0.5 ** 2
tr_q = 3 * (1.0 / 3) ** 2 + 0 + 1
print("    Tr(T₃²) = 0（d^c は SU(2) 一重項）＋ (1/2)² + (−1/2)² = **%.4f**" % tr_t3)
print("    Tr(Q²)  = 3×(1/3)² + 0² + (−1)² = **%.4f**" % tr_q)
print("    sin²θ_W = %.4f / %.4f = **%.4f = 3/8**" % (tr_t3, tr_q, tr_t3 / tr_q))
print("  ★ **純粋な数え上げから、有理数 3/8 が出ます。**")
print("")
print("  では、そこから低エネルギーまで走らせると合うか ── 実際に計算します。")
inv1, inv2, inv3 = 59.0, 29.6, 8.5      # M_Z での GUT 正規化した 1/α_i（実測）
for nm, (b1, b2, b3) in [("標準模型", (41 / 10., -19 / 6., -7.)),
                         ("**MSSM**", (33 / 5., 1., -3.))]:
    # 1/α_i(μ) = 1/α_i(M_Z) − (b_i/2π) ln(μ/M_Z)
    t = (inv1 - inv2) / ((b1 - b2) / (2 * math.pi))
    if t <= 0:
        print("  %-12s 1 と 2 が交わらない" % nm)
        continue
    invU = inv2 - b2 / (2 * math.pi) * t
    inv3_at = inv3 - b3 / (2 * math.pi) * t
    MG = MZ * math.exp(t)
    print("  %-12s 統一スケール **%.1e GeV**、1/α_U = %.2f、"
          "そこでの 1/α_3 = %.2f → **ずれ %.1f %%**" %
          (nm, MG, invU, inv3_at, abs(inv3_at - invU) / invU * 100))
print("")
print("  ★ **MSSM だと三本が 0.4 % で交わる。** 標準模型だと 13 % 外れる。")
print("  ★ これは **α の一部が数え上げで説明された**例です ── ")
print("     b_i は**粒子を数えた有理数**、3/8 は**表現を数えた有理数**。")
print("     残るのは **α_U というただ一つの実数**。")
print("  ★ つまり **『α は 1 個の実数 ＋ 数え上げ』にまで還元できている**。")
print("     ただし ── **その 1 個は、依然として数え上げではない**。")

