# -*- coding: utf-8 -*-
# 第22回：宇宙という計算機の、命令セット
import math
c=299792458.0; hbar=1.054571817e-34; G=6.67430e-11
t0=4.3536e17; RH=c*t0; Mpc=3.0857e22; Lsun=3.828e26
E=c**4*RH/(2*G)
V=4*math.pi/3*RH**3
Om_L,Om_c,Om_b,Om_g,Om_nu=0.685,0.265,0.049,5.4e-5,3.8e-5
print(f"=== 第1回のおさらい ===")
print(f"  地平面内の全エネルギー E = {E:.3e} J")
print(f"  総演算数 Ω = (ct/ℓ_P)²/2π = 1.04e121（マルゴラス＝レヴィティン限界の積算）")
print("  ── ただし『演算』の中身は空欄のままだった。今回それを埋める。")

print("\n=== ML レートはエネルギーに比例する → 演算はエネルギー割り当てで決まる ===")
comp=[("暗黒エネルギー",Om_L),("暗黒物質",Om_c),("バリオン",Om_b),
      ("光子",Om_g),("ニュートリノ",Om_nu)]
print(f"  {'成分':16s} {'エネルギー割合':>12} {'今日の演算レート':>16}")
for n,f in comp:
    print(f"  {n:16s} {f*100:11.4f}% {2*E*f/(math.pi*hbar):16.3e} /s")
print(f"  合計 {sum(f for _,f in comp)*100:.3f}%")

print("\n=== ★ ここで効く一言：真空は基底状態なので、遷移する先がない ===")
print("  ML 限界の E は『基底状態からのエネルギー』。真空エネルギーはその基底そのもの。")
print(f"  → 演算に数えるべきでない。演算資源の {Om_L*100:.1f}% が最初から消える。")
rest=1-Om_L
print(f"  残り {rest*100:.1f}% のうち、暗黒物質が {Om_c/rest*100:.1f}%")
print("  暗黒物質も、我々の知る限り重力以外に相互作用しない ── つまり何もしていない。")
act=Om_b+Om_g+Om_nu
print(f"  『何かしている』と言えるのは {act*100:.3f}%（バリオン＋放射）")
print(f"  真空を除いた中でも {act/rest*100:.1f}%")

print("\n=== 星として輝いたエネルギーは、どれだけか ===")
j=2e8   # L_sun / Mpc^3（ボロメトリック光度密度の目安）
Vmpc=V/Mpc**3
L=Vmpc*j*Lsun
Erad=L*t0
print(f"  ハッブル体積 {Vmpc:.3e} Mpc³ × 光度密度 {j:.0e} L_sun/Mpc³")
print(f"  → 総光度 {L:.3e} W、宇宙年齢ぶんで {Erad:.3e} J")
print(f"  E_total に対する割合 = {Erad/E:.3e}")
print(f"  → 宇宙が誕生以来『星として輝いた』エネルギーは、全体の {Erad/E:.1e}（百万分の1）")

print("\n=== 命令セットの内訳（まとめ）===")
rows=[("真空（遷移先なし）",Om_L,"何も起きない"),
      ("暗黒物質（重力のみ）",Om_c,"何も起きない"),
      ("バリオン",Om_b,"化学・核融合・生命"),
      ("放射",Om_g+Om_nu,"自由伝播のみ"),
      ]
print(f"  {'成分':22s} {'割合':>9}  {'やっていること'}")
for n,f,d in rows:
    print(f"  {n:22s} {f*100:8.3f}%  {d}")
print(f"\n  ★ 演算資源の {(Om_L+Om_c)*100:.1f}% が『何も起きない』成分に割り当てられている")
print(f"    残る {act*100:.2f}% のうち、星の光は全体の {Erad/E:.0e}")

print("\n=== 1粒子あたりの『クロック』 ===")
kT=2.349e-4*1.602e-19   # J
print(f"  CMB 光子 1 個の角振動数 ω ~ k_BT/ħ = {kT/hbar:.3e} /s")
print(f"  宇宙年齢ぶんの位相回転 = {kT/hbar*t0:.3e} 回")
print(f"  → 光子1個が『刻んだ回数』は {kT/hbar*t0:.1e}。第1回の 1ビットあたり 0.035 回と比べると桁違い")
print("     （ML の『演算』は系全体の直交遷移で、粒子ごとの位相回転とは別物）")
