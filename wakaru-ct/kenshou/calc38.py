# -*- coding: utf-8 -*-
# 第34回：共形重力（マンハイム）── 後付けでない共形対称性はありうるか
import math

c = 299792458.0
G = 6.67430e-11
Msun = 1.98892e30
pc = 3.0857e16
kpc = 1000 * pc
RH = 1.3052e26
lP = 1.616255e-35
H0 = 2.1842e-18
a0_mond = 1.2e-10

print("=== ① 作用を取り替える ===")
print("  アインシュタイン＝ヒルベルト： S = (1/16πG) ∫ √−g R d⁴x")
print("  共形重力（Weyl²）：           S = −α_g ∫ √−g C_μνρσ C^μνρσ d⁴x")
print("")
print("  ウェイトを数える（第11回とまったく同じ手続き）：")
print("    √−g d^D x        → Ω^D")
print("    C_μνρσ C^μνρσ    → Ω^(−4)")
print("    合わせて          → Ω^(D−4)")
for D in (2, 3, 4, 5, 6):
    e = D - 4
    tag = "  ← ぴったり共形不変" if e == 0 else ""
    print("      D = %d : Ω^%+d%s" % (D, e, tag))
print("  ★ **D = 4 でだけ共形不変** ── 第11回のマクスウェル作用と、まったく同じ構造。")

print("")
print("=== ② 結合定数が無次元になる ===")
print("  G の次元は m³kg⁻¹s⁻² ── 次元付き＝帳簿（第7回）")
print("  α_g は**無次元** ── ウェイト 0 ＝ 物理の列（第16回の地図）")
print("  → 共形重力では、重力の結合が最初から『動かせない側』にいる。")
print("     第7回で「G を動かしても何も起きない」と数えたのは、G が帳簿だったから。")
print("     α_g にはその逃げ道が無い ── **測れば決まる**。")

print("")
print("=== ③ 宇宙定数項が、書けなくなる ===")
print("  宇宙定数項： ∫ √−g Λ d⁴x → Ω⁴ ── **共形不変でない**")
print("  → 対称性が禁じるので、そもそも作用に書けない。")
print("  ★ 第12回で数えた ρ_Λ/M_Pl⁴ = 1.13e-123 の微調整（408 ビット）が、")
print("     **構造的に消える** ── パラメータを増やさずに。")
print("  ※ ただし粒子に質量を与えるには対称性を破る必要があり、そこで Λ が戻る。")
print("     マンハイムは同じ破れが真空エネルギーを相殺すると主張 ── **論争中**。")

print("")
print("=== ④ 真空解に、線形項が出る ===")
print("  静的球対称解：")
print("    B(r) = 1 − 3βγ − β(2−3βγ)/r + γr − κr²")
print("  ニュートン項 −2β/r に加えて、**遠方で効く線形項 +γr** がある。")
b_star = 1.475e3          # β* = GM☉/c² [m]
g_star = 5.42e-41         # γ*  [1/m] （太陽質量あたり）
g_0 = 3.06e-28            # γ_0 [1/m] （宇宙論的な項）
print("    β* = GM☉/c² = %.3e m" % b_star)
print("    γ* = %.2e 1/m（太陽質量あたり）" % g_star)
print("    γ_0 = %.2e 1/m（宇宙論的な項）" % g_0)

print("")
print("  銀河ごとの線形項： γ = γ*N* + γ_0/2")
print("  %-16s %-12s %-14s %-14s %s" % ("銀河の星質量", "β [m]", "γ [1/m]", "交差半径 r*", "備考"))
for N in (1e9, 1e10, 1e11, 1e12):
    beta = b_star * N
    gam = g_star * N + g_0 / 2
    rstar = math.sqrt(2 * beta / gam)
    print("  %-16.0e %-12.3e %-14.3e %-14s %s" %
          (N, beta, gam, "%.1f kpc" % (rstar / kpc),
           "この半径から線形項が勝つ"))
print("  ★ 交差半径が **数十 kpc** ── ちょうど回転曲線が平坦になるところ。")
print("     暗黒物質を入れずに、この一つの項で説明しようという狙い。")

print("")
print("=== ⑤ γ_0 も、宇宙論スケールにいる ===")
inv_RH = 1.0 / RH
print("  γ_0 = %.2e 1/m、1/R_H = %.2e 1/m" % (g_0, inv_RH))
print("  比 γ_0/(1/R_H) = %.3f  →  γ_0 ≈ 1/(%.0f R_H)" % (g_0 / inv_RH, inv_RH / g_0))
acc = c * c * g_0 / 2
print("  線形項が与える加速度 c²γ_0/2 = %.2e m/s²" % acc)
print("    MOND の a_0 = %.1e との比 %.3f" % (a0_mond, acc / a0_mond))
print("    cH₀ = %.2e との比 %.4f" % (c * H0, acc / (c * H0)))
span = math.log10((1 / lP) / inv_RH)
sur = -math.log2(math.log10(25.0) / span)
print("  第19回の手続きで驚きを測る：")
print("    逆長さの幅 1/ℓ_P 〜 1/R_H = %.1f 桁" % span)
print("    『係数 25 以内で一致』の驚き = %.1f ビット" % sur)
print("  ★ 第29回の MOND（5.9 ビット）と**ほぼ同じ層**。")
print("     加速度スケールが宇宙論スケールに一致する、という同じ形の偶然。")

print("")
print("=== ⑥ 代償 ── ゴースト ===")
print("  作用が微分 4 階なので、伝播関数が二つに割れる：")
print("    1/[k²(k²+M²)] = (1/M²)[ 1/k² − 1/(k²+M²) ]")
print("  → 第2項の**符号が負**。負ノルム状態＝ゴースト。")
print("  意味：エネルギーが下に非有界、またはユニタリ性の破れ。")
print("")
print("  ★ ここで面白い取引が起きている：")
print("    前シリーズ第9回：アインシュタイン重力では**共形因子がゴースト**だった")
print("    共形重力：共形因子はゲージ自由度なので、**その問題は消える**")
print("    ところが微分 4 階が、**質量を持つスピン 2 のゴースト**を新しく連れてくる")
print("  → ゴーストを消したのではなく、**別のゴーストと取り替えた**。")

print("")
print("=== ⑦ マンハイム＝ベンダーの反論 ===")
print("  『ハミルトニアンはエルミートではないが PT 対称であり、")
print("   適切な内積を取れば固有値は実で、負ノルム状態も現れない』")
print("  → 論文として出ている真面目な反論だが、**合意は無い**。")
print("  本稿は判定しない。ただし『どこに賭けているか』は第31回の CCC と同じ形。")

print("")
print("=== ⑧ 手術：切るものが無い ===")
print("  第27〜33回の理論はどれも (A) 記法 と (B) 主張 に切れた。")
print("  共形重力は違う ── 共形変換は**書き換えではなくゲージ対称性**。")
print("  つまり (A) が『別の書き方』ではなく『理論の定義の一部』になっている。")
print("  → **手術に切るものが無い。**")
print("  第16回の但し書き④で『共形場理論のように、変換そのものではなく")
print("  変換に対する不変性が働く分野もある』と書いた ── これがその重力版。")

print("")
print("=== ⑨ 帳簿 ===")
ND, NG = 2693, 175
bic = 0.5 * math.log2(ND)
rows = [
    ("共形重力", 3, "α_g、γ*、γ_0（すべて全銀河共通）"),
    ("MOND", 4, "a_0 ＋ 内挿関数（第29回）"),
    ("ハロー模型", 2 * NG, "銀河ごとに 2 個"),
]
print("  銀河の回転曲線（SPARC 相当：%d 銀河、%d 点、1 個 %.2f bit）" % (NG, ND, bic))
print("  %-14s %-10s %-12s %s" % ("模型", "パラメータ", "記述長", "内訳"))
