# -*- coding: utf-8 -*-
# 第26回：第III部の総決算 ── 八つの物差しは、いくつの独立な数だったのか
import math
ln2 = math.log(2)
c = 299792458.0
hbar = 1.054571817e-34
G = 6.67430e-11
lP = math.sqrt(hbar * G / c ** 3)
tP = math.sqrt(hbar * G / c ** 5)
t0 = 4.3536e17
RH = c * t0
S = 3.1e104          # 観測されているエントロピー S/k_B（超大質量ブラックホールが支配）
p = 1.0              # 膨張指数（c・t=一定）

print("=== ① 1.5e-18 は三度出てきた。同じ数か？ ===")
A = 4 * math.pi * RH ** 2
N = math.pi * (RH / lP) ** 2 / ln2
use = (S / ln2) / N
print("  (a) 第6回・使用率      = (S/ln2)/N            = %.4e" % use)
occ = 4 * lP ** 2 * S / A
print("  (b) 第6回・占有率      = ΣA_BH/A_H = 4ℓ_P²S/A = %.4e" % occ)
dec = 0.872 - 0.745
steps = math.log(t0 / tP)
arrow = 10 ** (-dec * steps)
print("  (c) 第21回・時間の矢   = 10^(-0.127×140.24)   = %.4e" % arrow)
print("  比 (a)/(b) = %.6f" % (use / occ))
print("  → (a) と (b) は【恒等式】。ブラックホールが S を支配する限り、")
print("     使用率 = (S/ln2)/N と 占有率 = 4ℓ_P²S/A は同じ式である：")
print("       N = A/(4ℓ_P² ln2) なので (S/ln2)/N = 4ℓ_P²S/A ちょうど。")
print("  → (c) は (a) に合うように 0.127 decade/step を逆算した数。独立な確認ではない。")
print("  ★ 三度出てきた 1.5e-18 は、【一つの数】だった。新情報 0 ビット。")

print("")
print("=== ② 140 は四度出てきた。同じ数か？ ===")
print("  (a) 第20回・対数ステップ数 ln(t₀/t_P)      = %.2f" % steps)
print("  (b) 第20回・『140 手のプログラム』         = 同じ")
print("  (c) 第2回・時計 N_t                        = 同じ")
print("  (d) 第21回で 0.127 に掛けた 140.24         = 同じ")
NT = math.log(1.417e32 / 2.725)
print("  一方、温度の対数ステップ N_T = ln(T_P/T₀)  = %.2f" % NT)
print("  N_T/N_t = %.4f  → 輻射期 T∝t^(-1/2) が対数レンジの大半を占めることの反映" % (NT / steps))
print("  ★ 140 は【一つの数】。独立なのは N_T のほうだけ。")

print("")
print("=== ③ 第III部の見出し数字を、全部並べる ===")
rows = [
    ("N = 地平面の容量",            "%.3e bit" % N,                       "t0, ℓP"),
    ("dN/dt = 容量が増える速さ",    "%.3e bit/s" % (2 * N / t0),          "t0, ℓP"),
    ("Ω/N = 1ビットあたり演算数",   "%.4f" % (p * ln2 / (2 * math.pi ** 2)), "p"),
    ("使用率",                      "%.3e" % use,                          "t0, ℓP, S"),
    ("占有率",                      "%.3e" % occ,                          "= 使用率"),
    ("時間の矢",                    "%.3e" % arrow,                        "= 使用率"),
    ("冗長度 n/k",                  "%.3e" % (1 / use),                    "= 1/使用率"),
    ("対数ステップ数",              "%.2f" % steps,                        "t0, ℓP"),
    ("温度ステップ数 N_T",          "%.2f" % NT,                           "T0"),
    ("N_T/N_t",                     "%.4f" % (NT / steps),                 "T0, t0, ℓP"),
    ("通信路容量 C",                "%.3e bit/s" % (math.pi * c * RH / (lP ** 2 * ln2)), "t0, ℓP"),
    ("C·t / N",                     "%.6f" % 1.0,                          "恒等式"),
    ("(dN/dt)/C",                   "%.6f" % 2.0,                          "恒等式"),
    ("BIC 1パラメータの値段",       "%.2f bit" % (0.5 * math.log2(1701)),  "N_data"),
    ("当てはまりの損",              "%.1f bit" % (213 / (2 * ln2)),        "Δχ²"),
    ("差し引き",                    "%.1f bit" % (0.5 * math.log2(1701) - 213 / (2 * ln2)), "N_data, Δχ²"),
    ("CMB モード数",                "%.3e" % sum(2 * l + 1 for l in range(2, 2501)), "l_max"),
    ("ΛCDM の圧縮率",               "%.2e 倍" % (sum(2 * l + 1 for l in range(2, 2501)) / 6), "l_max"),
    ("1ビット ↔ 長さ",              "%.2f fm" % ((ln2 / math.pi * RH * lP ** 2) ** (1 / 3) * 1e15), "t0, ℓP"),
    ("その驚き",                    "7.4 bit",                             "主観的な事前範囲"),
    ("何もしない成分の取り分",      "95.0 %",                              "Ω_Λ, Ω_dm"),
    ("地平線問題の情報量",          "20 KB",                               "CMB パッチ数"),
    ("20KB の送信時間（再結合）",   "8.55e-96 s",                          "t_rec, ℓP"),
    ("人類の全通信 ÷ 地平面",       "1.91e-90",                            "ネット総量"),
]
print("  %-28s %-16s %s" % ("量", "値", "由来"))
for a, b, cc in rows:
    print("  %-28s %-16s %s" % (a, b, cc))

print("")
print("=== ④ 独立な入力はいくつか ===")
inputs = ["t₀（宇宙の年齢）", "ℓ_P（ħ,G,c）", "S（観測エントロピー）", "p（膨張指数）",
          "T₀（CMB 温度）", "N_data=1701", "Δχ²=213", "l_max=2500",
          "Ω_Λ+Ω_dm=0.95", "CMB パッチ数（20 KB）", "t_rec", "ネット総トラフィック"]
print("  見出し数字 %d 個 ← 独立な入力 %d 個" % (len(rows), len(inputs)))
for i, s_ in enumerate(inputs, 1):
    print("    %2d. %s" % (i, s_))
print("  → シリーズ自身の圧縮率 = %d/%d = %.1f 倍" % (len(rows), len(inputs), len(rows) / len(inputs)))
print("  ★ 第25回の物差しを自分に当てると、たった %.1f 倍。桁ではない。" % (len(rows) / len(inputs)))

print("")
print("=== ⑤ 第19回の手続きを、シリーズ自身に当てる ===")
print("  『違う物差しで同じ数が出た』の驚きをビットで測る：")
cases = [
    ("使用率 = 占有率",        "恒等式（N=A/4ℓ_P²ln2 から）",     0.0),
    ("C·t = N",                "恒等式（E=c⁴R/2G とホログラフィー）", 0.0),
    ("dN/dt = 2C",             "恒等式（N∝t²）",                  0.0),
    ("140 が四度",             "全て ln(t₀/t_P)",                 0.0),
    ("Ω/N = p ln2/2π²",        "状態方程式だけで決まる（導出）",   0.0),
    ("1ビット ↔ 1.96 fm",      "偶然（第18回で判定済み）",         7.4),
    ("N_T/N_t ≈ 1/2",          "輻射期が対数レンジを支配（説明あり）", 1.0),
]
print("  %-24s %-34s %s" % ("一致", "正体", "驚き"))
for a, b, s_ in cases:
    print("  %-24s %-34s %.1f bit" % (a, b, s_))
tot = sum(x[2] for x in cases)
print("  合計 %.1f bit（うち %.1f は第18回で『偶然』と判定済みの一件）" % (tot, 7.4))
print("  ★ 第III部で出てきた一致のほとんどは、驚き 0 ビット＝恒等式だった。")

print("")
print("=== ⑥ では第III部は何をしたのか ===")
print("  発見したのではない。【同じ数を、八つの言語で言い直した】。")
print("  それは無駄ではない ── 第25回の言葉で：")
print("    ・L(法則) を短くする作業（言語依存、判定には使えない）")
print("    ・しかし『どの二つが恒等式で結ばれているか』は、言い直さないと見えない")
print("  → 恒等式が %d 本見つかった。これは構造の地図であって、新しい物理ではない。"
      % sum(1 for x in cases if x[2] == 0.0))
