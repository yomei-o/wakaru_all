# -*- coding: utf-8 -*-
# 深掘り⑱：強い力が「距離で強くなる」のは、逆二乗則の言い換えではないのか
import math

hbarc = 0.1973269804          # GeV·fm
sigma = 0.18                  # GeV²（ストリング張力）
sig_gev_fm = sigma / hbarc    # GeV/fm
alpha_s = 0.30

print("=== ① まず、提案をそのまま式にする ===")
print("  提案： 力は『クォークからの距離 r』ではなく")
print("        『何もない所からの距離 d』で決まり、F = k/d² である。")
print("  観測： 遠方で **F = σ = 一定**（クォークからの距離に依らない）。")
print("")
print("  この二つを同時に満たすには：")
print("    k/d² = σ  →  d = √(k/σ) = **定数**")
print("  ★ **d が r に依らない定数でなければならない。**")
print("     『距離で決まる』と言いながら、その距離が動かない。")
print("  ★ → **点からの逆二乗則としては、そのままでは成り立たない。**")
print("     ただし ── **形を変えると、これは正しくなる。**")

print("")
print("=== ② 逆二乗則から一定の力は、実際に出る（面が源のとき）===")
print("  ガウスの法則：力 ∝ 流束 / 面積。**面積の増え方が全部を決める**。")
src = [
    ("点", "4πr²", "**1/r²**", "電子、太陽"),
    ("直線", "2πrL", "**1/r**", "帯電した針金"),
    ("**面**", "**一定**", "**一定**", "**帯電した平板**"),
    ("**管（一定断面）**", "**一定**", "**一定**", "**QCD の色の管**"),
]
print("  %-18s %-14s %-14s %s" % ("源の形", "面積の増え方", "力", "例"))
for a, b, c, d in src:
    print("  %-18s %-14s %-14s %s" % (a, b, c, d))
print("")
print("  ★ **帯電した無限平板の電場は、距離に依らない一定。**")
print("     クーロンの逆二乗則そのものから出る。**新しい力ではない**。")
print("  ★ つまり ── **『一定の力』は逆二乗則と矛盾しない。**")
print("     必要なのは別の原点ではなく、**別の形の源**。")

print("")
print("=== ③ 一般化 ── 力の指数は、場が広がれる次元の数 ===")
print("  D 次元に広がる場： 面積 ∝ r^(D−1)、力 ∝ 1/r^(D−1)")
for D in [3, 2, 1]:
    e = D - 1
    lab = {3: "ふつうの空間", 2: "面に閉じ込め", 1: "**線に閉じ込め**"}[D]
    f = "**一定**" if e == 0 else "1/r^%d" % e
    print("    D = %d  →  力 ∝ %-12s  %s" % (D, f, lab))
print("")
print("  ★ **閉じ込めとは、場が 1 次元にしか広がれないこと。**")
print("     力の法則が変わったのではなく、**次元が 3 から 1 に落ちた**。")
print("  ★ あなたの直感の当たっている所 ── **原因はクォークではなく、間の空間**。")

print("")
print("=== ④ その『管』は、実際に測られている ===")
r_tube = 0.35
print("  格子 QCD で色電場の横分布を測ると：")
print("    管の半径 ≈ **%.2f fm**、しかも距離を伸ばしてもほぼ一定" % r_tube)
print("    → 断面が一定 → **力が一定**。ガウスの法則そのまま。")
print("")
print("  力の大きさ： σ = %.2f GeV² = **%.2f GeV/fm**" % (sigma, sig_gev_fm))
newton = sig_gev_fm * 1.602176634e-10 / 1e-15
print("             = %.3e N = **約 %.0f トン重**" % (newton, newton / 9.80665 / 1000))
print("  ★ **15 トンの一定張力**。距離をいくら伸ばしても弱まらない。")

print("")
print("=== ⑤ そして短距離では、本当に 1/r² に戻る ===")
print("  コーネル・ポテンシャル： V(r) = **−(4/3)α_s/r** + σr")
print("                            ↑逆二乗の側    ↑一定の側")
rc = math.sqrt((4.0 / 3.0) * alpha_s / sigma) * hbarc
print("")
print("  二つの力が釣り合う距離： r_c = √((4/3)α_s/σ) = **%.3f fm**" % rc)
print("  格子で測った管の半径　： **%.2f fm**" % r_tube)
print("  ★ **一致する。**")
print("     → **管ができる距離と、逆二乗が終わる距離が同じ。**")
print("       つまり **1/r² が終わるのは、場が管に押し込められたとき**。")
print("")
reg = [
    ("r < %.2f fm" % rc, "**1/r²**", "**まだ逆二乗。ふつうの力**", "チャーモニウムの内側"),
    ("r > %.2f fm" % rc, "**一定**", "管に押し込められた", "ハドロンの大きさ"),
]
print("  %-18s %-14s %-30s %s" % ("領域", "力", "状態", "見える所"))
for a, b, c, d in reg:
    print("  %-18s %-14s %-30s %s" % (a, b, c, d))

print("")
print("=== ⑥ 押し込めているのは『何もない所』── これは当たり ===")
print("  真空が**双対超伝導体**になっている：")
print("    ふつうの超伝導体 …… 磁場を排除し、**磁束を管に絞る**（アブリコソフ渦）")
print("    QCD の真空　　 …… **色電場**を排除し、**電束を管に絞る**（双対マイスナー）")
print("  ★ **管の半径は、真空の応答（双対ロンドン長）で決まる。**")
print("     クォークの性質ではない。**間にある『何もない所』の性質**。")
print("  ★ → **『何もない所が効いている』という読みは、正しい。**")
print("       ただし効いているのは**距離としてではなく、媒質として**。")

print("")
print("=== ⑦ 一方、『絶対的な原点からの距離』は、検定できて落ちる ===")
tests = [
    ("場所に依るか", "地球上と遠方クェーサーで同じ", "**依らない**"),
    ("向きに依るか", "格子の軸方向と対角方向で V(r) 一致", "**依らない（< 1 %）**"),
    ("系に依るか", "cc̄、bb̄、軽いクォークで同じ σ", "**依らない**"),
]
print("  %-20s %-38s %s" % ("もし原点があれば", "実際の測定", "結果"))
for a, b, c in tests:
    print("  %-20s %-38s %s" % (a, b, c))
print("")
sigs = [("レッジェ軌道の傾き α' = 0.9 GeV⁻²", 1 / (2 * math.pi * 0.9)),
        ("チャーモニウム／ボトモニウムの準位", 0.19),
        ("格子 QCD（√σ = 440 MeV）", 0.440 ** 2)]
print("  σ を三通りの無関係な方法で測る：")
for a, v in sigs:
    print("    %-40s σ = **%.3f GeV²**" % (a, v))
sp = max(v for _, v in sigs) / min(v for _, v in sigs)
print("  ★ **ばらつき %.0f %% 以内で一致。** ペランの 13 通りと同じ形。" % ((sp - 1) * 100))
print("     → **σ は本物の一つの量**。原点の位置に依る量ではない。")

print("")
print("=== ⑧ しかも、一定の力は永遠には続かない ===")
r_break = 1.25
e_break = sig_gev_fm * r_break
print("  伸ばし続けると、管の中のエネルギーが対生成の閾値を超える：")
print("    r = %.2f fm で E = %.2f × %.2f = **%.2f GeV**" %
      (r_break, sig_gev_fm, r_break, e_break))
print("    ≈ 2 × %.2f GeV（軽い中間子 2 個分）→ **紐が切れる**" % (e_break / 2))
print("  ★ 格子 QCD で実際に **r ≈ 1.2〜1.4 fm で切れる**のが見えている。")
print("  ★ → **『離れるほど強くなる』は、1.2 fm までの話**。")
print("       その先は力が **ゼロ**になる（中間子 2 個に分かれて、もう無関係）。")

print("")
print("=== ⑨ 紐であることの証拠 ── 予言された小さなずれ ===")
r1 = 1.0 / hbarc
luscher = -math.pi / (12 * r1)
lin = sigma * r1
print("  紐が量子的に揺れると、ポテンシャルに補正が出る（リュッシャー項）：")
print("    V(r) = σr **− π/(12r)** + 定数")
print("  r = 1 fm で： σr = %.3f GeV、補正 = %.4f GeV（**%.1f %%**）" %
      (lin, luscher, abs(luscher) / lin * 100))
print("  ★ この **−π/12r** は係数に自由度が無い ── **紐なら必ずこの値**。")
print("     格子 QCD で確認済み。**管の描像そのものが検定に通っている**。")

print("")
print("=== ⑩ 判定 ===")
v = [
    ("『別の点からの距離の逆二乗』", "**外れ**", "その距離が定数になってしまう"),
    ("『逆二乗則のままで一定の力が出る』", "**当たり**", "源が面／管なら出る"),
    ("『クォークではなく間の空間が効いている』", "**当たり**", "真空の双対マイスナー効果"),
    ("『短距離では普通の 1/r² 』", "**当たり**", "r < %.2f fm では実際そう" % rc),
    ("『絶対的な原点がある』", "**外れ**", "場所・向き・系に依らない"),
]
print("  %-38s %-12s %s" % ("読み", "判定", "根拠"))
for a, b, c in v:
    print("  %-38s %-12s %s" % (a, b, c))
print("")
print("  ★ **まとめ：力の法則は変わっていない。変わったのは次元。**")
print("     3 次元に広がれば 1/r²、1 次元に押し込まれれば一定。")
print("     押し込んでいるのは、クォークではなく **間にある真空**。")
print("  ★ **『何もない所が決めている』という直感は当たっていて、**")
print("    **『距離として効く』という部分だけが外れていた。**")

print("")
print("=== ⑪ 正直な線 ===")
print("  ・④の管の半径 0.35 fm は測り方（どの演算子で見るか）に依る。0.3〜0.5 fm の幅。")
print("  ・⑤の r_c ≈ %.2f fm は α_s = %.1f を固定した値。α_s は走るので、" % (rc, alpha_s))
print("    **一致は桁の一致であって、精密な一致ではない**。")
