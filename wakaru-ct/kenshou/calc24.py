# 第20回：光シートを、本当に縛ってみる
import math
c=299792458.0; hbar=1.054571817e-34; G=6.67430e-11; kB=1.380649e-23
lP=math.sqrt(hbar*G/c**3); tP=lP/c
t0=4.3536e17; t_eq=1.6e12; yr=3.1557e7

print("=== 使用率 f = s / (3H/4ℓ_P²) の時間変化 ===")
print("  s ∝ a^-3、H ∝ 1/t なので  f ∝ t^(1-3p)")
print("  プランク期に f≈1 とおいて、標準の熱史で今日まで積む：")
f=1.0
for name,ta,tb,p in [("放射期 (p=1/2)",tP,t_eq,0.5),("物質期 (p=2/3)",t_eq,t0,2/3.)]:
    e=1-3*p; fac=(tb/ta)**e; f*=fac
    print(f"    {name:16s} 指数 {e:+.3f}  倍率 {fac:.3e}  → f = {f:.3e}")
print(f"  今日の f = {f:.2e}   → 余裕 {-math.log10(f):.1f} 桁")

print("\n=== なぜプランク期にちょうど飽和するのか ===")
print("  T ~ M_Pl のとき s ~ T³ ~ 1/ℓ_P³、H ~ 1/t_P ~ c/ℓ_P")
print("  f = s /(3H/4ℓ_P²) ~ (1/ℓ_P³)/((1/ℓ_P)/ℓ_P²) = 1")
print("  → 次元解析だけから O(1)。第19回の分類でいう【恒等式】＝驚き 0 ビット。")

print("\n=== 各時代の余裕 ===")
def f_at(t):
    # プランク期 f=1 から、放射→物質で積む
    if t<=t_eq: return (t/tP)**(-0.5)
    return (t_eq/tP)**(-0.5)*(t/t_eq)**(-1.0)
for n,t in [("プランク期",tP),("電弱期 1e-11 s",1e-11),("元素合成 1 s",1.0),
            ("再結合 38万年",1.2e13),("今日",t0)]:
    v=f_at(t)
    print(f"  {n:16s} t={t:9.3e} s   f={v:9.3e}   余裕 {-math.log10(v):5.1f} 桁")

print("\n=== 膨張則ごとに、いつ境界を破るか ===")
print("  f ∝ t^(1-3p)。今日の f を固定して遡ると、f=1 になる時刻は")
f0=f
for p,name in [(1/3.,"stiff w=1"),(0.5,"放射"),(2/3.,"物質"),(1.0,"c·t=一定")]:
    e=1-3*p
    if abs(e)<1e-12:
        print(f"  p={p:.3f} ({name:10s}): 指数 0 → f は一定。飽和させ続けられる唯一の膨張則")
        continue
    tv=t0*f0**(1/(-e))
    print(f"  p={p:.3f} ({name:10s}): 指数 {e:+.3f} → f=1 になるのは t = {tv:.3e} s"
          + ("  ← プランク時刻より前（破らない）" if tv<tP else "  ← 破る"))

print("\n=== 制約としての強さを、第19回の道具で測る ===")
print(f"  今日の余裕 {-math.log10(f0):.0f} 桁。境界が排除する a(t) は、")
print("  『プランク期より前で f>1 になるもの』だけ ── 実質すべての標準的な膨張則が通る。")
print("  → 制約としての情報量はほぼゼロ。予言を出す力はない。")
print("  効くのは f~1 の領域、すなわちプランク期だけ。そしてそこで飽和するのは恒等式。")

print("\n=== 恒等的に飽和させると（番外編③の再確認）===")
print("  s = 3H/4ℓ_P² を恒等的に課す → σ/a³ = 3ȧ/(4Ga) → a²ȧ=一定 → a ∝ t^(1/3)")
print("  すなわち w=1（stiff／キネーション）。実際の宇宙ではない。")
