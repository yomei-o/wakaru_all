print("     第25回の言葉：L(残差) はハッブル図だけで決まらない。")

print("")
print("=== ⑥ 混同が起きる理由と、その解き方 ===")
print("  混同の元：どちらも『a ∝ t』『膨張が減速も加速もしない』と言われる。")
print("  解き方：**k を見る**。")
print("    k = −1（＋空）→ ミルン → Riemann = 0 → 座標変換で済む → 物理の中身ゼロ")
print("    k =  0（＋物質）→ R_h=ct → Riemann ≠ 0 → 共形変換が要る → 質量が動く")
print("  ★ 第3回で『c·t=一定 は座標変換ではなく共形変換』と書いたことの、")
print("     いちばん具体的な意味がこれ。")

print("")
print("=== ⑦ このシリーズの位置づけ ===")
