# 第9回：原子に入れてみる ── アインシュタイン1918の論法が効かない理由
import math
hbar_eV=6.582119569e-16   # eV s
t0=4.3536e17; yr=3.1557e7; t_rec=1.2e13
H0=1/t0
print("=== 断熱パラメータ  ħH/ΔE ===")
print("  ハミルトニアンの変化率 ṁ/m = 1/t = H。準位間隔 ΔE/ħ と比べる。")
print(f"  ħH₀ = {hbar_eV*H0:.4e} eV\n")
tr=[("水素 リュードベリ",13.6),("Lyman-α",10.2),("可視光 2 eV",2.0),
    ("21cm 超微細",5.874e-6),("セシウム時計 9.19 GHz",3.80e-5),("CMB 光子 k_BT₀",2.349e-4)]
print(f"  {'遷移':24s} {'ΔE [eV]':>12} {'ħH₀/ΔE':>12}   {'断熱が破れる時刻 t=ħ/ΔE'}")
for n,E in tr:
    print(f"  {n:24s} {E:12.4g} {hbar_eV*H0/E:12.3e}   t = {hbar_eV/E:.3e} s")
print(f"\n  原子ができるのは再結合（t ≈ {t_rec:.1e} s = 38万年）以降")
print("  → どの遷移も、断熱が破れる時刻は原子ができるはるか前。")
print("     原子が存在する全時代にわたって、完全に断熱。")

print("\n=== では、線幅はどれだけ『ぼける』か ===")
A=6.265e8          # Lyman-α の自然放出係数 [1/s]
nu=2.4661e15       # Hz
dnu_nat=A/(2*math.pi)
print(f"  Lyman-α：ν={nu:.4e} Hz、自然幅 Δν=A/2π={dnu_nat:.3e} Hz  → Δν/ν={dnu_nat/nu:.3e}")
drift=H0/A         # 放射が起きている間（1/A）に振動数が変わる割合
print(f"  この絵での『放射中のずれ』 = (ν̇/ν)·(1/A) = H₀/A = {drift:.3e}")
print(f"  → 自然幅の {drift/(dnu_nat/nu):.2e} 倍。つまり {abs(math.log10(drift/(dnu_nat/nu))):.0f} 桁下。")
print("     スペクトル線は、まったくぼけない。")

print("\n=== 原子時計の制約は、厳密にゼロで満たされる ===")
for n,v in [("α（微細構造定数）","1.0(1.1)e-18 /年 (Lange 2021)"),
            ("μ=m_p/m_e","分子時計で ~1e-17 /年"),
            ("m_e/M_Pl 等の比","すべて無次元")]:
    print(f"    {n:22s} 実測上限 {v}")
print("    この絵での予言：どれも厳密に 0（分子と分母が同じウェイトだから）")

print("\n=== ボーア半径は縮むのに、なぜ測れないのか ===")
print(f"  ȧ_B/a_B = -H₀ = {-H0*yr:.3e} /年")
print("  比べる相手を探すと：別の原子（同じだけ縮む）、光の波長（+1 なので同じだけ縮む）、")
print("  定規（原子でできている）── 全部が同じウェイト +1。")
print("  → 比較相手が存在しない。第3回の『名前の中に比較相手が隠れている』の、原子版。")

print("\n=== ワイル1918が殺された論法との違い ===")
print("  ワイル：長さ接続が非可積分 → 経路依存 → 履歴で時計がずれる（第二時計効果）")
print("  現代 ：Ω(x) は一価関数 → 可積分 → 経路依存性が最初から無い")
print("  さらに：仮に時間変化しても、断熱パラメータ 1e-34 で遷移は誘起されない")
print("  → 二重に守られている。")
