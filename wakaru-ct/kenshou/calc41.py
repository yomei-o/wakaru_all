# -*- coding: utf-8 -*-
# 第37回：量子アノマリー ── 「光には何も起きていない」は古典の話だった
import math

ainv0 = 137.035999177        # CODATA 2022
da_rel = 1.6e-10             # α の相対精度（第30回③と同じ値）
ainvZ = 127.951              # α(M_Z) MS-bar（PDG）
me = 0.51099895e-3           # GeV
MZ = 91.1876                 # GeV

print("=== ① 第11回で数えたのは、古典の話だった ===")
print("  第11回：マクスウェル作用は D=4 でちょうど共形不変 ── 『光には何も起きていない』")
print("  第34回：その作用は Weyl 変換で S → Ω^(D−4) S。**指数がゼロになるのは D=4 だけ**。")
print("")
print("  ところが量子にすると、D=4 に留まれない。")
print("    ・次元正則化：D = 4 − ε で計算する（ε→0 は最後）")
print("    ・格子・切断：細かさの基準 μ を持ち込む")
print("  → どちらでも **Ω^(D−4) = Ω^(−ε) ≠ 1**。第34回で見た指数が、そのまま破れになる。")
print("")
print("  次元を数える：D 次元では [e²] = 質量^(4−D) = 質量^ε")
print("    → **α は D=4 でだけ無次元**。ε≠0 では次元を持ってしまうので、")
print("       第35回と同じ手当てが要る ── **スケールと組ませて無次元にする**：α(μ)")
print("  ★ 第16回のウェイトの地図で『0 の列』にいた α が、量子にすると μ を持つ。")

print("")
print("=== ② どれくらい動くのか（1 ループ QED）===")
print("  1/α(μ) = 1/α(0) − (2/3π) Σ_f N_c Q_f² ln(μ/m_f)")
lnr = math.log(MZ / me)
d1 = (2 / (3 * math.pi)) * lnr
print("  電子ループだけ： ln(M_Z/m_e) = %.2f、Δ(1/α) = %.3f" % (lnr, d1))
print("    → 1/α(M_Z) ≈ %.2f" % (ainv0 - d1))
print("  実測（PDG, MS-bar）： 1/α(M_Z) = %.3f" % ainvZ)
print("  ★ 電子だけで %.0f パーセントぶん、全部の荷電フェルミオンで残りが埋まる。" %
      (100 * d1 / (ainv0 - ainvZ)))
print("  ※ 全部を m_e から走らせる粗い近似なら 1/α(M_Z) = %.2f となり、行き過ぎる。"
      % (ainv0 - (2/(3*math.pi))*(20/3)*lnr))
print("     実際は各粒子が自分の質量から走り始める。")
print("  ※ 残りのうちハドロンの寄与は摂動では計算できず、e⁺e⁻→ハドロンの")
print("     実測データから入れる ── **ここは理論ではなく測定値**。")

ratio = ainv0 / ainvZ
print("")
print("  α(M_Z)/α(0) = %.4f  → **%.1f パーセント大きい**" % (ratio, 100 * (ratio - 1)))

print("")
print("=== ③ 『実効ウェイト』を測る ===")
for lab, s in [("電子 1 種のみ", 1.0), ("荷電レプトン 3 種", 3.0), ("標準模型の全荷電フェルミオン", 20.0 / 3)]:
    w = 2 * (1 / ainv0) * s / (3 * math.pi)
    print("  %-28s d ln α / d ln μ = %.2e" % (lab, w))
print("  → 古典のウェイトは 0。量子では 10⁻³ 台の『実効ウェイト』が付く。")
print("  1 e-fold あたりは小さいが、%.1f e-fold ぶん積むと %.1f パーセントになる。" %
      (lnr, 100 * (ratio - 1)))
print("  ★ **ウェイトの地図の 0 の列に、量子が小さな数字を書き込んだ。**")

print("")
print("=== ④ 破れを、ビットで測る ===")
bit_prec = -math.log2(da_rel)
bit_run = math.log2((ratio - 1) / da_rel)
print("  実験室での α の精度 1.6e-10 → %.1f ビット（第30回③と同じ）" % bit_prec)
print("  m_e → M_Z の走り %.4f を、その精度を単位に測る：" % (ratio - 1))
print("    %.3e / %.1e = %.2e  → **%.1f ビット**" % (ratio - 1, da_rel, (ratio - 1) / da_rel, bit_run))
print("")
print("  第19回の目盛りに置くと：")
for lab, b in [("恒等式（第24回の C・t = N）", 0.0),
               ("偶然の帯（第36回）", 5.6),
               ("小出の関係式", 15.7),
               ("**QED の共形対称性の破れ**", bit_run),
               ("CMB の一様性（第17回）", 1.6e5)]:
    print("    %-34s %10s bit" % (lab, ("%.1f" % b) if b < 1e3 else "1.6e5"))
print("  ※ 雑音の床の取り方に依存する：床を α(M_Z) の精度 1e-4 に取れば %.1f ビット。"
      % math.log2((ratio-1)/1e-4))
print("     数字そのものより、『偶然の帯のはるか上』という位置づけが要点。")
print("  ★ 破れは雑音の上 %.0f ビット ── **偶然ではありえない、測定された効果**。" % bit_run)

print("")
print("=== ⑤ 第30回と矛盾しないのか ===")
print("  第30回：α は**宇宙時間**について 26 ビットで一定（オクロ・原子時計）")
print("  今回　：α は**エネルギースケール**について %.1f ビットぶん動く" % bit_run)
print("  → 矛盾しない。**別の問いだから**。")
print("     ・第30回の『一定』は  ∂α/∂t = 0 （同じ μ で、時代を変える）")
print("     ・今回の『動く』は    ∂α/∂μ ≠ 0（同じ時代で、μ を変える）")
print("  ★ 『α は一定』は、**何について一定かを言わないと文になっていない**。")
print("     ── 第3回の判定手続きが、そのまま効いている。")

print("")
print("=== ⑥ 破れの大きさは、自由度の数を数えている ===")
print("  曲がった時空でのトレースアノマリー：")
print("    ⟨T^μ_μ⟩ = (1/16π²)( c·C² − a·E₄ )     C²=ワイル², E₄=ガウス・ボネ")
print("  係数は場の中身だけで決まる（規格化は文献で異なる。ここでは")
print("    a = (N₀ + 11 N_{1/2} + 62 N₁)/360、 c = (N₀ + 6 N_{1/2} + 12 N₁)/120 を採る）")
contents = [
    ("実スカラー 1 個", 1, 0, 0),
    ("ワイル フェルミオン 1 個", 0, 1, 0),
    ("ベクトル場 1 個（光子）", 0, 0, 1),
    ("標準模型（N₀=4, N_{1/2}=45, N₁=12）", 4, 45, 12),
]
print("  %-36s %-10s %-10s %s" % ("場の中身", "a", "c", "c/a"))
for lab, n0, nh, n1 in contents:
    a = (n0 + 11 * nh + 62 * n1) / 360.0
    c = (n0 + 6 * nh + 12 * n1) / 120.0
    print("  %-36s %-10.4f %-10.4f %.3f" % (lab, a, c, c / a))
print("")
print("  ★ **アノマリーの係数は、場を数えているだけ**。")
print("     破れの大きさ ＝ 自由度の個数。第24回で情報を数えたのと同じ通貨。")
print("  そして a 定理（Komargodski–Schwimmer 2011, 4 次元）：")
print("    RG の流れに沿って **a は減る一方**（a_UV > a_IR）")
print("  → 『粗くしていくと自由度は減る』が定理として証明されている。")
print("     第4回で『粗視化は不可逆』と書いたことの、場の理論での対応物。")

