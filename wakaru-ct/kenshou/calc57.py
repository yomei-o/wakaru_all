# -*- coding: utf-8 -*-
# 深掘り②：次元転移は圧縮器である ── 階層は自分の対数まで縮む
import math

ln2 = math.log(2)
bic = 0.5 * math.log2(1701)      # 第5回：パラメータ 1 個の値段

MP = 1.220890e19     # GeV（プランク質量）
v = 246.22           # GeV（ヒッグス真空期待値）
LQ = 0.332           # GeV（Λ_QCD、MS-bar、n_f=3）

print("=== ① 次元転移とは、指数写像である ===")
print("  Λ = M · exp( −2π / (b₀ α(M)) )")
print("  → ln(M/Λ) = 2π / (b₀ α(M)) ≡ H   （H は『階層』をネイパー単位で測ったもの）")
print("  → d lnΛ / d lnα = **+H**   ── 利得はちょうど階層の大きさ。")
print("  ★ **α の 1 ビットが、Λ の H ビットになる。** 階層が大きいほど利得も大きい。")

print("")
print("=== ② だから、階層の値段は『階層の対数』になる ===")
print("  階層を B ビットとする（B = H/ln2）。")
print("  Λ を 2 倍以内に決めたいなら δ(lnΛ) = ln2、つまり δα/α = ln2/H = **1/B**。")
print("  → α に必要な精度のビット数 = log₂(1/(δα/α)) = **log₂ B**")
print("")
print("  ★ **B ビットの階層は、指数写像を通せば log₂B ビットで買える。**")
print("     圧縮率 B / log₂B ── これは厳密な結果で、近似も規約も入っていない。")

print("")
print("=== ③ 実際の階層に当てる ===")
hier = [
    ("Λ_QCD / M_Planck", MP / LQ, "**指数写像あり**（QCD の走り）"),
    ("v / M_Planck（階層性問題）", MP / v, "指数写像なし"),
    ("Λ_QCD / v", v / LQ, "**指数写像あり**"),
    ("ρ_Λ / ρ_Planck（宇宙定数問題）", 1.0 / 1.13e-123, "指数写像なし"),
]
print("  %-34s %-12s %-12s %-12s %s" % ("階層", "生の B", "log₂B", "圧縮率", "指数写像"))
for lab, r, note in hier:
    B = math.log2(r)
    print("  %-34s %-12.1f %-12.2f %-12.1f %s" % (lab, B, math.log2(B), B / math.log2(B), note))
print("")
print("  ★ **408 ビットの宇宙定数問題ですら、指数写像があれば 8.7 ビットで済む。**")
print("     圧縮率 47 倍 ── だから誰もが指数関数的な機構を探しにいく。")

print("")
print("=== ④ 核心 ── 微調整が『問題』かどうかの判定基準 ===")
print("  第48回で一つ目の基準を作った：**事前分布に理由があるか**。")
print("  今回、二つ目が出た：**指数写像が使えるか**。")
tri = [
    ("強い CP（θ_QCD）", "**ある**（角度）", "**ない**", "35.9", "本物の問題（二重に）"),
    ("Λ_QCD / v", "ない", "**ある**", "9.5 → 3.2", "問題ではない（実際、誰も問題視しない）"),
    ("v / M_Planck", "ない", "ない", "55.5", "論争中（実際、論争中）"),
    ("ρ_Λ / ρ_Planck", "ない", "ない", "408.4", "論争中（実際、論争中）"),
]
print("  %-24s %-16s %-14s %-14s %s" % ("微調整", "事前に理由", "指数写像", "値段[bit]", "判定と、実際の扱われ方"))
for a, b, c, d, e in tri:
    print("  %-24s %-16s %-14s %-14s %s" % (a, b, c, d, e))
print("")
print("  ★ **二つの基準だけで、物理学者が実際にどれを問題視しているかが再現される。**")
print("     ── 判定を作ってから見に行ったら、社会の側がすでに同じ線を引いていた。")
print("        第47回で SI が第3回の線を引いていたのと、同じ形。")

print("")
print("=== ⑤ 階層性問題を指数写像で解くには、どんな結合が要るか ===")
H_hier = math.log(MP / v)
print("  ln(M_P/v) = %.3f ネイパー = %.1f ビット" % (H_hier, H_hier / ln2))
print("  これを次元転移で作るなら 2π/(b₀ α) = %.3f が要る：" % H_hier)
for b0, lab in [(7.667, "n_f=5 相当"), (9.0, "n_f=3 相当"), (11.0, "物質なし")]:
    a_req = 2 * math.pi / (b0 * H_hier)
    print("    b₀ = %-6.3f（%-10s） → α(M_P) = **%.4f = 1/%.1f**" % (b0, lab, a_req, 1 / a_req))
# 参考：α_s を M_P まで走らせるといくつか
als_mz, b0_6 = 0.1180, 7.0
inv = 1 / als_mz + (b0_6 / (2 * math.pi)) * math.log(MP / 91.1876)
print("  参考：α_s(M_Z)=0.118 を 1 ループで M_P まで走らせると α_s(M_P) = %.4f = 1/%.1f" %
      (1 / inv, inv))
print("  ★ 必要な値とほぼ同じ ── ただしこれは**偶然ではなく、ほぼ恒等式**：")
print("     ln(v/Λ_QCD) = %.2f は ln(M_P/v) = %.2f に比べて小さいので、" %
      (math.log(v / LQ), H_hier))
print("     必要な α の差は %.0f パーセントにしかならない。第19回の分類では **0 ビット**。" %
      (100 * math.log(v / LQ) / H_hier))
print("     （見つけた一致を、その場で殺しておく ── 第47回⑥と同じ作法）")

print("")
print("=== ⑥ 第32回のコスモンを、この物差しに当てる ===")
B_cc = math.log2(1.0 / 1.13e-123)
floor = math.log2(B_cc)
cosmon_pay = 2 * bic
print("  宇宙定数問題 B = %.1f ビット" % B_cc)
print("  指数機構が払うべき理論下限 = log₂B = **%.2f ビット**" % floor)
print("  第32回のコスモンが実際に払った値段 = パラメータ 2 個 = **%.2f ビット**" % cosmon_pay)
print("  → 超過はわずか **%.2f ビット**（%.0f パーセント）" %
      (cosmon_pay - floor, 100 * (cosmon_pay - floor) / floor))
print("  ★ **コスモンは、指数機構の情報理論的な下限から 2 ビットしか離れていない。**")
print("     第32回では『10.7 払って最大 408 買う』と書いたが、")
print("     いま分かるのは **10.7 という値段自体が、ほぼ最小だった**ということ。")
print("  ※ ただしこれは『コスモンが正しい』という意味ではない ──")
print("     **指数機構であるかぎり、これ以上安くはならない**という下限の話。")

print("")
print("=== ⑦ 下限をパラメータの個数に直すと、基準が検証される ===")
print("  下限 log₂B を、第5回の値段（%.2f ビット / パラメータ 1 個）で割る。" % bic)
pred = [
    ("強い CP", 35.9, "アクシオン（PQ 機構）", "**新しいスケール f_a が 1 個**"),
    ("階層性", 55.5, "次元転移による生成", "スケール 1 個"),
    ("宇宙定数", B_cc, "コスモン（第32回）", "**指数ポテンシャルは 2 個**"),
]
print("  %-14s %-12s %-12s %-14s %-24s %s" %
      ("問題", "B[bit]", "下限[bit]", "＝ 何個ぶん", "実際に提案されている機構", "実際の個数"))
for lab, B, mech, n in pred:
    f = math.log2(B)
    print("  %-14s %-12.1f %-12.2f %-14.2f %-24s %s" % (lab, B, f, f / bic, mech, n))
print("")
print("  ★ **下限が予測する個数と、実際に提案されている機構の個数が一致する。**")
print("     ・強い CP は下限 0.96 個 → **1 個で足りる** → アクシオンは 1 個。合う。")
print("     ・宇宙定数は下限 1.61 個 → **2 個要る** → コスモンは 2 個。合う。")
print("  ★ そして log₂B なので、**階層がどれだけ大きくても下限は 1〜2 個で頭打ち**。")
print("     408 ビットも 55 ビットも 36 ビットも、要るのは 1〜2 個 ──")
print("     **指数写像があるなら、階層の大きさはほとんど値段に効かない。**")
print("  ※ 逆に、指数写像が無ければ B ビットをそのまま払う。")
print("     408 ビットは第5回の値段で **%.0f 個ぶん** ── だから解けていない。" % (B_cc / bic))

print("")
print("=== ⑧ 正直な線 ── どこが強くて、どこが弱いか ===")
print("  **強い（厳密）**：")
print("    ・d lnΛ/d lnα = H  ── 1 ループの次元転移から直接。近似も規約も無い。")
print("    ・B ビットの階層を 1 ビット以内に決めるのに要る α の精度は log₂B ビット。")
print("      → **記述長として、階層は自分の対数まで縮む**。これは MDL の言明そのもの。")
print("  **中くらい**：")
print("    ・④の判定表。『指数写像があるか』は模型を見れば分かるので客観的だが、")
print("      『実際の扱われ方』の欄は文献の空気を要約したもの。")
print("  **弱い（ここが本稿のいちばん弱いところ）**：")
print("    ・⑥⑦で log₂B を第5回の 5.37 ビット/個 で割ってパラメータ数に直した部分。")
print("      5.37 は N=1701 という特定のデータ点数から出た**パラメータの値段**で、")
print("      **記述長の精度ビットと同じ通貨だという保証は無い**（第48回②と同じ弱点）。")
print("    ・⑦の一致（0.96→アクシオン 1 個、1.61→コスモン 2 個）は 2 例だけ。")
print("      第36回②の但し書きと同じ ── **目に付いたパターンの記録であって、結果ではない**。")
print("")
print("=== ⑨ まとめ ===")
print("  ・次元転移は圧縮器で、利得はちょうど階層の大きさ H（厳密）。")
print("  ・**B ビットの階層は、記述長 log₂B ビットまで縮む**（厳密）。")
print("  ・だから微調整が『問題』かどうかは、第48回の『事前に理由があるか』に加えて、")
print("    **『指数写像が使えるか』**で判定できる ── そして実際の扱われ方を再現する。")
print("  ・第32回のコスモンは、指数機構の下限から 2 ビットしか離れていなかった。")
print("  ・階層がどれだけ大きくても、指数写像があれば下限は 1〜2 個ぶんで頭打ち。")
print("    **408 ビットも 55 ビットも、値段はほとんど変わらない。**")
