# 第32回：ヴェッテリヒのコスモン ── 記法が理論になると、何が増えるのか
import math

ln2 = math.log(2)
bic = 0.5 * math.log2(1701)

print("=== ① 第4回の絵と、コスモンの違い ===")
print("  第4回：消せるものを全部消すと、動くのは質量ひとつ ── m̃(t) = a(t)·m")
print("    ただし a(t) は**手で置いた関数**。何も決めていないので、予言もゼロ。")
print("  コスモン：質量を決めるのはスカラー場 χ で、m ∝ χ。")
print("    χ の動きは場の方程式（ポテンシャル V(χ)）が決める。")
print("  ★ 同じ絵でも、m(t) が『選ばれる』のか『決まる』のかで、まったく別物になる。")

print("")
print("=== ② パラメータの値段（第5回の天秤）===")
print("  第4回の絵          パラメータ 0 個 → 記述長の変化 0、予言 0")
V = [("指数型ポテンシャル V = M⁴ exp(−αχ/M)", 2)]
for n, k in V:
    print("  %-38s パラメータ %d 個 → %.1f bit" % (n, k, k * bic))
print("  （パラメータ 1 個の値段 = ½log2(1701) = %.2f bit、第5回）" % bic)

print("")
print("=== ③ 何を買うのか ── 宇宙定数のチューニング ===")
rhoL = 1.13e-123          # ρ_Λ / M_Pl^4（第12回）
tune = -math.log2(rhoL)
print("  第12回：ρ_Λ/M_Pl⁴ = %.2e" % rhoL)
print("  これを『手で合わせる』としたら、何ビット設定することになるか：")
print("    −log2(%.2e) = %.1f bit" % (rhoL, tune))
print("  クインテッセンスの主張：この値は**アトラクタ（引き込み解）**で自動的に出る。")
print("  → 払う %.1f bit で、最大 %.0f bit を買い戻す勘定になる。" % (2 * bic, tune))
print("  ※ ただし完全には買い戻せない（下の⑦を見ること）。")

print("")
print("=== ④ なぜ第28回の VSL のように死なないのか ===")
print("  コスモンは**すべての質量を同じ χ で決める**ので、質量比が固定される。")
ratios = [
    ("m_p/m_e", 1.4e-7, "分子時計 ~1e-17/yr を 138 億年ぶん外挿"),
    ("α", 1.4e-8, "原子時計（第30回）"),
    ("m_n/m_p", 1e-2, "元素合成"),
]
print("  %-14s %-12s %-10s %s" % ("無次元比", "観測上限", "縛ったビット", "出どころ"))
for n, b, note in ratios:
    print("  %-14s %-12.1e %-10.1f %s" % (n, b, -math.log2(b), note))
print("  コスモンの予言：これらは**すべて厳密に不変**（比だから）")
print("  VSL の予言（第28回）：α が動く → 26 ビットの制約に正面衝突")
print("  ★ 同じ『定数が変わる』でも、比が守られるかどうかで生死が分かれる。")
print("     第3回・第9回で見た『比較相手を揃えれば安全』が、理論の設計原理になっている。")

print("")
print("=== ⑤ では、コスモンは何で判定されるのか ===")
print("  比が守られるので、定数の測定では区別できない。判定は**暗黒エネルギーの状態方程式**へ。")
w0, we = -1.03, 0.03
print("  観測：w = %.2f ± %.2f（Planck + SNe + BAO）" % (w0, we))
prior = 2.0               # w の事前範囲 [-2, 0]
bits_w = -math.log2(2 * we / prior)
print("  事前範囲を w ∈ [−2,0] と取ると、縛られたビット数 = %.1f bit" % bits_w)
print("  → 宇宙定数（w = −1 ちょうど）と、動くクインテッセンス（w ≠ −1）の差はここに出る。")
print("  ※ DESI (2024) は w が時間変化する模型を選好する兆候を報告 ── 現在進行形。")

print("")
print("=== ⑥ 特異点は消えるのか ===")
print("  第4回の表：曲率 R は共形変換で消える（R̃ = 0、a ∝ t のとき）")
print("  ヴェッテリヒの主張：質量が育つ絵では、過去は χ → 0 の**有限の側**にあり、")
print("    曲率不変量が発散しない ── 『宇宙に始まりは無い』")
print("  ところが第6回で見たとおり、**無次元比を作ると謎は戻ってくる**。")
print("  ここで戻ってくるのは：")
print("    ・光（質量ゼロ）の測地線は共形変換で（再パラメータ化を除いて）保たれる → 延長できる")
print("    ・質量を持つ粒子の世界線は保たれない → こちらが本体")
print("  → コスモンの絵では過去で質量も 0 になるので、massive も massless に近づく。")
print("     **『特異点が消えた』かどうかは、この極限をどう扱うかに依存する** ── 論争中。")

print("")
print("=== ⑦ 正直な帳簿 ===")
print("  買い戻せる分：")
print("    ・ρ_Λ の大きさ（アトラクタで説明できれば最大 %.0f bit）" % tune)
print("  買い戻せない分：")
print("    ・ポテンシャルのスケール M は依然として置く必要がある")
print("    ・『なぜ今』問題（第12回）は残る ── アトラクタでも今日の一致は説明しない")
print("    ・χ と物質の結合の強さは新しい自由度")
print("  → 実際に買い戻せるのは %.0f bit のうち一部。**桁は縮むが、ゼロにはならない。**" % tune)

print("")
print("=== ⑧ 手術：名前と中身 ===")
print("  論文の題は『膨張しない宇宙』── これは (A) 座標の選び方＝記法の側の言い方。")
print("  中身は (B) 動的なスカラー場とそのポテンシャル ── 観測にかかる主張。")
print("  ★ ただしヴェッテリヒ自身が**二つの絵は Weyl 変換で等価だと明示している**。")
print("     第28回の VSL（名前を残したまま (B) を主張）とは違い、手術は論文の中で済んでいる。")
print("  → 第31回の CCC と同じ型：記法だと知ったうえで道具として使い、主張は (B) に置く。")

print("")
print("=== ⑨ 記法が理論になると、何が増えるのか ===")
inc = [
    ("パラメータ", "0 個 → 2 個", "%.1f bit 払う" % (2 * bic)),
    ("予言", "0 個 → w(z)", "%.1f bit ぶんの土俵に乗る" % bits_w),
    ("説明", "無し → ρ_Λ の大きさ", "最大 %.0f bit 買い戻す" % tune),
    ("反証可能性", "無し → 有り", "w = −1 からのずれで判定できる"),
]
print("  %-14s %-22s %s" % ("増えるもの", "変化", "帳簿での意味"))
for a, b, c in inc:
    print("  %-14s %-22s %s" % (a, b, c))
print("  ★ 第25回の言葉で言えば ── 記法は L(法則) を短くするだけで、")
print("     理論は L(パラメータ) を払って L(残差) を減らしにいく。**土俵が違う**。")
