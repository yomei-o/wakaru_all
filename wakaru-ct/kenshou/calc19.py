# 第14回：相転移に入れてみる ── ウェイト表そのものが、実験で測られている
d_list=[2,3,4]
# 既知の Δ_σ（スピン演算子のスケーリング次元）
DS={2:0.125, 3:0.5181489, 4:1.0}
ETA={2:0.25, 3:0.0362978, 4:0.0}
print("=== 古典のウェイトと、実際のウェイト ===")
print(f"  {'次元 d':>6} {'自由場 (d-2)/2':>14} {'実際の Δ_σ':>14} {'異常次元 γ_σ':>14} {'η=2γ':>10}")
for d in d_list:
    free=(d-2)/2
    print(f"  {d:6d} {free:14.7f} {DS[d]:14.7f} {DS[d]-free:14.7f} {ETA[d]:10.7f}")
print("\n  → 4次元では古典のウェイト表が厳密に正しい（γ=0）")
print("    次元を下げるほど、ずれが大きくなる（3次元で 1.8%、2次元で 12.5%）")

print("\n=== ε展開（先頭項）と比べる ===")
for d in [3,2]:
    eps=4-d
    eta_lead=eps**2*3/(2*(1+8)**2)     # N=1: η = ε²(N+2)/(2(N+8)²)
    print(f"  d={d}: ε={eps}  η(先頭項)={eta_lead:.6f}   実際 {ETA[d]:.6f}   比 {ETA[d]/eta_lead:.2f}")
print("  → 先頭項だけでは 2 倍ずれる。ブートストラップの 7 桁とは別物。")

print("\n=== 3次元イジングの二つの数から、六つの指数 ===")
d=3; Ds=DS[3]; De=1.412625
eta=2*Ds-d+2; nu=1/(d-De)
alpha=2-d*nu; beta=nu*(d-2+eta)/2; gamma=nu*(2-eta); delta=(d+2-eta)/(d-2+eta)
exp_meas={'η':0.0363,'ν':0.6300,'α':0.110,'β':0.3265,'γ':1.2372,'δ':4.789}
print(f"  Δ_σ={Ds}, Δ_ε={De}")
for n,v in [('η',eta),('ν',nu),('α',alpha),('β',beta),('γ',gamma),('δ',delta)]:
    print(f"    {n} = {v:.6f}   （実験・MC {exp_meas[n]}）")
print(f"  恒等式の検算 α+2β+γ = {alpha+2*beta+gamma:.10f}")

print("\n=== このシリーズのウェイト表は、古典近似だった ===")
print("  第1〜13回で使ったウェイト（長さ+1, 質量-1, ...）は、次元解析＝古典。")
print("  場の理論では Δ = Δ_古典 + γ。γ は演算子ごとに違い、走る。")
print("  そして 3次元イジングでは γ_σ = 0.0181489 が 7 桁で測られている。")
print("  → 『ウェイト表の誤差』が、実験値として存在する。")

print("\n=== ただし、測られる無次元量そのものは不変 ===")
print("  臨界指数は観測量（無次元）→ 共形変換で動かない。")
print("  動くのは『古典的に予想したウェイト』であって、実際の物理量ではない。")
