# -*- coding: utf-8 -*-
# 深掘り⑤：1/α がちょうど 137 だったら、何がずれるのか
import math

ln2 = math.log(2)
inv_a = 137.035999177
err_a = 0.000000021          # CODATA 2022
alpha = 1.0 / inv_a

print("=== ① まず、どれだけずれているか ===")
dev = inv_a - 137.0
print("  1/α = %.9f(%d)" % (inv_a, err_a * 1e9))
print("  137 からのずれ = %.9f" % dev)
print("  観測の不確かさ = %.1e" % err_a)
nsig = dev / err_a
print("  → **%.3e σ**（%.2f 百万 σ）" % (nsig, nsig / 1e6))
bits = nsig * nsig / 2 / ln2
print("  第19回の作法でビットに直すと ≈ **%.2e ビット**" % bits)
print("  ★ **『ちょうど 137』は、170 万 σ で排除されている。**")
print("     宇宙のどんな測定より強い排除の一つ。")

print("")
print("=== ② でも、物理としてはどれだけ違うのか ===")
da = (1.0 / 137.0 - alpha) / alpha
print("  1/α = 137 なら α は今より **%.4e（＝ %.4f パーセント）大きい**。" % (da, 100 * da))
print("  ★ たった 0.026 パーセント。**排除が巨大なのは、測定が精密だから**であって、")
print("     物理が微妙に釣り合っているからではない。")

print("")
print("=== ③ 実験室では、何がずれるか ===")
lab = []
# 電子の異常磁気モーメント
a_e, a_e_err = 1.15965218059e-3, 1.3e-13
shift_ae = (alpha / (2 * math.pi)) * da
lab.append(("電子の g−2（a_e）", shift_ae, a_e_err, "a_e ≈ α/2π が主項"))
# 水素 1S-2S（エネルギーは α² に比例）
f12, f12_rel_err = 2.466061413187e15, 4.2e-15
shift_12 = f12 * 2 * da
lab.append(("水素 1S-2S 遷移 [Hz]", shift_12, f12 * f12_rel_err, "E ∝ α²"))
# 微細構造分裂（α⁴）
print("  %-28s %-16s %-16s %-8s %s" % ("量", "ずれ", "測定精度", "何σ", "中身"))
for lab_, sh, er, note in lab:
    print("  %-28s %-16.3e %-16.3e %-8.1e %s" % (lab_, sh, er, sh / er, note))
print("  ★ どちらも **10⁶ σ 級**。実験室だけで完全に決着する。")

print("")
print("=== ④ 世界のほうは、何がずれるか ===")
mn_mp = 1.29333       # MeV
em_part = -1.04       # MeV（n−p 質量差への電磁的寄与。符号：陽子を重くする方向）
me = 0.51099895       # MeV
d_em = em_part * da
Q = mn_mp - me
Qn = (mn_mp + d_em) - me
print("  中性子・陽子の質量差 %.5f MeV のうち、電磁的な寄与は約 %.2f MeV。" % (mn_mp, em_part))
print("  α が %.4e 大きいと、その寄与が %.3f keV 変わる：" % (da, 1000 * d_em))
print("    m_n − m_p : %.5f → %.5f MeV" % (mn_mp, mn_mp + d_em))
print("    β 崩壊の Q値: %.5f → %.5f MeV（%.2e の変化）" % (Q, Qn, (Qn - Q) / Q))
tau, tau_err = 878.4, 0.5
dtau = -5.0 * ((Qn - Q) / Q) * tau
print("  中性子寿命 τ ∝ Q⁻⁵ とすると：%.1f s → %.1f s（**%+.2f s**）" %
      (tau, tau + dtau, dtau))
print("    実測精度 ±%.1f s → **%.1f σ のずれ**" % (tau_err, abs(dtau) / tau_err))
print("  ★ **中性子寿命だけは、かろうじて効く**（3σ 級）。")

print("")
print("=== ⑤ ほかは、ほとんど何も起きない ===")
Tf = 0.8              # MeV（n/p 凍結時の温度）
r = 1.0 / 7.0
dr = -(Qn - Q) / Tf
dY = dr * (1.0 / (1.0 + r))
Yp, Yp_err = 0.247, 0.003
world = [
    ("元素合成のヘリウム量 Y_p", Yp * abs(dY), Yp_err, "n/p ∝ exp(−Q/T_f)"),
    ("ホイル状態（三重α過程）", 0.0, 0.0, "破綻には |Δα/α| > 4 パーセントが要る ── 今回はその 1/152"),
    ("恒星の主系列・化学・生物", 0.0, 0.0, "何も起きない"),
]
print("  %-30s %-14s %-14s %s" % ("量", "ずれ", "観測精度", "中身"))
print("  %-30s %-14.2e %-14.2e %s" % (world[0][0], world[0][1], world[0][2], world[0][3]))
print("    → %.3f σ ── **見えない**" % (world[0][1] / world[0][2]))
for w in world[1:]:
    print("  %-30s %-14s %-14s %s" % (w[0], "──", "──", w[3]))
print("")
print("  ★ **0.026 パーセントでは、宇宙は何も変わらない。**")
print("     効くのは中性子寿命だけで、それも 3σ。")
print("     ── 巨大な排除と、ほぼゼロの物理的影響。この二つは矛盾しない。")

print("")
print("=== ⑥ 核心 ── では、なぜ『137 ちょうど』が気になるのか ===")
print("  それが**整数**だから。整数なら α は『比』ではなく『個数』かもしれない ──")
print("  番外編③の型でいえば、**型 R（比）ではなく型 N（個数）**ということになる。")
print("  エディントンが 1929 年に賭けたのは、まさにそれだった（最初は 136、のち 137）。")
print("")
print("  第19回の作法で、この『近さ』の驚きを測る：")
win = 0.5 * 2   # 136.5〜137.5 の幅 1
hit = 2 * dev   # ±0.036
s = -math.log2(hit / 1.0)
print("    1/α が [136.5, 137.5] に一様なら、整数から ±%.3f 以内に入る確率 = %.3f" % (dev, hit))
print("    驚き = −log₂(%.3f) = **%.1f ビット**" % (hit, s))
print("  ★ **3.8 ビット ── 第36回の『偶然の帯』の、下のほう。**")
print("     気に留めるが、意味は無い。エディントンの誤りは、")
print("     **3.8 ビットの偶然を 0 ビットの恒等式として扱ったこと**だった。")

print("")
print("=== ⑦ そして、もっと効く反論がある ===")
print("  『1/α = 137 ちょうど』は、**そもそも文になっていない**。")
print("  第37回：α は走る。低エネルギーで 137.036、M_Z で **128**。")
inv_mz = 127.951
print("    1/α(0) = %.3f、1/α(M_Z) = %.3f ── 差は %.1f" % (inv_a, inv_mz, inv_a - inv_mz))
print("  → **どのスケールで整数なのかを言わないと、主張が定まらない。**")
print("     第3回：比較相手（ここではスケール）を言わなければ、まだ文になっていない。")
print("  ★ エディントンの時代（1929）には走りが知られていなかった ──")
print("     だから彼の主張は**当時は文になっていて、いまは文になっていない**。")

print("")
print("=== ⑧ 番外編③との接続 ===")
print("  番外編③で無次元量を四型に分けた：比／角度／個数／指数。")
print("  『1/α は整数か』は、**α が型 R か型 N かを問う実験**だった。")
print("  答え：**型 R**。170 万 σ で整数ではないと確定している。")
print("  ★ そしてこれは番外編③の主張の、いちばん鋭い検証になっている ──")
print("     型が違えば自然な測度が違い、事前分布が違い、驚きの計算が変わる。")
print("     **α が個数でないことは、測って決まった。**")

print("")
print("=== ⑨ まとめ ===")
print("  ・『ちょうど 137』は **%.1e σ** で排除。ビットにすれば 10¹² ビット級。" % nsig)
print("  ・ところが物理的な差は **0.026 パーセント** しかない。")
print("    実験室では 10⁶ σ で見えるが、世界の側で効くのは**中性子寿命の 3σ だけ**。")
print("  ・気になる理由は整数だから ── だが『近さ』の驚きは **%.1f ビット**、偶然の帯の下端。" % s)
