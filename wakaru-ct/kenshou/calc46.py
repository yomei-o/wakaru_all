# -*- coding: utf-8 -*-
# 第42回：ブラックホールの内部 ── 地平面は、共形変換では消せない
import math

G = 6.67430e-11
c = 2.99792458e8
hbar = 1.054571817e-34
ln2 = math.log(2)
Msun = 1.98892e30
t0 = 13.79e9 * 3.1557e7
g0 = 9.80665

print("=== ① 地平面は、共形変換で消せるか ===")
print("  共形変換 g → Ω²g（Ω > 0、なめらか）は、**光円錐を動かさない**。")
print("  → ヌル測地線の集合は変わらず、因果構造はそのまま。")
print("  事象の地平面の定義は『未来のヌル無限遠の因果的過去の境界』── **因果構造だけで決まる**。")
print("  ★ したがって **事象の地平面はウェイト 0。共形変換では作れも消せもしない**。")
print("     このシリーズの道具が、ブラックホールを消せない理由。")

print("")
print("=== ② ところが、見かけの地平面は共形不変ではない ===")
print("  見かけの地平面は『外向きヌル束の膨張 θ = 0』で決まる ── 局所的な幾何の量。")
print("  共形変換のもとで  θ → Ω⁻¹( θ + 2 lᵘ ∂ᵘ lnΩ )")
print("  → **θ = 0 は保たれない**。見かけの地平面は動く。")
print("  ★ 二つの地平面の違いが、そのままウェイトの違いになっている：")
rows = [
    ("事象の地平面", "因果構造で決まる（大域的）", "ウェイト 0", "動かない"),
    ("見かけの地平面", "θ = 0 で決まる（局所的）", "ウェイト ≠ 0", "**動く**"),
]
print("  %-18s %-30s %-14s %s" % ("地平面", "決め方", "ウェイト", "共形変換"))
for a, b, c_, d in rows:
    print("  %-18s %-30s %-14s %s" % (a, b, c_, d))
print("  ※ ただし事象の地平面を実際に見つけるには**未来を全部知る必要がある**。")
print("     動かない方は測れず、測れる方は動く ── これが③につながる。")

print("")
print("=== ③ ペンローズ図 ── 記法が仕事をする、ただ一つの場所 ===")
print("  ペンローズ図は共形変換そのもの：Ω を選んで無限遠を有限の距離に引き寄せる。")
print("  変わるもの ── 紙の上の距離（帳簿）")
print("  変わらないもの ── 光円錐の傾き（＝因果構造＝物理）")
print("  ★ 第1回の主張『c·t = 一定 は記法であってモデルではない』の**双子**：")
print("     ペンローズ図もモデルではない。**それでも相対論で最も有用な道具の一つ**。")
print("     → **記法は無価値ではない。ただ、主張ではないだけ。**")

print("")
print("=== ④ 中に入ると、どれくらい痛いか ===")
print("  地平面での潮汐加速度（身長 h = 2 m）： Δa = h c⁶ / (4 G² M²)")
h = 2.0
for name, Msol in [("太陽質量 BH", 1.0), ("いて座 A* (4.3e6 M☉)", 4.3e6),
                   ("M87* (6.5e9 M☉)", 6.5e9)]:
    M = Msol * Msun
    da = h * c ** 6 / (4 * G ** 2 * M ** 2)
    rs = 2 * G * M / c ** 2
    tau = math.pi * G * M / c ** 3
    print("  %-24s r_s = %-11.3e m  Δa = %-11.3e m/s² = %-11.2e g  地平面→特異点 %.3e s" %
          (name, rs, da, da / g0, tau))
print("  ★ 太陽質量では 2×10⁹ g ── 原子ごと引き裂かれる。")
print("     **M87* では 5×10⁻¹¹ g ── まったく感じない。**")
print("     地平面は『何かが起きる場所』ではない ── 大きい BH では、通過に気づかない。")

print("")
print("=== ⑤ 中で、どれだけ情報を読めるか ===")
E_human = 70.0 * c ** 2
C_human = 2 * math.pi * E_human / (hbar * ln2)
print("  第24回のチャンネル容量を、70 kg の観測者に当てる：")
print("    E = mc² = %.3e J → C = 2πE/(ħ ln2) = %.3e bit/s" % (E_human, C_human))
print("")
print("  %-24s %-14s %-14s %-14s %s" % ("BH", "τ [s]", "読める [bit]", "BH の S [bit]", "足りない [bit]"))
for name, Msol in [("太陽質量", 1.0), ("いて座 A*", 4.3e6), ("M87*", 6.5e9)]:
    M = Msol * Msun
    tau = math.pi * G * M / c ** 3
    read = C_human * tau
    S = 4 * math.pi * G * M ** 2 / (hbar * c) / ln2
    print("  %-24s %-14.3e %-14.3e %-14.3e %.1f" %
          (name, tau, read, S, math.log2(S / read)))
print("  ★ どの場合も**桁違いに足りない**。中に入っても、中身は読めない。")
print("     ── 情報が『失われる』かどうか以前に、**取り出す時間が無い**。")

print("")
print("=== ⑥ 蒸発の時計 ===")
print("  t_evap = 5120 π G² M³ / (ħ c⁴)")
K = 5120 * math.pi * G ** 2 / (hbar * c ** 4)
for name, Msol in [("太陽質量", 1.0), ("M87*", 6.5e9)]:
    M = Msol * Msun
    te = K * M ** 3
    print("  %-16s t_evap = %.3e s = %.3e 年 （宇宙年齢の %.2e 倍）" %
          (name, te, te / 3.1557e7, te / t0))
M_now = (t0 / K) ** (1.0 / 3.0)
print("  いま蒸発し終わる質量： M = (t₀/K)^(1/3) = %.3e kg" % M_now)
print("    （地球の山ひとつぶん。原始ブラックホールとして探されている質量帯）")
print("  ★ 恒星質量以上の BH は、**宇宙年齢の 10⁵⁷ 倍以上**かかる ── 実質、蒸発しない。")

print("")
print("=== ⑦ ページ時間 ── 情報が出てくるとしたら、いつか ===")
print("  ページ曲線：放射のエンタングルメント・エントロピーは、")
print("  BH のエントロピーと等しくなる時点（ページ時間）で折り返す。")
print("  面積が半分 ＝ M/M₀ = 1/√2 = %.4f のとき。" % (1 / math.sqrt(2)))
frac = 1 - (1 / math.sqrt(2)) ** 3
print("  質量が M₀ → M₀/√2 になるまでの時間の割合：")
print("    t/t_evap = 1 − (1/√2)³ = %.4f  → **蒸発時間の %.0f パーセント**" % (frac, 100 * frac))
print("  ※ よく引かれる『0.54』は別の規約（放射のエントロピーが最大になる時点の取り方）")
print("     による値で、ここでは面積が半分になる時点を採った。")
print("  ★ どちらにせよ**蒸発の中盤**。情報が出てくるとしたら、そこから後。")
print("     太陽質量なら %.2e 年後 ── 待てる話ではない。" % (frac * K * Msun ** 3 / 3.1557e7))

