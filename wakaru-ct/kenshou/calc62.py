print("")
print("  【広い読み】もっと広く探したとする：")
wide = [("使う質量の部分集合（12 個から選ぶ）", 2 ** 12),
        ("指数を −3〜3 の 7 通りで振る（3 か所）", 7 ** 3),
        ("目標の有理数", 100)]
Mw = 1
for lab, n in wide:
    Mw *= n
    print("    %-40s %d 通り" % (lab, n))
print("    → M = %.2e、閾値 = **%.1f ビット**" % (Mw, math.log2(Mw)))
print("")
koide = 15.7
