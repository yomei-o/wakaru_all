rel_width = Gam / m_tau_eV
print("  そして τ には**自然幅という原理的な限界**がある：")
print("    寿命 %.1f fs → Γ = %.3e eV、Γ/m_τ = %.3e" % (tau_life * 1e15, Gam, rel_width))
