print("  この式が属する『族』の大きさを、二通りに見積もる：")
narrow = [("指数 p ∈ {1/2, 1, 2}", 3), ("指数 q ∈ {1/2, 1, 2}", 3),
          ("外側のべき r ∈ {1, 2}", 2), ("目標の簡単な有理数", 7)]
Mn = 1
print("  【狭い読み】小出の形だけを試したとする：")
for lab, n in narrow:
    Mn *= n
    print("    %-30s %d 通り" % (lab, n))
