# -*- coding: utf-8 -*-
# 深掘り⑪：「素粒子はこじつけ」を、第5回の天秤に載せる
import math

ln2 = math.log(2)
bic = 0.5 * math.log2(1701)      # パラメータ 1 個の値段

print("=== ① 主張を、四つの読みに分ける ===")
claims = [
    ("(a) 合わせ込みだ", "パラメータが 19 個もある。ただのフィットではないか", "②で検定"),
    ("(b) 無限大を引く計算が怪しい", "くりこみは辻褄合わせではないか", "③で検定"),
    ("(c) 困ると粒子を足す", "ニュートリノ、クォーク、ヒッグス、SUSY…", "④で検定"),
    ("(d) 中身が説明されていない", "なぜ 3 世代か、なぜこの質量か", "⑥で検定"),
]
print("  %-26s %-40s %s" % ("読み", "中身", "どこで"))
for a, b, c in claims:
    print("  %-26s %-40s %s" % (a, b, c))

print("")
print("=== ② 検定 (a) ── 標準模型は、払った以上に買っているか ===")
n_par = 19
pay = n_par * bic
print("  払う：パラメータ %d 個 × %.2f = **%.1f ビット**" % (n_par, bic, pay))
print("")
print("  買う（合わせていないデータに当たったもの。第48回の『深さ』）：")
buys = []

# 電子の g−2：α は別の実験（原子反跳）から取り、あとは純粋な計算
a_e, a_e_err = 1.15965218059e-3, 1.3e-13
agree_rel = 2.0e-10
buys.append(("電子の g−2（10 桁）", -math.log2(agree_rel), "α は原子反跳から。残りは計算だけ"))

# W ボソン質量：α, G_F, m_Z から予言
mW, mW_err = 80.377, 0.012
buys.append(("W 質量（発見前に予言）", math.log2(990.0 / mW_err), "prior 10〜1000 GeV"))

# Z 幅からの軽いニュートリノの数
nnu, nnu_err = 2.9840, 0.0082
buys.append(("軽いニュートリノは 3 種（Z 幅）", math.log2(10.0 / (2 * nnu_err)), "prior 0〜10"))

# トップ質量：電弱フィットが発見前に予言
buys.append(("トップ質量（発見前に予言）", math.log2(999.0 / 40.0), "1994 年の予言 178±20、実測 173"))

# ヒッグス質量：電弱フィットが上限を予言
buys.append(("ヒッグス質量の上限（発見前）", math.log2(900.0 / 120.0), "prior 100〜1000 GeV"))

# くりこみの検算（第44回）：格子と連続がまったく別の方法で一致
buys.append(("格子 対 連続の一致（第44回）", math.log2(2.0 / 1.7e-4), "ν が 4 桁一致"))

print("  %-34s %-14s %s" % ("買ったもの", "ビット", "中身"))
tot = 0.0
for a, b, c in buys:
    tot += b
    print("  %-34s %-14.1f %s" % (a, b, c))
print("  ── 六項目の小計 **%.1f ビット**（払いの %.0f%%）" % (tot, 100 * tot / pay))
print("")
print("  ★ **六項目だけではまだ足りない。** %.1f − %.1f = **%+.1f ビット**。" %
      (tot, pay, tot - pay))
print("     → 帳簿を閉じるには、もう一段数える必要がある。")
print("")
print("  二段目（同じく、発見前の予言か、合わせていない一致）：")
buys2 = []
# Z 質量：中性カレントから sin^2θ_W を決めて、発見前に予言
buys2.append(("Z 質量（発見前に予言）", math.log2(990.0 / 4.0),
              "1983 年の予言 93.8±2.0、実測 91.19"))
# Ω⁻：SU(3) の分類から質量ごと予言
buys2.append(("Ω⁻ 質量（発見前に予言）", math.log2(1000.0 / 13.0),
              "予言 1685 MeV、実測 1672"))
# R 比：色の数 = 3 はパラメータを使わない予言
buys2.append(("e⁺e⁻ の R 比（色は 3 色）", math.log2(10.0 / 0.3),
              "R = 3Σq²。パラメータを一つも使わない"))
# α_s の普遍性：まったく違う過程から同じ値
buys2.append(("α_s の普遍性（τ 崩壊 対 格子）", math.log2(0.45 / 0.0021),
              "エネルギーが 50 倍違う測定が一致"))
for a, b, c in buys2:
    tot += b
    print("  %-34s %-14.1f %s" % (a, b, c))
print("  ── 十一項目で **%.1f ビット**" % tot)
print("")
print("  ★ **払い %.1f に対し、十一項目で買い %.1f。** 差し引き **%+.1f ビット**。" %
      (pay, tot, tot - pay))
print("     ただしこの **%+.1f は細い** ── 事前範囲の取り方で簡単に前後する。" % (tot - pay))
print("")
print("  そこで、**事前範囲を決めなくていい項目**を一つだけ足す：")
cpt = -math.log2(1.6e-12)
print("    反陽子と陽子の q/m が **1.6e-12** で一致（BASE）→ **%.1f ビット**" % cpt)
print("    これはパラメータを一つも使わない。場の量子論の枠組み（CPT）が")
print("    「ちょうど等しい」と言うだけで、ずれを許すつまみが一つも無い。")
print("  ★ 合計 **%.1f ビット**。払い %.1f に対して **%+.1f**。" %
      (tot + cpt, pay, tot + cpt - pay))
print("")
print("  ★ しかも数え漏らしが大量にある ── 中性カレント、チャーム、")
print("     グルーオンのスピン、漸近自由性、スケーリング違反、CP 対称性の破れの大きさ…")
print("  → **(a) は外れる。ただし『圧倒的に』ではなく、**")
print("     **数え方を丁寧にやってやっと黒字になる。**")

print("")
print("=== ③ 検定 (b) ── くりこみは辻褄合わせか ===")
print("  もし『無限大を都合よく引いている』だけなら、")
print("  **まったく違う正則化どうしが一致するはずがない**。")
boot = 0.6299709
latt = 0.63002
rel = abs(boot - latt) / boot
print("    共形ブートストラップ（連続）  ν = %.7f" % boot)
print("    格子モンテカルロ（切断あり）  ν = %.5f" % latt)
print("    相対差 %.1e → **%.1f ビットぶん一致している**" % (rel, -math.log2(rel)))
print("  ★ **切断を入れる方法と、入れない方法が 4 桁一致する。**")
print("     辻褄合わせなら起きない。第44回のとおり ──")
print("     **くりこみは『答えが切断に依らない』という主張**であって、引き算の技ではない。")
print("  → **(b) も外れる。**")

print("")
print("=== ④ 検定 (c) ── 粒子を足した歴史の成績 ===")
hist = [
    ("ニュートリノ（1930）", "エネルギー保存が壊れる", "**強制**", "1956 発見", "◎"),
    ("クォーク（1964）", "ハドロンの分類が説明できない", "**強制**", "1969 DIS", "◎"),
    ("チャーム（1970）", "K 中間子の FCNC が合わない", "**強制**", "1974 発見", "◎"),
    ("ヒッグス（1964）", "ゲージ不変性と質量が両立しない", "**強制**", "2012 発見", "◎"),
    ("グルーオン（1973）", "スケーリング則が破れる", "**強制**", "1979 3 ジェット", "◎"),
    ("超対称性（1970s〜）", "**自然さ**（階層性問題）", "任意", "未発見", "✗"),
    ("テクニカラー", "**自然さ**", "任意", "排除", "✗"),
    ("大きな余剰次元", "**自然さ**", "任意", "排除", "✗"),
    ("WIMP", "**存在量の偶然**（WIMP miracle）", "任意", "未発見", "✗"),
    ("アクシオン（1977）", "強い CP（**本物の微調整**）", "半ば強制", "未発見", "△"),
]
print("  %-24s %-30s %-12s %-16s %s" % ("追加したもの", "動機", "強制か", "その後", "成績"))
for a, b, c, d, e in hist:
    print("  %-24s %-30s %-12s %-16s %s" % (a, b, c, d, e))
forced = sum(1 for h in hist if h[2] == "**強制**")
opt = sum(1 for h in hist if h[2] == "任意")
print("")
print("  ★ **矛盾に強制された追加：%d 件、全部当たり。**" % forced)
print("  ★ **自然さから動機づけられた追加：%d 件、全部外れ（未発見か排除）。**" % opt)
print("  → **(c) は半分当たり。** 『困ると足す』が正しいのは、**後者だけ**。")

print("")
print("=== ⑤ 核心 ── 『こじつけ』という感覚は、探索空間を検出している ===")
print("  ④の分かれ目は、番外編④の引き算そのもの：")
sp = [
    ("矛盾に強制された追加", "候補は事実上 1 通り", "log₂M ≈ 0", "**引かれない → こじつけに見えない**"),
    ("自然さから動機づけられた追加", "候補は無数（模型は千を超える）", "log₂M ≫ 10", "**大きく引かれる → こじつけに見える**"),
]
print("  %-30s %-28s %-14s %s" % ("種類", "探索空間", "値段", "感じ方"))
for a, b, c, d in sp:
    print("  %-30s %-28s %-14s %s" % (a, b, c, d))
print("")
print("  ★ **『こじつけっぽい』は、探索空間の大きさを鼻で嗅ぎ当てている。**")
print("     ── 番外編④で計算した log₂M が、感覚として先に来ていた。")
print("     ニュートリノは『そう置くしかなかった』からこじつけに見えず、")
print("     超対称性は『そう置く理由が無数にある』からこじつけに見える。")

print("")
print("=== ⑥ 検定 (d) ── そして、ここは完全に当たっている ===")
unexplained = 32 * bic
print("  第47回：無次元パラメータ 32 個、第一原理から導かれたものは**ほぼゼロ**。")
print("    → **%.1f ビットが説明されていない**。" % unexplained)
print("  ・なぜ 3 世代か ── 答えが無い")
print("  ・なぜこの質量比か ── 答えが無い（番外編④の型 C は一つも確立していない）")
print("  ・なぜこのゲージ群か ── 答えが無い")
print("  ★ **標準模型は、記述であって説明ではない。** ここは (d) の言うとおり。")

print("")
print("=== ⑦ そして、標準模型の『上』はもっと悪い ===")
mssm_new = 105
print("  最小超対称標準模型（MSSM）の新しいパラメータ：**%d 個**" % mssm_new)
print("    払う： %d × %.2f = **%.0f ビット**" % (mssm_new, bic, mssm_new * bic))
print("    買う： 確認された予言 **0 ビット**")
print("  ★ **%.0f ビット払って 0 ビット。** これは標準模型とは真逆の帳簿。" % (mssm_new * bic))
print("     ── **『こじつけ』が当てはまるのは、標準模型ではなく、その上に建てたもの。**")
print("  ※ ただし MSSM の 105 個の多くは実験で強く制限されており、")
print("     『払った %.0f ビット』は最悪の見積もり。それでも黒字にはほど遠い。" % (mssm_new * bic))

print("")
print("=== ⑧ 判定 ===")
verdict = [
    ("(a) 合わせ込みだ", "**外れ**", "十一項目＋CPT で払いを上回る（%+.0f ビット）" % (tot + cpt - pay)),
    ("(b) くりこみは辻褄合わせ", "**外れ**", "別々の正則化が 4 桁一致（%.0f ビット）" % (-math.log2(rel))),
    ("(c) 困ると粒子を足す", "**半分当たり**", "矛盾駆動は 5 戦 5 勝、自然さ駆動は 4 戦 0 勝"),
    ("(d) 中身が説明されていない", "**当たり**", "%.0f ビットが未説明、型 C はゼロ" % unexplained),
]
print("  %-30s %-14s %s" % ("読み", "判定", "根拠"))
for a, b, c in verdict:
    print("  %-30s %-14s %s" % (a, b, c))
print("")
print("  ★ **標準模型は『こじつけ』ではない ── この物差しでは黒字。**")
print("  ★ **標準模型の上に建てたものは『こじつけ』── 払いだけで買いがゼロ。**")
print("  ★ そして **『説明していない』という不満は完全に正当**。")
print("     標準模型は世界を**書き写して**いるだけで、**導いて**はいない。")

print("")
print("=== ⑨ 正直な線 ===")
print("  ・②の『買い』のビット数は、事前範囲を私が決めている。")
print("    W 質量の prior を 10〜1000 GeV と取るのは恣意的で、")
print("    **番外編④で自分が指摘した弱点をそのまま踏んでいる**。")
print("    ただし④の歴史的な成績（5 勝 0 敗 対 0 勝 4 敗）は事前範囲に依らない。")
print("  ・黒字幅は細い。事前範囲を少し狭く取るだけで赤字にできる。")
print("    『圧倒的な黒字』と書きたくなったが、計算はそう言っていない。")
print("  ・②の合計は**部分的**で、完全な帳簿は作れない（買いの項目が多すぎる）。")
print("    多すぎて数え切れないこと自体が (a) への反証になっている、とも言える。")
print("  ・⑦の MSSM の 105 個は最悪の数え方。制限を入れれば実効的にはずっと少ない。")
print("  ・⑤の『感覚が探索空間を検出している』は、面白い読みだが**推測**。")
print("    人がなぜこじつけと感じるかの心理は、本稿では測っていない。")
