# 深掘り④：無次元量とは何か ── そして、定数は一つもないのかもしれない
import math

ln2 = math.log(2)
pi = math.pi

print("=== ① 無次元量とは、そもそも何か ===")
print("  作業的な定義がひとつある ── **電波で送れるもの**。")
print("  「1 メートル」は送れない（相手に物差しが要る）。")
print("  「α = 1/137.036」は送れる ── 受け取った側が自分の実験で確かめられる。")
print("  ★ **無次元量とは、物を運ばずに伝えられる量。** それが『物理』の中身だった。")
print("     第47回で SI が c を法令で決めて α を決められなかったのも、これと同じこと。")

print("")
print("=== ② ところが『0 の列』は、一様ではなかった ===")
print("  50 回のあいだ、無次元量をひとつの列に入れて扱ってきた。")
print("  だが中身は少なくとも四種類ある ── **群が違う**：")
kinds = [
    ("比（スケール的）", "α、m_p/m_e、Ω_Λ、ρ_Λ/ρ_P", "乗法群 ℝ₊", "d(ln x) ＝ 対数一様", "**発散する（正規化できない）**"),
    ("角度・位相", "θ_QCD、CKM/PMNS の角と位相", "コンパクト群 U(1) など", "dθ ＝ 一様", "**有限（正規化できる）**"),
    ("個数", "世代 3、色 3、次元 4", "離散", "数える", "有限"),
    ("指数（対数微分）", "n_s、ν、η、ω", "接空間（すでに log の傾き）", "定めにくい", "──"),
]
print("  %-18s %-30s %-20s %-22s %s" % ("型", "例", "群", "自然な測度（Haar）", "全測度"))
for a, b, c, d, e in kinds:
    print("  %-18s %-30s %-20s %-22s %s" % (a, b, c, d, e))

print("")
print("=== ③ 『本当に対数なのか』── 対数は発見ではなく、同型 ===")
print("  比は掛け算で合成する（α を 2 倍、さらに 3 倍 → 6 倍）。**乗法群**。")
print("  log を取ると足し算になる ── **log は ℝ₊ → ℝ の群同型**、それだけ。")
print("  そして ℝ₊ の Haar 測度は dx/x = d(ln x)。**対数一様が『自然』なのはこのため。**")
print("")
print("  角度は違う。足し算で合成し、2π で戻る。**コンパクト群**。")
print("  → Haar 測度は dθ（一様）。**角度の log には意味が無い。**")
print("  ★ だから：**ビットは量そのものの対数ではなく、確率の対数**。")
print("     −log₂(確率) を測るには測度が要り、測度は群が決める。")
print("     本シリーズが 50 回ぶんやってきたのは、ずっとこれだった。")

print("")
print("=== ④ 核心 ── これで第48回の基準が『定理』になる ===")
print("  第48回：『自然さは事前分布の選択』『事前に理由があるかを見よ』── 基準だった。")
print("  ②③より、それは群の性質から出る：")
print("")
print("    **コンパクト群** → Haar 測度は有限 → 正規化できる → **事前分布が一意に決まる**")
print("                     → 微調整の議論は **well-posed**")
print("    **非コンパクト（ℝ₊）** → Haar 測度は無限 → 正規化できない")
print("                     → **事前分布は決まらない**（切断を入れるのは選択）")
print("                     → 微調整の議論は **ill-posed**")
print("")
print("  ★ **第48回の『角度には理由がある、質量比には無い』は、")
print("     コンパクトか否かの言い換えだった。** 基準ではなく、定理。")

print("")
print("=== ⑤ 検証 ── コンパクト類のなかで、ビットは深刻さを予測するか ===")
ang = [
    ("PMNS θ₂₃", 49.0, "最大混合に近い（『小さい』のとは別種）"),
    ("PMNS θ₁₂", 33.4, "とくに問題視されない"),
    ("CKM θ₁₂（カビボ角）", 13.04, "とくに問題視されない"),
    ("PMNS θ₁₃", 8.57, "小さめ、議論はある"),
    ("CKM θ₂₃", 2.38, "フレーバー階層の一部"),
    ("CKM θ₁₃", 0.201, "**フレーバー puzzle の中心**"),
]
print("  %-24s %-12s %-12s %s" % ("角度", "値[度]", "驚き[bit]", "実際の扱われ方"))
for lab, deg, note in ang:
    r = math.radians(deg)
    s = -math.log2(r / (pi / 2))
    print("  %-24s %-12.3f %-12.2f %s" % (lab, deg, s, note))
th_bound = 1e-10
s_theta = -math.log2(th_bound / (2 * pi))
print("  %-24s %-12s %-12.2f %s" % ("θ_QCD", "< 1e-10", s_theta, "**唯一の『危機』**"))
print("")
print("  ★ **コンパクト類の中では、ビット数と深刻さがきれいに単調**：")
print("     0〜3 ビット＝話題にならない／5〜9＝フレーバー puzzle／36＝危機。")
print("  ★ そして**争いのない微調整問題は、唯一の角度（θ_QCD）だけ**。")
print("     論争中のもの（v/M_P、ρ_Λ）はすべて非コンパクト類 ──")
print("     **論争しているのではなく、問いが well-posed でないから決まらない。**")

