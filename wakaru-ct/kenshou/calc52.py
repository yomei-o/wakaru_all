# -*- coding: utf-8 -*-
# 第48回：短さ・当てはまり・美しさ ── 三つの通貨
import math

bic = 0.5 * math.log2(1701)      # 第5回：パラメータ 1 個の値段

print("=== ① 第5回の天秤には、通貨が二つあった ===")
print("  記述長 L = L(モデル) + L(データ|モデル)")
print("    L(モデル)      ── **短さ**：パラメータ 1 個につき %.2f ビット" % bic)
print("    L(データ|モデル) ── **当てはまり**：Δχ² / (2 ln2) ビット")
print("  ★ 物理学者はしばしば三つ目のことを言う ── 『**美しい**』。")
print("     それは三つ目の通貨なのか、それとも前の二つの言い換えなのか。")

print("")
print("=== ② 『美しさ』を、部品に分解する ===")
parts = [
    ("対称性", "独立なパラメータを減らす", "**短さ**に還元できる"),
    ("統一", "入力の個数を減らす", "**短さ**に還元できる"),
    ("剛性（他に選びようがない）", "自由な選択を減らす", "**短さ**に還元できる"),
    ("深さ（作った目的外まで当たる）", "合わせていないデータに当たる", "**当てはまり**に還元できる"),
    ("自然さ（不自然に小さい数が無い）", "**事前分布についての主張**", "**還元できない**"),
    ("感覚的な快", "式を見たときの手応え", "**本シリーズの道具では測れない**"),
]
print("  %-30s %-32s %s" % ("部品", "中身", "どの通貨か"))
for a, b, c in parts:
    print("  %-30s %-32s %s" % (a, b, c))
print("  ★ 六つのうち四つは既存の二通貨に還元できる。")
print("     残りは **自然さ**（③で測る）と **感覚的な快**（⑦で扱う）。")

print("")
print("=== ③ 対称性は、いくら買うのか ── CKM 行列で数える ===")
print("  3×3 のユニタリ行列の独立なパラメータは 9 個。")
print("  クォーク場の位相を付け替える自由度で 5 個が落ちる（全体の位相 1 個は効かない）。")
print("  → 残る物理的なパラメータは **4 個**（3 つの角 ＋ 1 つの位相）。")
print("  %d → %d、圧縮 %.2f 倍。第5回の値段では **%.1f ビットの節約**。" %
      (9, 4, 9.0 / 4, 5 * bic))
print("  ★ **対称性は、短さで測れる。** ここに謎は無い。")

print("")
print("=== ④ 核心 ── 『自然さ』は、事前分布についての主張だった ===")
print("  同じ数字が、事前分布の取り方で**まったく違う驚きになる**：")
cases = [
    ("v / M_Planck（階層性問題）", 2.017e-17, 80.0, "線形なら「不自然」、対数一様なら普通"),
    ("(v / M_Planck)²（ヒッグス質量の微調整）", 4.07e-34, 80.0, "同上"),
    ("ρ_Λ / ρ_Planck（第32回）", 1.13e-123, 300.0, "第32回の 408 ビットの正体"),
]
print("  %-40s %-14s %-14s %s" % ("量", "線形な事前", "対数一様な事前", "差"))
for name, val, decades, note in cases:
    lin = -math.log2(val)
    logu = math.log2(decades)
    print("  %-40s %-14.1f %-14.1f %.1f" % (name, lin, logu, lin - logu))
print("")
print("  ★ **同じ数が、55 ビット驚きにも 6 ビット驚きにもなる。**")
print("     『不自然だ』という言明は、**事前分布を線形に取ると宣言している**のと同じ。")
print("     ── 第19回①で『事前範囲の取り方に依存する』と書いた、その場所そのもの。")
print("  ★ したがって：**自然さは第三の通貨ではなく、事前分布の選択である。**")

print("")
print("=== ⑤ ただし、線形な事前が正当な場合もある ===")
theta_bound = 1e-10
print("  強い CP 問題：θ_QCD < %.0e（中性子の電気双極子モーメントから）" % theta_bound)
print("  θ は**角度**なので、事前分布が [0, 2π) の一様分布であることに理由がある。")
print("  → 対数一様に逃げられない。驚き = −log₂(%.0e/2π) ≈ **%.1f ビット**" %
      (theta_bound, -math.log2(theta_bound / (2 * math.pi))))
print("  ★ **これは本物の微調整**。④の二つとは性質が違う ──")
print("     『自然さ』を言うときは、**事前分布に理由があるかどうか**を見ればよい。")
print("     角度には理由がある。質量の比には、いまのところ無い。")

print("")
print("=== ⑥ 有名な『美しい理論』を、分解してみる ===")
th = [
    ("一般相対論", "剛性（仮定を置くとほぼ一意）", "短さ", "◎ 測れる"),
    ("ディラック方程式", "陽電子を予言した（作った目的外）", "当てはまり", "◎ 測れる"),
    ("標準模型", "32 個のパラメータ", "短くない", "── 美しいとは呼ばれない"),
    ("超対称性", "階層性問題を解く（自然さ）", "事前分布", "△ 事前次第"),
    ("弦理論", "一意性の主張 → ランドスケープ", "短さの主張が崩れた", "△ 未決着"),
]
print("  %-16s %-34s %-16s %s" % ("理論", "美しさの中身", "通貨", "測れるか"))
for a, b, c, d in th:
    print("  %-16s %-34s %-16s %s" % (a, b, c, d))
print("  ★ **『美しい』と呼ばれる理由は、たいてい短さか当てはまりに分解できる。**")
print("     分解できないときは、事前分布を疑うとよい。")

print("")
print("=== ⑦ 測れなかったもの ===")
print("  ②の六つ目 ── **感覚的な快**は、本シリーズの道具では測れなかった。")
print("  ・記述長では測れない（短い式が美しいとは限らない）")
print("  ・当てはまりでは測れない（当たる式が美しいとは限らない）")
print("  ・事前分布でも測れない（それは自然さの話）")
print("  ★ **正直に書いておく：ここは測れない。**")
print("     測れないことは、無いことではない ── ただ、本シリーズの通貨では扱えない。")
print("     そして『測れないものを判定に使わない』のが、第3回以来の作法だった。")

print("")
print("=== ⑧ このシリーズ自身を、この物差しに当てる ===")
print("  c·t = 一定 の『美しさ』を分解すると：")
mine = [
    ("短さ", "パラメータが 1 個減る（第25回）", "**買っている**"),
    ("当てはまり", "q、w が桁で外れる（第46回）", "**大きく払っている**"),
    ("自然さ", "『c·t = 一定』は不自然な数を含まない", "事前分布の話 ── 効かない"),
    ("感覚的な快", "『一定』という形の心地よさ", "**測れない**"),
]
print("  %-14s %-38s %s" % ("通貨", "中身", "判定"))
for a, b, c in mine:
    print("  %-14s %-38s %s" % (a, b, c))
print("  ★ **短さで買い、当てはまりで大きく払っている。** 判定は変わらない。")
print("     そして『形が心地よい』ことは、**判定に入れない** ── それが手続きだった。")

print("")
