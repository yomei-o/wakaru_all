# -*- coding: utf-8 -*-
# 第40回：重力エントロピー ── 1.5e77 ビットは何の情報か
import math

G = 6.67430e-11
c = 2.99792458e8
hbar = 1.054571817e-34
lP = 1.616255e-35
H0 = 67.4 * 1000 / 3.0856775814913673e22    # [1/s]
t0 = 13.79e9 * 3.1557e7                      # 宇宙年齢 [s]（第30回と同じ）
ln2 = math.log(2)

RH = c / H0
rho_c = 3 * H0 ** 2 / (8 * math.pi * G)
V = 4.0 / 3.0 * math.pi * RH ** 3
M = rho_c * V

print("=== ① ブラックホールのエントロピーは、ウェイト 0 の列にある ===")
rows = [
    ("S/k_B = A / 4ℓ_P²", "+2 −(+2) = 0", "面積を面積で割っている"),
    ("ベケンシュタイン限界 2πER/(ħc)", "−1 +1 −0 = 0", "エネルギー × 長さ"),
    ("ワイル² / リッチ²（ペンローズ）", "−4 −(−4) = 0", "曲率²を曲率²で割っている"),
    ("K·r_s⁴（クレッチマン × 半径⁴）", "−4 +4 = 0", "後で使う"),
]
print("  %-34s %-18s %s" % ("量", "ウェイト", "中身"))
for a, b, d in rows:
    print("  %-34s %-18s %s" % (a, b, d))
print("  ★ **重力エントロピーという主題は、まるごと無次元の列にある**。")
print("     第36回③で見たとおり ── 判定の土俵に乗っている。")

print("")
print("=== ② ハッブル球は、ちょうど自分のシュヴァルツシルト半径にいる ===")
rs = 2 * G * M / c ** 2
print("  H₀ = 67.4 → R_H = c/H₀ = %.4e m" % RH)
print("  臨界密度 ρ_c = 3H₀²/8πG = %.4e kg/m³" % rho_c)
print("  ハッブル球の質量 M = ρ_c V = %.4e kg" % M)
print("  その シュヴァルツシルト半径 r_s = 2GM/c² = %.4e m" % rs)
print("  r_s / R_H = %.6f" % (rs / RH))
print("  ★ **ちょうど 1**。これは偶然ではなく**恒等式**：")
print("     r_s = 2G/c² · (4/3)πR³ · 3H²/(8πG) = R³H²/c² = R  （R = c/H だから）")
print("  → 第19回の分類では **0 ビット（恒等式）**。")

print("")
print("=== ③ 三つの『10¹²²』は、同じ数だった ===")
S_holo = math.pi * RH ** 2 / lP ** 2                 # A/4ℓ_P² = πR²/ℓ_P²
S_bh = 4 * math.pi * G * M ** 2 / (hbar * c)         # 同じ質量を 1 個の BH にした場合
E = M * c ** 2
C_ch = 2 * math.pi * E / (hbar * ln2)                # 第24回のチャンネル容量 [bit/s]
N24 = C_ch * t0
print("  %-44s %s" % ("量", "値"))
print("  %-44s %.3e nat" % ("ホログラフィック限界 A/4ℓ_P²", S_holo))
print("  %-44s %.3e bit" % ("　同じものをビットで", S_holo / ln2))
print("  %-44s %.3e nat" % ("全質量を 1 個の BH にしたときの S/k_B", S_bh))
print("  %-44s %.3e bit/s" % ("第24回のチャンネル容量 C = 2πE/(ħ ln2)", C_ch))
print("  %-44s %.3e bit" % ("第24回の N = C·t₀", N24))
print("")
print("  S_BH / S_holo = %.6f   ← **恒等式**（②より r_s = R_H だから）" % (S_bh / S_holo))
print("  N / (S_holo/ln2) = %.4f" % (N24 / (S_holo / ln2)))
print("  そのずれの正体： t₀ / (R_H/c) = %.4f" % (t0 / (RH / c)))
print("  ★ **二つは同じ数で、5 パーセントのずれは『宇宙年齢とハッブル時間の差』そのもの**。")
print("     第26回でやった圧縮がまた効いた ── **三つの見出しの数字は、一つだった**。")
print("     第19回の分類では **0 ビット**（恒等式）。")

print("")
print("=== ④ では、実際のエントロピーはいくつか ===")
budget = [
    ("超巨大ブラックホール", 3.1e104, "全体を支配する。見積もりの幅は大きい"),
    ("恒星質量ブラックホール", 2.2e96, ""),
    ("CMB 光子", 2.03e89, ""),
    ("背景ニュートリノ", 1.93e89, ""),
    ("背景重力波（相対論的重力子）", 2.3e87, "特に不確か"),
    ("星間物質・星など", 2.6e81, ""),
]
tot = sum(x[1] for x in budget)
print("  Egan & Lineweaver (2010) の見積もり（単位は k_B）：")
print("  %-28s %-12s %-10s %s" % ("成分", "S/k_B", "全体比", "備考"))
for n, s, m in budget:
    print("  %-28s %-12.2e %-10.2e %s" % (n, s, s / tot, m))
print("  合計 %.2e k_B = %.2e ビット" % (tot, tot / ln2))
print("")
print("  ★ **すでに 99.999... パーセントが重力のエントロピー**（地平面のエントロピー）。")
nonbh = tot - budget[0][1] - budget[1][1]
print("     BH 以外を全部足しても %.2e ── BH より %.1f ビット（%.0f 桁）低い。" %
      (nonbh, math.log2(tot / nonbh), math.log10(tot / nonbh)))

print("")
print("=== ⑤ 使っている容量は、どれくらいか ===")
print("  実際 %.2e nat  対  上限 %.2e nat" % (tot, S_holo))
print("  比 = %.2e  → 上限の **1/%.1e** しか使っていない" % (tot / S_holo, S_holo / tot))
print("  ビットで言えば **%.1f ビットぶんの余白**（＝ %.0f 回の倍化ぶん）" %
      (math.log2(S_holo / tot), math.log2(S_holo / tot)))
print("")
print("  倍化のはしごで見る（log₂ S）：")
S_rec = budget[2][1] + budget[3][1]
for lab, s in [("再結合のころ（CMB＋ニュートリノ）", S_rec),
               ("いま（合計）", tot),
               ("上限（ホログラフィック）", S_holo)]:
    print("    %-34s S = %-12.2e log₂S = %.1f" % (lab, s, math.log2(s)))
print("    → 初期からいままで %.1f 倍化、いまから上限まで %.1f 倍化。" %
      (math.log2(tot / S_rec), math.log2(S_holo / tot)))
print("  ★ **宇宙は、行程の半分も進んでいない。**")

print("")
print("=== ⑥ 余白の正体 ── 重力の自由度は熱平衡にいない ===")
print("  ⑤の余白は『まだ使っていない容量』だが、なぜ使われないのか。")
print("  → 重力は引力しかないので、熱平衡が最大エントロピーの状態ではない。")
print("     一様な気体は最大エントロピー。**一様な重力場は最小エントロピー**。")
print("  ★ だから『重力場そのもののエントロピー』を別に測る必要がある。")
print("     その候補が、第39回で出てきた**ワイル曲率**。")

print("")
print("=== ⑦ ペンローズの候補と、その弱点 ===")
print("  ペンローズの提案： 重力エントロピーの目安は ワイル²/リッチ²")
print("    ・FLRW：ワイル = 0 ちょうど → **比は 0**（初期宇宙の重力エントロピーはゼロ）")
print("    ・凸凹した宇宙：ワイルが育つ → 比が上がる")
print("  ところが真空解では リッチ = 0 なので、**比が発散する**：")
K_h = 12.0
print("    シュヴァルツシルト：リッチ = 0、ワイル² = クレッチマン K = 48(GM/c²)²/r⁶")
print("    地平面 r = r_s では  K·r_s⁴ = %.0f  ← **有限で、しかも無次元**" % K_h)
for name, Msol in [("太陽質量 BH", 1.0), ("M87* (6.5e9 M☉)", 6.5e9)]:
    Mkg = Msol * 1.98892e30
    rs_ = 2 * G * Mkg / c ** 2
    K = 48 * (G * Mkg / c ** 2) ** 2 / rs_ ** 6
    print("      %-22s r_s = %-12.3e m   K = %.3e m⁻⁴   K·r_s⁴ = %.1f" %
          (name, rs_, K, K * rs_ ** 4))
print("  ★ **ワイルの側は有限で無次元。壊れているのは『リッチで割る』ところ**。")
print("     → 比を取る形は宇宙論では使えるが、真空では使えない。")
print("     Clifton–Ellis–Tavakol (2013) など、別の定義が提案されている。")

print("")
