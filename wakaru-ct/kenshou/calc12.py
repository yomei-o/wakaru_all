# 第7回：重力に入れてみる ── G は 1450 倍速く変わるのに、誰も気づけない
import math
c=299792458.0; hbar=1.054571817e-34; G=6.67430e-11; kB=1.380649e-23
e=1.602176634e-19; eps0=8.8541878128e-12
me=9.1093837015e-31; mp=1.67262192369e-27
mP=math.sqrt(hbar*c/G); lP=math.sqrt(hbar*G/c**3); tP=lP/c
t0=4.3536e17; yr=3.1557e7; H0=1/t0
Msun=1.98892e30

def sec(t): print("\n"+"="*64+"\n"+t+"\n"+"="*64)

sec("① G のウェイト")
print("  α_G = G m²/(ħc) は無次元 → 不変。 m→am なので  G → G/a²")
print(f"    この絵での Ġ/G = -2/t = {-2*H0*yr:.4e} /年")
llr=1e-13
print(f"    月レーザー測距の上限 |Ġ/G| < {llr:.0e} /年  →  上限の {2*H0*yr/llr:.0f} 倍")
print("  それでも観測にかからない。無次元の α_G が動かないから。")
for n,m in [("ニュートリノ(0.05eV)",0.05*e/c**2),("電子",me),("陽子",mp),("プランク質量",mP)]:
    print(f"    α_G({n:16s}) = {(m/mP)**2:.3e}   ← 不変")

sec("② ディラックの大数 ── 本当に G を変えてみる")
N1 = e*e/(4*math.pi*eps0*G*mp*me)         # 電気力/重力（水素）
re = e*e/(4*math.pi*eps0*me*c*c)          # 古典電子半径
N2 = t0/(re/c)                            # 宇宙年齢 ÷ 古典電子時間
print(f"  N₁ = e²/(4πε₀ G m_p m_e) = {N1:.3e}")
print(f"  r_e = {re:.4e} m,  r_e/c = {re/c:.4e} s")
print(f"  N₂ = t₀/(r_e/c)          = {N2:.3e}")
print(f"  比 N₂/N₁ = {N2/N1:.1f}   ← ディラックが『一致』と呼んだもの（1937）")
print()
print("  ディラックの推論：N₂ は t に比例して増える。ならば N₁ も増えねばならない → G ∝ 1/t")
print("  ところが、この絵で実際に G を変えてみると：")
print("    N₁ の分母 = (G/a²)·(a m_p)·(a m_e) = G m_p m_e   → 不変")
print("    N₂ = t̃/(r̃_e/c) = (t/a)/((r_e/a)/c)              → 不変")
print("  → 両方とも動かない。大数の一致は、良くも悪くもならない。")
print("  ★ G だけを動かすことはできない（動かせば VSL と同じ誤り）。")
print("    ちゃんと共形変換にすると、ディラックの処方は空回りする。")

sec("③ 重力の量を、片っ端から変換する")
rows=[("ニュートン定数 G","+2 相当","÷a²"),
      ("重力加速度 g=GM/r²","−1","×a"),
      ("シュヴァルツシルト半径 2GM/c²","+1","÷a"),
      ("ホーキング温度 ħc³/8πGMk_B","−1","×a"),
      ("BH エントロピー A/4ℓ_P²","0（無次元）","不変"),
      ("重力波のひずみ h","0（無次元）","不変"),
      ("ケプラー第三法則 T²=4π²r³/GM","恒等的に成立","形も不変"),
      ("α_G=(m/M_Pl)²","0","不変"),
      ("潮汐（測地線偏差）Δa/Δx","−2","×a²")]
print(f"  {'量':30s} {'ウェイト':>12}  {'この絵で'}")
for a_,b_,c_ in rows: print(f"  {a_:30s} {b_:>12}  {c_}")

sec("④ ケプラーが形を保つことの検算")
print("  T²=4π²r³/(GM) の両辺を変換：")
print("    左辺 T̃² = T²/a²")
print("    右辺 = 4π²(r/a)³ / ((G/a²)(aM)) = 4π²r³/(GM) · (1/a³)·(a²/a) = 4π²r³/(GM)/a²")
print("  → 両辺とも 1/a²。恒等的に成立し、軌道は相似に縮むだけ")

sec("⑤ BH エントロピーが不変であることの意味")
M=1e6*Msun
rs=2*G*M/c**2; A=4*math.pi*rs**2; S=A/(4*lP**2)
print(f"  10⁶ 太陽質量の BH: r_s={rs:.3e} m, A={A:.3e} m², S/k_B={S:.3e}")
print("  A はウェイト +2、ℓ_P² もウェイト +2 → 比は不変")
print("  → 第6回の『使われているメモリ』は、この絵でも一切動かない。")
print("     共形変換が触れるのは、空いている側だけ。")

sec("⑥ 一行")
print("  次元付きの G は、この絵で観測上限の 1450 倍速く変化する。")
print("  それでも、無次元の α_G も、ディラックの大数も、BH エントロピーも、重力波の h も、")
print("  ひとつとして動かない。── だから誰も気づけない。")
