# -*- coding: utf-8 -*-
# 第35回：漸近安全性と、走る G
import math

lP = 1.616255e-35
hbarc = 1.973269804e-16     # ħc [GeV·m]
Epl = 1.220890e19           # プランクエネルギー [GeV]

def k_inv_m(E_GeV):
    """エネルギー[GeV] を 逆長さ[1/m] に直す"""
    return E_GeV / hbarc

def g_of(E_GeV):
    """無次元化したニュートン結合 g = G k² = ℓ_P² k²"""
    k = k_inv_m(E_GeV)
    return (lP * k) ** 2

print("=== ① G を無次元にする ===")
print("  4 次元では [G] = 長さ²（ħ=c=1 で G = ℓ_P²）── 次元付き＝帳簿（第7回）")
print("  スケール k と組んで無次元にする：")
print("    g(k) = G k² = (ℓ_P k)²   ← これが**物理の側**（第16回の地図でウェイト 0）")
print("  ★ このシリーズの判定手続きを、重力の結合そのものに当てたのが漸近安全性。")

print("")
print("=== ② 実際に走らせてみる ===")
scales = [
    ("実験室（1 m⁻¹）", hbarc),                 # k = 1/m
    ("原子（1 keV）", 1e-6),
    ("陽子（1 GeV）", 1.0),
    ("LHC（10 TeV）", 1e4),
    ("大統一（10¹⁶ GeV）", 1e16),
    ("プランク（1.22×10¹⁹ GeV）", Epl),
]
print("  %-26s %-14s %s" % ("スケール", "k [1/m]", "g = (ℓ_P k)²"))
for n, E in scales:
    print("  %-26s %-14.3e %.3e" % (n, k_inv_m(E), g_of(E)))
gl, gh = g_of(1.0), g_of(Epl)
dec_g = math.log10(gh / gl)
dec_E = math.log10(Epl / 1.0)
print("  1 GeV → プランクで g は %.1f 桁、エネルギーは %.1f 桁" % (dec_g, dec_E))
print("  傾き = %.2f ── **ちょうど 2**（g = Gk² の古典次元そのもの）" % (dec_g / dec_E))
print("  → プランク以下では**ウェイト表がぴったり正しい**（異常次元ゼロ）。")

print("")
print("=== ③ 紫外で固定点に落ち着く ===")
print("  漸近安全性の主張：β_g = 2g − b g² が g* = 2/b ≠ 0 で消える（非ガウス固定点）")
gstar, lstar = 0.707, 0.193
print("  ロイター系の代表値： g* ≈ %.2f、λ* ≈ %.2f（**切り捨て・スキーム依存**）" % (gstar, lstar))
print("  → g がここで止まるので、G(k) ∝ 1/k² となり、**重力は紫外で弱くなる**。")
E_star = math.sqrt(gstar) / lP * hbarc
print("  g = g* に達するエネルギー = √g*/ℓ_P = %.3e GeV = %.2f × E_Pl" %
      (E_star, E_star / Epl))

print("")
print("=== ④ 固定点での異常次元 ── ウェイト表が 100% 外れる ===")
print("  g = G k² が定数になるには、G の走りが k^(−2) でなければならない。")
print("  つまりニュートン結合の異常次元は  η_N = −2 ちょうど。")
print("")
print("  第14回で測った『ウェイト表の誤差』と並べる：")
rows = [
    ("3 次元イジングのスピン演算子", 0.5, 0.0181489),
    ("重力の結合（固定点）", 2.0, 2.0),
]
print("  %-30s %-12s %-12s %s" % ("演算子", "古典次元", "異常次元", "誤差の割合"))
for n, cl, an in rows:
    print("  %-30s %-12.4f %-12.4f %.1f%%" % (n, cl, an, 100 * an / cl))
print("  ★ イジングは 3.6 パーセント、重力の固定点は **100 パーセント**。")
print("     第14回で『帳簿の数字に誤差棒が付く』と書いたが、重力では")
print("     **古典次元が丸ごと打ち消される** ── 誤差棒どころではない。")

print("")
print("=== ⑤ 何を買うのか ── 予言の個数 ===")
print("  漸近安全性の売りは『紫外臨界面の次元 ＝ 自由パラメータの個数』が有限なこと。")
print("  切り捨て計算では relevant な方向は **2〜3 個**（切り捨ての取り方で変わる）。")
print("  → もし 3 個なら、紫外の物理は 3 個で決まる。")
bic = 0.5 * math.log2(1701)
print("  第5回の値段で言えば、3 個 = %.1f ビット。" % (3 * bic))
print("  ※ ただし『個数が切り捨て依存で定まらない』こと自体が、この理論の弱点。")

print("")
print("=== ⑥ 実際に当たった予言 ── ヒッグス質量 ===")
mH_pred, mH_obs, mH_err = 126.0, 125.25, 0.17
print("  Shaposhnikov & Wetterich (2010)：漸近安全性から m_H ≈ %.0f GeV と予言" % mH_pred)
print("  実測（2012 発見、現在）：m_H = %.2f ± %.2f GeV" % (mH_obs, mH_err))
print("  ずれ %.2f GeV（%.1f%%）" % (abs(mH_pred - mH_obs), 100 * abs(mH_pred - mH_obs) / mH_obs))
print("")
print("  第19回の手続きで驚きを測る：")
for prior, hit, lab in [(70.0, 3.0, "当時の LEP+精密電弱が示唆した幅 90〜160 GeV"),
                        (200.0, 3.0, "もっと広く 100〜300 GeV と取る場合")]:
    s = -math.log2(hit / prior)
    print("    事前範囲 %.0f GeV、命中幅 %.0f GeV → 驚き %.1f ビット   （%s）" % (prior, hit, s, lab))
print("  → 4〜6 ビット。第19回の目盛りでは【偶然】の帯だが、")
print("     **説明（固定点条件）がある**ので、当たっていれば【物理】へ移る。")
print("  ※ この予言は物質セクターについての仮定に依存し、頑健性には議論がある。")

print("")
