print("=== ⑤ 誕生日会で、番外編④の look-elsewhere をやる ===")
n = 23
pairs = n * (n - 1) // 2
p_naive = 1.0 / 365
# 実際に一致が起きる確率
p_none = 1.0
for k in range(n):
    p_none *= (365 - k) / 365.0
p_any = 1 - p_none
print("  23 人の部屋で、誕生日が一致する二人が見つかった。")
print("    素朴な驚き：−log₂(1/365) = **%.2f ビット**" % (-math.log2(p_naive)))
print("    ところが組は %d 通りある → 探索の値段 log₂(%d) = **%.2f ビット**" %
      (pairs, pairs, math.log2(pairs)))
print("    引くと %.2f − %.2f = **%.2f ビット**" %
      (-math.log2(p_naive), math.log2(pairs), -math.log2(p_naive) - math.log2(pairs)))
print("    実際に一致が起きる確率 = %.3f → 驚き **%.2f ビット**" % (p_any, -math.log2(p_any)))
print("  ★ **ほぼ一致する。** 引き算が正しかったことの確認。")
print("  ★ そして『先に一人を指名してからその人と一致した』なら、探索空間は 1 ──")
print("     **%.2f ビットまるごと残る**。" % (-math.log2(p_naive)))
print("     ── **これが『4.1 ビットの予言が 15.7 ビットの発見に勝つ』の全部。**")

