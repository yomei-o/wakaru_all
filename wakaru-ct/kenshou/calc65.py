print("=== ③ 複利で、番外編②の圧縮則をやる ===")
ratio = 1e40
H = math.log(ratio)
B = math.log2(ratio)
cost = math.log2(B)
print("  『元手の 10⁴⁰ 倍にしたい』── 複利なら rt = ln(10⁴⁰) = %.1f" % H)
print("  比を 2 倍以内に決めたいなら、rt の相対精度は ln2/%.1f = 1/%.1f" % (H, B))
print("  → rt に要る精度 = log₂(%.1f) = **%.2f ビット**" % (B, cost))
print("  ★ **%.1f ビットの階層が、%.2f ビットで買える**（圧縮 %.1f 倍）。" % (B, cost, B / cost))
print("     ── 番外編②の B → log₂B。**次元転移も QCD も要らない。**")

