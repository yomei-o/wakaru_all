print("=== ② 銀行口座で、階層性問題をやる ===")
print("  口座A：複利　dM/dt = rM　（乗法的）")
print("  口座B：毎月定額の入金　dM/dt = c　（加法的）")
print("  どちらも残高は 1,000 円。銀行全体の資産は 10¹² 円。")
print("  問い：**『なぜ 10¹² ではなく 10³ なのか』**")
print("")
lo_dec, hi_dec = 0.0, 12.0        # 1 円 〜 10¹² 円
obs_dec = 3.0                     # 1,000 円
win_dec = 0.301                   # 「2 倍以内」の窓
b_log = math.log2((hi_dec - lo_dec) / win_dec)
b_lin = math.log2(10 ** hi_dec / 10 ** obs_dec)
print("  口座A（複利 → 不変測度は dM/M ＝ 対数一様）：")
print("    12 桁のうち 0.3 桁の窓 → 驚き = **%.1f ビット**  ── どの桁も同じくらいありそう" % b_log)
print("  口座B（定額 → 不変測度は dM ＝ 線形）：")
print("    10¹² のうち 10³ → 驚き = **%.1f ビット**  ── **とても不自然**" % b_lin)
print("")
print("  ★ **同じ残高なのに、判定が %.1f ビット違う。**" % (b_lin - b_log))
print("     違いは金額ではなく、**増え方（β の形）**だけ。")
print("  ★ これが階層性問題の全部。素粒子論は一文字も出ていない。")

