# -*- coding: utf-8 -*-
# 第38回：共形因子問題 ── 符号が逆の運動項
import math

lP = 1.616255e-35
RH = 1.3e26              # ハッブル半径 [m]（第2回と同じ値）

print("=== ① 共形因子を取り出すと、運動項が出てくる ===")
print("  g = Ω² ĝ と書いて、アインシュタイン・ヒルベルト作用を書き直す：")
print("    √g R[g] = √ĝ Ω^(D−2) ( R̂ − 2(D−1)□̂ lnΩ − (D−1)(D−2)(∂lnΩ)² )")
print("  部分積分でまとめると、Ω の運動項の係数は")
print("    (D−1)(D−2)   ── **符号が、普通のスカラー場と逆**")
print("")
print("  %-8s %-14s %s" % ("D", "(D−1)(D−2)", "意味"))
for D in (1, 2, 3, 4, 5, 6, 10):
    c = (D - 1) * (D - 2)
    if D == 2:
        m = "ちょうどゼロ ── 2 次元では共形因子に運動項が無い"
    elif D == 1:
        m = "ちょうどゼロ"
    elif D == 4:
        m = "**私たちの次元**：係数 6"
    else:
        m = ""
    print("  %-8d %-14d %s" % (D, c, m))
print("  ★ D=4 では 6。**ゼロにできる次元は D=1 と D=2 だけ**。")

print("")
print("=== ② 共形因子は『符号が逆の、共形結合スカラー』だった ===")
print("  共形結合スカラーの結合定数 ξ = (D−2) / (4(D−1))：")
print("  %-8s %-12s %s" % ("D", "ξ", ""))
for D in (3, 4, 5, 6, 10, 100):
    xi = (D - 2) / (4.0 * (D - 1))
    tag = "**私たちの次元：1/6 = 0.1667**" if D == 4 else ("D→∞ で 1/4 に近づく" if D == 100 else "")
    print("  %-8d %-12.4f %s" % (D, xi, tag))
print("  ★ Ω を場と見ると、アインシュタイン作用は")
print("     **共形結合スカラーの作用に、全体のマイナスを掛けたもの**になっている。")
print("     → だから運動項の符号が逆。これが**共形因子問題**（Gibbons–Hawking–Perry 1978）。")

print("")
print("=== ③ どれくらい悪いのか ── 皺を細かくするだけで発散する ===")
print("  平坦な 4 次元トーラス（一辺 L、プランク単位）に")
print("    Ω = a sin(2πn x / L)     の皺を入れる。")
print("  ユークリッド作用は  |S| = (6/16π) · a² (2πn/L)² · L⁴/2 = 2.357 a² n² L²")
print("  重み e^(−S) = e^(+|S|) をビットで測ると |S|/ln2：")
L, a = 10.0, 0.1
print("  （L = %.0f ℓ_P、a = %.2f）" % (L, a))
print("  %-8s %-16s %s" % ("n（皺の数）", "|S|", "重み [bit]"))
for n in (1, 2, 5, 10, 20, 50):
    S = 6.0 / (16 * math.pi) * a * a * (2 * math.pi * n / L) ** 2 * L ** 4 / 2
    print("  %-8d %-16.2f %.1f" % (n, S, S / math.log(2)))
print("  ★ **n² で伸び続け、上限が無い。** 皺を細かくするだけで")
print("     経路積分の重みがいくらでも大きくなる ── **e^(−S) が発散する**。")
print("  ※ これは**古典的な不安定性ではない**。古典の一般相対論では共形モードは")
print("     ハミルトニアン拘束で決まってしまい、伝播する自由度ではない。")
print("     壊れているのは**ユークリッド経路積分の定義**であって、天体の安定性ではない。")

print("")
print("=== ④ 発散する方向は、いくつあるか ===")
ncell = (RH / lP) ** 3
print("  ハッブル半径のなかのプランク体積の個数：")
print("    (R_H/ℓ_P)³ = (%.2e)³ = %.2e" % (RH / lP, ncell))
print("  共形因子は各点に 1 個の自由度を持つので、")
print("  → **%.1e 個の方向すべてで、作用が下に非有界**。" % ncell)
print("  対数で言うと %.0f ビットぶんの方向の数。" % math.log2(ncell))
print("  ★ 第24回で数えた『宇宙が処理してきた情報』3e122 ビットと同じ通貨だが、")
print("     こちらは**情報ではなく、壊れている方向の個数**。")

print("")
print("=== ⑤ 直し方 ── 積分路を回す ===")
print("  Gibbons–Hawking–Perry の処方：共形因子だけ Ω → iΩ と積分路を回す。")
print("    → 符号が戻り、ガウス積分が収束する。1 ループでは実際にうまくいく。")
print("  第5回の天秤で言えば：")
print("    払うもの ── 『共形因子だけ別扱いする』という規則を手で 1 個足す")
print("    買うもの ── ユークリッド経路積分が定義できる")
print("  ★ ただし**第一原理からの導出は無い**。「そうすると合う」という処方。")
print("     これは第32回のコスモンや第29回の MOND と同じ形の帳簿 ──")
print("     **手で足した規則は、必ず値段が付く**。")

print("")
print("=== ⑥ ゴーストの置き場所 ── 第34回との取引 ===")
tab = [
    ("アインシュタイン重力", "健全（スピン 2 は正しい符号）", "**ゴースト**（符号が逆）", "積分路を回す"),
    ("共形重力（第34回）", "**ゴースト**（4 階微分のスピン 2）", "ゲージで消える", "未解決"),
]
print("  %-22s %-30s %-24s %s" % ("理論", "スピン 2", "共形因子", "処方"))
for a_, b, c, d in tab:
    print("  %-22s %-30s %-24s %s" % (a_, b, c, d))
print("")
print("  ★ **ゴーストを共形因子に置くか、スピン 2 に置くかの取引だった。**")
print("     どちらにも置かない選択肢は、まだ見つかっていない。")
print("     ── 第 V 部の主題そのもの：道具が壊れる場所は、消えずに移動する。")

print("")
print("=== ⑦ D=2 だけは別 ── 第37回とつながる ===")
print("  ①の表のとおり、D=2 では (D−1)(D−2) = 0 ── 共形因子に運動項が無い。")
print("  ではなぜ 2 次元重力に共形因子の運動項（リウヴィル作用）が現れるのか。")
print("  → **アノマリーから出てくる**（第37回）。古典ではゼロ、量子で生える。")
print("  ★ 第37回：量子が『0 の列』に数字を書き込んだ。")
print("     ここでも同じことが起きている ── **2 次元では、運動項そのものが量子起源**。")

print("")
print("=== ⑧ 第39回への引き継ぎ ===")
print("  第37回：量子が D=4 から出ると、破れが出る。")
print("  第38回：共形因子の運動項は符号が逆で、ユークリッド経路積分が壊れる。")
