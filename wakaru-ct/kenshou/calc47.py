print("     （破らない定式化もある）。この制限が効くのは破る形のものだけ。")

print("")
print("=== ⑥ 第18回の 1.96 fm との関係 ===")
RH18 = 1.3e26   # 第18回が使ったハッブル半径
L18 = (math.log(2) / math.pi * RH18 * lP ** 2) ** (1.0 / 3.0)
print("  第18回：1 ビットに対応する長さ = (ln2/π · R_H · ℓ_P²)^(1/3) = %.3e m = %.2f fm" %
      (L18, L18 * 1e15))
