# 第43回：プランクスケール ── 最小の長さは、ウェイト表のどこにいるか
import math

G = 6.67430e-11
c = 2.99792458e8
hbar = 1.054571817e-34
lP = 1.616255e-35
tP = 5.391247e-44
mP = 2.176434e-8
EP = 1.220890e19          # GeV
hbarc = 1.973269804e-16   # GeV·m
RH = 1.3725e26
t0 = 13.79e9 * 3.1557e7

print("=== ① プランク長は、ウェイト表のどこにいるか ===")
print("  ℓ_P = √(ħG/c³)。ħ と c はウェイト 0、G はウェイト +2（第35回①）。")
print("  → ℓ_P のウェイト = (+2)/2 = **+1**  ── ただの長さ。")
rows = [
    ("ℓ_P = 1.616e-35 m", "+1", "長さ ＝ 帳簿"),
    ("t_P = 5.391e-44 s", "+1", "時間 ＝ 帳簿"),
    ("m_P = 2.176e-8 kg", "−1", "質量 ＝ 帳簿"),
    ("E_P = 1.221e19 GeV", "−1", "エネルギー ＝ 帳簿"),
    ("L / ℓ_P（長さの比）", "**0**", "**無次元 ＝ 物理**"),
]
print("  %-26s %-10s %s" % ("量", "ウェイト", "分類"))
for a, b, d in rows:
    print("  %-26s %-10s %s" % (a, b, d))
print("  ★ **プランク量はどれも帳簿の列にいる**。物理の列にいるのは比だけ。")
print("     → 『最小の長さは ℓ_P』は、そのままでは第3回の意味で**まだ文になっていない**。")
print("       文にするなら **L/ℓ_P ≥ 1**。")

print("")
print("=== ② ところが、ここで道具が本当に壊れる ===")
print("  問題は『G は共形変換で動くのか』── 第36回の (A)/(B) が、G に当たる。")
read = [
    ("(A) G も動く（G → Ω²G）", "ℓ_P も一緒に動く", "L/ℓ_P はウェイト 0", "最小長は保たれる → **記法**"),
    ("(B) G は固定", "ℓ_P は動かない", "L/ℓ_P はウェイト +1", "**最小長を割り込ませられる** → 主張"),
]
print("  %-24s %-20s %-20s %s" % ("読み方", "ℓ_P", "L/ℓ_P", "帰結"))
for a, b, c_, d in read:
    print("  %-24s %-20s %-20s %s" % (a, b, c_, d))
print("")
print("  ★ **『最小の長さがある』理論は、そもそも共形不変ではありえない。**")
print("     共形不変性はスケールが無いことを要求し、最小長はスケールそのものだから。")
print("     第 V 部でここまで『壊れる／届かない』を見てきたが、ここは違う ──")
print("     **仮定からして排除されている**。道具の効く範囲の、はっきりした端。")

print("")
print("=== ③ では、プランクスケールとは結局何か ===")
print("  指させる長さではなく、**指させる二つの長さの比が 1 になる場所**：")
print("    コンプトン波長      λ_C = ħ/(mc)      （量子の広がり）")
print("    シュヴァルツシルト半径 r_s = 2Gm/c²     （重力の広がり）")
m_star = math.sqrt(hbar * c / (2 * G))
l_star = hbar / (m_star * c)
print("  等しくなるのは m = √(ħc/2G) = %.4e kg = m_P/√2 = %.4f m_P" % (m_star, m_star / mP))
print("  そのときの長さ = %.4e m = %.4f ℓ_P" % (l_star, l_star / lP))
print("  ★ **交点は無次元の言明**。だからプランクスケールという概念は生き残る ──")
print("     『長さ』としてではなく、**『二つの効果が並ぶ場所』**として。")
print("")
print("  %-14s %-16s %-16s %s" % ("質量 [kg]", "λ_C [m]", "r_s [m]", "λ_C / r_s"))
for m in (9.109e-31, 1.673e-27, 1e-15, m_star, 1e-3, 1.0):
    lc = hbar / (m * c)
    rs = 2 * G * m / c ** 2
    print("  %-14.3e %-16.3e %-16.3e %.3e" % (m, lc, rs, lc / rs))

print("")
print("=== ④ 私たちは、そこからどれだけ遠いか ===")
E_lhc = 13600.0    # GeV
L_lhc = hbarc / E_lhc
print("  LHC の重心系エネルギー %.0f GeV → 見えている長さ ħc/E = %.3e m" % (E_lhc, L_lhc))
print("  ℓ_P までの比 = %.2e  → **%.1f 桁 ＝ %.1f 倍化**" %
      (L_lhc / lP, math.log10(L_lhc / lP), math.log2(L_lhc / lP)))
print("  ★ **50 回の倍化ぶん遠い。** 加速器のエネルギーを 2 倍にするたびに 1 歩。")
print("")
print("  宇宙全体の対数の幅（第2回の目盛りと同じ）：")
print("    ln(R_H/ℓ_P) = %.2f、  ln(t₀/t_P) = %.2f  ← ほぼ同じ値" %
      (math.log(RH / lP), math.log(t0 / tP)))
print("    → 第2回の『140.24 対数ステップ』は、**空間で数えても同じ**。")
print("  1 次元の位置をプランク精度で指定するのに要るビット数：")
print("    log₂(R_H/ℓ_P) = %.1f ビット" % math.log2(RH / lP))
print("  3 次元なら %.0f ビット（第38回④と同じ数）" % (3 * math.log2(RH / lP)))

