print("     ※ R_H = 1.3e26 m（第18回が使った値）で計算。1.3725e26 なら 1.99 fm。")
print("     → 『1 ビットの長さ』は、プランク長から **%.0f 倍化ぶん上**にある。" %
      math.log2(L18 / lP))

