# -*- coding: utf-8 -*-
# 第11回：光に入れてみる ── 光子ガスは完全に静止している
import math
c=299792458.0; hbar=1.054571817e-34; kB=1.380649e-23; eV=1.602176634e-19
t0=4.3536e17; T0=2.7255; RH=c*t0
n_g=4.1105e8            # /m^3  （CMB 光子数密度）
s_g=1.4784e9            # k_B/m^3（CMB エントロピー密度）
eta=6.10e-10            # バリオン光子比
print("=== この絵での光子ガス ===")
for q,w,res in [("数密度 n","+3 →×a³","一定"),("エネルギー密度 ρ","−4 →×a⁴","一定"),
                ("温度 T","−1 →×a","一定"),("光子1個のエネルギー ħω","−1 →×a","一定"),
                ("波長 λ","+1 →÷a","一定（÷a と ×a が相殺しない：λ は +1 なので ÷a）")]:
    print(f"  {q:22s} ウェイト {w:12s} → {res}")
print("\n  ※ 標準の絵では n∝a⁻³, ρ∝a⁻⁴, T∝a⁻¹。掛け合わせると全部ぴったり一定になる。")
print(f"  今日の光子数密度 {n_g:.4e} /m³ が、宇宙の全歴史で不変")

print("\n=== 光子ガスを決める無次元数は二つだけ ===")
print(f"  光子1個あたりのエントロピー s/n = {s_g/n_g:.4f} k_B   （黒体の 3.602 と一致）")
print(f"  バリオン光子比 η = {eta:.3e}")
print("  → どちらも無次元。この絵でも標準の絵でも、同じ値。")

print("\n=== ハッブル体積の中の光子の数 ===")
V=4*math.pi/3*RH**3
Ng=n_g*V; Sg=s_g*V
print(f"  V = {V:.4e} m³,  光子数 = {Ng:.4e} 個,  エントロピー = {Sg:.4e} k_B")
print(f"  （Egan & Lineweaver 2010 の 2.03e88 は、やや大きい共動体積を使った値。比 {2.03e88/Sg:.2f}）")

print("\n=== 赤方偏移を、二つの絵で書く ===")
for z in [1,7,1100]:
    print(f"  z={z:5d}: 標準『波長が {1+z} 倍に伸びた』 ／ この絵『実験室の基準が {1+z} 倍細かくなった』"
          f"  → 観測される比はどちらも {1+z}")

print("\n=== マクスウェル作用の数え上げ（前シリーズ第7回） ===")
print("  S = -(1/4μ₀)∫√-g F_{μν}F_{αβ} g^{μα} g^{νβ} d^D x")
for D in [2,3,4,5,6]:
    print(f"    D={D}: √-g が Ω を {D} 個産み、逆計量2つが 4 個食う → Ω^{D-4}"
          + ("   ← ぴったり共形不変" if D==4 else ""))

print("\n=== 光には、物差しも時計もない ===")
print("  コンプトン波長 ħ/mc → m→0 で ∞：どんな長さも指定しない")
print("  光の世界線に沿った固有時間 = 0：どんな時間も指定しない")
print("  → 物差しを取り替えられても、比べる相手がないので気づけない")

print("\n=== ただし量子では壊れる（第V部への伏線） ===")
print("  量子化には細かさの基準 μ が要る → トレースアノマリー T^μ_μ=(β/2g)F²")
print("  1/137 → 1/128 は、その破れを実験で測っている（前シリーズ第8回）")
