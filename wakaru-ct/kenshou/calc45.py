# -*- coding: utf-8 -*-
# 第41回：ワイル曲率仮説 ── 10^(10^123) の正体
import math

ln2 = math.log(2)
ln10 = math.log(10)
bic = 0.5 * math.log2(1701)          # 第5回：パラメータ 1 個の値段

S_max = 2.265e122        # 第40回③：ホログラフィック限界 [k_B]
S_now = 3.10e104         # 第40回④：いまの合計 [k_B]
S_init = 3.96e89         # 第40回⑤：再結合のころ [k_B]

print("=== ① ワイル曲率仮説とは何か ===")
print("  ペンローズ (1979)：**初期特異点ではワイル曲率 C = 0**、")
print("                      終期特異点（ブラックホール）では制限しない。")
print("  → 初期と終期を**非対称に**する法則。これが時間の矢の起源だ、という主張。")
print("")
print("  4 次元でのリーマン曲率の独立成分は 20 個：")
print("    リッチ 10 個（物質が決める、アインシュタイン方程式）")
print("    ワイル 10 個（自由。重力波・潮汐力はここ）")
print("  ★ ワイル仮説は、**初期面で曲率の自由度のちょうど半分を落とす**要請。")

print("")
print("=== ② なぜ要請が要るのか ── 第40回の余白を、確率に直す ===")
print("  第40回：初期 %.2e、いま %.2e、上限 %.2e（すべて k_B）" % (S_init, S_now, S_max))
print("  統計力学：位相空間の体積比 = exp(ΔS/k_B)")
vol_log10 = S_max / ln10
print("  上限の状態と初期の状態の体積比 ≈ exp(%.3e) = 10^(%.3e)" % (S_max, vol_log10))
print("  → **『10 の 10 の 122 乗 分の 1』を引き当てたことになる**。")
print("  ※ ペンローズは 10^(10^123) と書いている ── S_max の見積もりが少し大きいだけで、")
print("     同じ数の同じ話。")

print("")
print("=== ③ その『途方もない数』を、ビットで測る ===")
bits = S_max / ln2
print("  驚き = −log₂(体積比の逆数) = S_max / ln2 = **%.3e ビット**" % bits)
print("")
print("  ここまでに出てきた 10¹²² を並べる：")
tab = [
    ("第24回：宇宙が処理してきた情報 N = C·t₀", 3.107e122),
    ("第40回：ホログラフィック限界（ビット）", S_max / ln2),
    ("第40回：全質量を 1 個の BH にしたときの S（ビット）", S_max / ln2),
    ("第41回：初期状態の特別さ（ビット）", bits),
]
for n, v in tab:
    print("    %-46s %.3e bit" % (n, v))
print("  ★ **四つとも同じ数**。ペンローズの 10^(10^123) は、")
print("     このシリーズの通貨では **3.3×10¹²² ビット** ── 見慣れた数だった。")
print("     第26回・第40回に続いて、**圧縮がまた効いた**。")

print("")
print("=== ④ 帳簿 ── これはシリーズ最良の取引か ===")
led = [
    ("インフレーション（第27回）", 2 * bic, "地平線・平坦性・n_s", "−6.5 と評価"),
    ("コスモン（第32回）", 2 * bic, "ρ_Λ の大きさ", "最大 408 bit"),
    ("MOND（第29回）", 4 * bic, "回転曲線", "+1971 bit（赤字）"),
    ("**ワイル曲率仮説**", 1 * bic, "初期状態の特別さ", "**%.2e bit**" % bits),
]
print("  %-28s %-14s %-22s %s" % ("理論", "払う [bit]", "買うもの", "買った量"))
for n, p, b, g in led:
    print("  %-28s %-14.2f %-22s %s" % (n, p, b, g))
print("")
print("  ワイル仮説：%.2f ビット払って %.2e ビット買う → 比 %.1e" % (bic, bits, bits / bic))
print("  ★ **帳簿の上では、このシリーズで見たどの理論よりも桁違いに良い取引**。")
print("  ※ ただし『法則 1 個 = パラメータ 1 個 = 5.37 ビット』という値付けは")
print("     第5回の便宜であって、境界条件と力学法則を同じ値段にしてよい保証は無い。")
print("     ここが本回のいちばん弱いところ（正直な線②）。")

print("")
print("=== ⑤ 核心 ── 時間の矢は、道具が届く場所から届かない場所へ向かう ===")
print("  第33回の三段判定で、初期と終期を並べる：")
rows = [
    ("初期特異点（ワイル仮説）", "ワイル = 0", "**第 2 段：共形平坦**", "**共形変換が届く**"),
    ("いまの宇宙（大域的には FLRW）", "ワイル ≈ 0", "第 2 段", "ほぼ届く"),
    ("終期（ブラックホール、第39回）", "ワイル ≠ 0", "**第 3 段**", "**届かない**"),
]
print("  %-30s %-14s %-22s %s" % ("時期", "ワイル", "第33回の段", "共形変換"))
for a, b, c_, d in rows:
    print("  %-30s %-14s %-22s %s" % (a, b, c_, d))
print("")
print("  ★ **時間の矢は、共形変換が届く場所から、届かない場所へ向かっている。**")
print("     第 V 部でここまで見てきた『道具が壊れる／届かない』が、")
print("     じつは**時間の向きそのもの**だった。")

print("")
print("=== ⑥ 第31回とのつながり ── 同じ要請を二度見ていた ===")
print("  第31回（CCC）：前の宇宙と次の宇宙を貼り合わせるには、境界で物差しが無いこと。")
print("                  ＝ 境界で共形構造だけが残る ＝ **ワイル = 0 の要請**。")
print("  → 第31回と第41回は、**同じ要請を別の目的で使っている**。")
print("     CCC は『続きがある』ために、ワイル仮説は『初期が特別』を説明するために。")
print("  ★ ペンローズの二つの提案は、根が一つだった。")

print("")
print("=== ⑦ 観測にかかるか ===")
r_bound = 0.036
print("  ワイル曲率＝重力波の自由度。初期にワイル = 0 なら、原始重力波は出ない。")
print("  一方インフレーションはテンソルモード（原始重力波）を予言する。")
print("  現在の上限：r < %.3f（BICEP/Keck 2021, 95%% CL）" % r_bound)
print("  第19回の作法で（事前を r ∈ [0,1] と取れば）： %.1f ビット" % (-math.log2(r_bound)))
print("  ★ いまのところ**原始重力波は見つかっていない** ── ワイル仮説には追い風。")
print("  ※ ただし論理は詰まっていない：ワイル仮説は**特異点そのもの**についての要請で、")
print("     インフレーションはそのあとの段階を扱う。r ≠ 0 が出ても")
print("     ワイル仮説が直ちに否定されるわけではない（正直な線④）。")

print("")
print("=== ⑧ 反論 ── インフレーションでは代わりにならない ===")
print("  『初期が特別なのはインフレーションで説明済みでは？』という反論に対して、")
print("  ペンローズの再反論：**インフレーションを始めるには、それ自体が低エントロピーの")
print("  初期状態を要る**。説明したい当のものを前提にしている。")
print("  → 両者は代替物ではない、というのがペンローズの立場。")
print("  ※ これは決着していない論争で、本稿はどちらも支持しない。")

print("")
