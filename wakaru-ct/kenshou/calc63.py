print("=== ⑤ 五つの場合を、実際に採点する ===")

def bits_linear(x, xmax=1.0):
    return -math.log2(x / xmax)

def bits_log(dec_range, win_dec=0.301):
    return math.log2(dec_range / win_dec)

cases = []

# 1. θ_QCD（β = 0、コンパクト）
th = 1e-10
cases.append(("θ_QCD", "β = 0（走らない）", "コンパクト → Haar 一様",
              -math.log2(th / (2 * math.pi)), "**本物の危機**", "実際、唯一の争いなき問題"))

# 2. 電子質量（β ∝ m、カイラル対称性）
me_v = 0.51099895e-3 / 246.22
cases.append(("m_e / v", "β ∝ m（カイラル対称性）", "対数一様",
              bits_log(8.0), "安い", "実際、誰も微調整と呼ばない"))

# 3. ヒッグス質量（標準模型だけなら β ∝ m²）
v_MP = 246.22 / 1.220890e19
cases.append(("v / M_P（標準模型のみ）", "β ∝ m²（次元正則化）", "対数一様",
              bits_log(40.0), "安い", "**純粋な標準模型では問題ではない**"))

# 4. ヒッグス質量（新物理が M にあれば β に M² が加法的に入る）
cases.append(("v / M_P（新物理あり）", "β ⊃ M²（加法的）", "**線形**",
              bits_linear(v_MP), "**高い**", "**これが階層性問題の正体**"))

# 5. 宇宙定数（β は m⁴ が加法的）
rho = 1.13e-123
cases.append(("ρ_Λ / ρ_P", "β ⊃ m⁴（加法的）", "**線形**",
              bits_linear(rho), "**高い**", "**本物の危機**"))

print("  %-24s %-24s %-16s %-12s %-12s %s" %
      ("量", "β の構造", "誘導測度", "値段[bit]", "判定", "実際の扱われ方"))
for a, b, c, d, e, f in cases:
    print("  %-24s %-24s %-16s %-12.1f %-12s %s" % (a, b, c, d, e, f))

