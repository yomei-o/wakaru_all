print("=== ⑨ 番外編②は、無事か（頑健性の検査）===")
B = 408.4
print("  番外編②：B ビットの階層は log₂B ビットに縮む。α の事前を一様と仮定していた。")
print("  正準な測度（ゲージ結合なら dα/α²）で計算し直す：")
alpha = 1 / 137.035999177
delta = 1.0 / B
frac_uni = delta
frac_rg = delta / (1.0 - alpha)
print("    一様な測度での割合      = δ            = %.4e → %.2f ビット" %
      (frac_uni, -math.log2(frac_uni)))
print("    RG 測度 dα/α² での割合  = δ/(1−α)      = %.4e → %.2f ビット" %
      (frac_rg, -math.log2(frac_rg)))
print("    対数一様（3 桁）での割合                        → %.2f ビット" %
      (-math.log2(delta) + math.log2(math.log(1000.0))))
print("  ★ **一様と RG 測度は 0.01 ビットしか違わない。** 番外編②は頑健。")
