# -*- coding: utf-8 -*-
# 第21回：時間の矢の目盛りは、何本あるか
import math
t0=4.3536e17; tP=5.391247e-44; t_eq=1.6e12
N_steps=math.log(t0/tP)
print(f"宇宙の対数クロック = {N_steps:.2f} ステップ\n")

print("=== これまでに手に入れた『時間の矢の目盛り』===")
rows=[
 ("① 総エントロピー S/k_B", "2.0e88 → 3.1e104", "増える", "第6回", 16.2),
 ("② メモリ使用率 S/S_max", "1 → 1.5e-18", "減る", "第6回", -18.0),
 ("③ ホログラフィック余裕", "0桁 → 33桁", "増える", "第20回", 33.2),
 ("④ 自由度 a（a定理）", "995.5 → 62.0", "減る", "第2回", -math.log10(995.5/62)),
]
print(f"  {'目盛り':26s} {'変化':22s} {'向き':>6}  {'出どころ':>8}  {'桁数'}")
for n,c,d,s,dec in rows:
    print(f"  {n:26s} {c:22s} {d:>6}  {s:>8}  {dec:+7.2f}")

print("\n=== 共形変換で動くか ===")
for n in ["総エントロピー（ビット）","使用率（比）","ホログラフィック余裕（比）","自由度 a（無次元）"]:
    print(f"    {n:28s} 無次元 → 不変 ✓")
print("  → 四本とも『物理』の列。時間の矢は、まるごと不変な側にある。")

print("\n=== 1対数ステップあたりの速さに揃える ===")
print("  ② 使用率：f ∝ t^(1-3p) なので 1ステップあたり |1-3p| nat")
for p,n in [(0.5,"放射期"),(2/3.,"物質期"),(1.0,"c·t=一定")]:
    print(f"      {n:10s} p={p:.3f} → {abs(1-3*p):.3f} nat/ステップ")
a_drop=math.log(995.5/62)
span=132.2-74.1
print(f"  ④ a定理：全 {N_steps:.0f} ステップで割ると {a_drop/N_steps*100:.2f} %/ステップ")
print(f"           実働区間（74→132、{span:.1f} ステップ）なら {a_drop/span:.4f} nat/ステップ = {a_drop/span*100:.2f} %")

print("\n=== なぜ二本は増えて、二本は減るのか ===")
print("  分子（実際に使われた情報）は必ず増える ── 熱力学第二法則")
print("  分母（容量 ∝ R_H²）は、もっと速く増える ── 膨張")
print("  → 割合（②）と余裕（③）は、分母の勝ち負けで決まる")
print("  ★ 時間の矢は分子にある。分母は膨張が決める。")

print("\n=== 分子と分母の速さを、1ステップあたりの桁数で比べる ===")
Smax=2.049e122; Sobs=3.1e104
a_=math.log10(Smax)/N_steps
b_=math.log10(Sobs)/N_steps
print(f"  分母 S_max : プランク期 ~1 → 今日 {Smax:.3e}   = {math.log10(Smax):6.2f} 桁  -> {a_:.3f} 桁/ステップ")
print(f"  分子 S_obs : プランク期 ~1 → 今日 {Sobs:.2e}   = {math.log10(Sobs):6.2f} 桁  -> {b_:.3f} 桁/ステップ")
print(f"  差         : {a_-b_:.3f} 桁/ステップ")
print(f"  -> 140 ステップで {(a_-b_)*N_steps:.1f} 桁の目減り = 使用率 {10**(-(a_-b_)*N_steps):.2e}")
print(f"     （第6回の実測 1.5e-18 と一致）")
print()
print("  ★ 分子も分母も猛烈に増えている。分母がわずかに（1ステップ 0.13 桁）速いだけ。")
print("     その 0.13 桁の差が、140 ステップ積もって 18 桁の空きになった。")
