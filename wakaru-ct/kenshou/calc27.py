# -*- coding: utf-8 -*-
# 第23回：誤り訂正としての地平面 ── 使用率 10^-18 を「冗長度」と読み替える
import math
ln2=math.log(2)
n=2.9556e122          # 物理ビット（地平面のホログラフィック容量）
S=3.1e104             # 使われているエントロピー S/k_B
k=S/ln2               # 論理ビット相当
print("=== 符号として読む ===")
print(f"  物理ビット n = {n:.4e}（地平面に書ける量、第1回）")
print(f"  使われている S/k_B = {S:.2e} → 論理ビット k = S/ln2 = {k:.4e}（第6回）")
print(f"  符号化率 R = k/n = {k/n:.4e}")
print(f"  冗長度 n/k = {n/k:.4e}")
print("  → 第6回の『使用率 1.5e-18』は、符号の言葉では『冗長度 6.6e17』")

print("\n=== 現実の符号と比べる ===")
rows=[("QR コード（最高水準）",1.0/0.7,"~1.4倍"),
      ("RAID6",1.5,"1.5倍"),
      ("低符号化率の通信路符号",10,"10倍"),
      ("量子誤り訂正・表面符号",1e3,"10³倍（論理1量子ビットに物理1000個）"),
      ("宇宙の地平面",n/k,"")]
print(f"  {'符号':28s} {'冗長度':>12}")
for a,b,c in rows:
    print(f"  {a:28s} {b:12.3e}  {c}")
print(f"  → 宇宙は表面符号の {n/k/1e3:.2e} 倍の冗長度")

print("\n=== 訂正能力の上限（シングルトン限界）===")
print("  古典：距離 d ≤ n − k + 1")
d_cl=n-k+1
print(f"    d ≤ {d_cl:.4e}  （n とほぼ同じ）")
print("  量子：d ≤ (n − k)/2 + 1")
d_q=(n-k)/2+1
print(f"    d ≤ {d_q:.4e} = n の {d_q/n:.4f} 倍")
print(f"  → 原理上は、地平面のビットの約半分が壊れても復元できる（上限としては）")

print("\n=== 別の読み方：空きか、冗長か ===")
print("  同じ 1.5e-18 を、二通りに読める：")
print("    ① 容量の 1.5e-18 しか使っていない（＝空いている）      … 第6回の読み方")
print("    ② 同じ情報が 6.6e17 回ぶん重ねて書かれている（＝冗長）  … 今回の読み方")
print("  観測でこの二つを区別できるか？")
print("  → 区別するには『何と比べるか』が要る。第3回の手続きがそのまま効く。")

print("\n=== 冗長度を、地平面の面積で言い直す ===")
lP=1.616255e-35; RH=1.3052e26
A=4*math.pi*RH**2
print(f"  地平面の面積 A = {A:.3e} m²")
print(f"  論理1ビットあたりの面積 = A/k = {A/k:.3e} m²")
side=math.sqrt(A/k)
print(f"     → 一辺 {side:.3e} m")
print(f"  参考：物理1ビットあたりは 4ℓ_P²ln2 = {4*lP**2*ln2:.3e} m²（一辺 {math.sqrt(4*lP**2*ln2):.2e} m）")
print(f"  論理1ビットは物理ビット {n/k:.2e} 個ぶんの面積を占める")
print("\n  第19回の作法で、この 2.2e-26 m が何かに一致するか確かめる：")
for nm,v in [("陽子",1e-15),("電弱スケール ħ/M_W c",2.5e-18),("大統一 ~10^16 GeV",2e-32),("プランク長",lP)]:
    print(f"    {nm:24s} {v:.2e} m   比 {side/v:.2e}")
print("  → 何とも一致しない。だから何も言うことがない。")
print("     （第18回の 1.96 fm と違い、この数は近い相手を持たない ── 沈黙が正解）")
