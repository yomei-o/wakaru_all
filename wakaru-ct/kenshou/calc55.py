# -*- coding: utf-8 -*-
# 番外編候補：質量が変わるとは、どういうことか ── μ = m_p/m_e を掘る
import math

ln2 = math.log(2)
mp = 938.27208816      # MeV
me = 0.51099895000     # MeV
mu = mp / me

print("=== ① そもそも μ は動けるのか ===")
print("  共形変換のもとで 質量はウェイト −1（第16回）。")
print("  → m_p も m_e も同じ重みで動く → **比 μ = m_p/m_e はウェイト 0**。")
print("  μ = %.8f" % mu)
print("  ★ **純粋な共形変換では、μ は動かせない。**")
print("     『空間が膨張』か『原子が縮む』かの区別がつかないのは、まさにこれが理由。")
print("  → だから μ が動いたら、それは**共形変換ではない何か**である。")

print("")
print("=== ② ところが m_p と m_e は、出どころが違う ===")
sigma_lo, sigma_hi = 45.0, 60.0    # πN シグマ項 [MeV]（文献に幅がある）
sigma_s_lo, sigma_s_hi = 20.0, 60.0  # ストレンジ・シグマ項 [MeV]（さらに幅が大きい）
print("  m_e ＝ y_e · v      ── **100 パーセント ヒッグス起源**")
print("  m_p ＝ ほぼ Λ_QCD  ── **ほとんどが強い相互作用の凝縮エネルギー**")
print("     ヒッグス起源の部分＝シグマ項：")
for lo, hi, lab in [(sigma_lo, sigma_hi, "πN シグマ項 σ_πN"),
                    (sigma_s_lo, sigma_s_hi, "ストレンジ・シグマ項 σ_s")]:
    print("       %-26s %.0f〜%.0f MeV" % (lab, lo, hi))
tot_lo, tot_hi = sigma_lo + sigma_s_lo, sigma_hi + sigma_s_hi
print("     合計 %.0f〜%.0f MeV / %.1f MeV = **%.1f〜%.1f パーセント**" %
      (tot_lo, tot_hi, mp, 100 * tot_lo / mp, 100 * tot_hi / mp))
print("  ★ **陽子質量の 9 割前後は、ヒッグスと無関係。**")
print("     その 9 割は Λ_QCD ＝ 次元転移で生まれた量 ＝ **トレースアノマリーの産物**（第37回）。")
print("  ★ つまり μ は、**アノマリー起源の質量とヒッグス起源の質量の比**。")
print("     このシリーズで唯一、『0 の列に量子が書き込んだ数字』を分母分子にまたぐ量。")

print("")
print("=== ③ だから μ は、結合定数の変化を増幅する ===")
print("  Λ_QCD = μ_ref · exp( −2π / (b₀ α_s(μ_ref)) )   ← 次元転移")
print("  → d lnΛ / d ln α_s = **+2π / (b₀ α_s)**")
for nf, als, lab in [(5, 0.1180, "m_Z（n_f=5）"), (4, 0.2140, "m_b 付近（n_f=4）"),
                     (3, 0.3300, "m_c 付近（n_f=3）")]:
    b0 = 11 - 2.0 * nf / 3
    amp = 2 * math.pi / (b0 * als)
    print("    %-20s b₀ = %.3f、α_s = %.4f → 増幅率 %.1f" % (lab, b0, als, amp))
print("  ※ 値がスケールで違うのは、変化をどのスケールで指定するかの違い ── 同じ物理。")
print("  ★ 高いスケール（M_Z）で指定するなら **約 7 倍の増幅**。")
print("     さらに大統一で α_s と α が同じ結合に繋がっていれば、")
print("     文献の見積もりは **Δμ/μ ≈ R · Δα/α、R ≈ 30〜50**（模型依存）。")
print("     ── 第30回の『増幅率 K』が、今度は**理論側**に現れた。")

print("")
print("=== ④ 核心 ── μ の観測は、α よりどれだけ厳しいか ===")
obs = [
    ("メタノール・メーザー（z≈0.89）", 1.0e-7, "Δμ/μ", "Bagdonaite et al. 2013"),
    ("H₂ クエーサー吸収線（z≈2〜4）", 5.0e-6, "Δμ/μ", "複数の系"),
    ("アンモニア吸収（z≈0.68）", 3.5e-7, "Δμ/μ", ""),
    ("クエーサー多重項法", 1.0e-5, "Δα/α", "第30回で使った値"),
    ("オクロ天然原子炉", 1.1e-8, "Δα/α", "第30回（K=10⁷ の増幅つき）"),
]
print("  %-32s %-10s %-12s %-10s %s" % ("測定", "量", "上限", "ビット", "出典"))
for lab, val, q, src in obs:
    print("  %-32s %-10s %-12.1e %-10.1f %s" % (lab, q, val, -math.log2(val), src))
print("")
best_mu = 1.0e-7
best_a_qso = 1.0e-5
print("  同じ赤方偏移帯（クエーサー領域）で比べると：")
print("    Δμ/μ の上限 %.0e   対   Δα/α の上限 %.0e" % (best_mu, best_a_qso))
print("    → **μ のほうが %.0f 倍きつい（%.1f ビット）**" %
      (best_a_qso / best_mu, math.log2(best_a_qso / best_mu)))
for R in (7, 35):
    print("    増幅率 R = %d を掛けて、下敷きの結合定数への制限に直すと" % R)
    print("      μ からの制限は α からの制限より **%.0f 倍（%.1f ビット）強い**" %
          (R * best_a_qso / best_mu, math.log2(R * best_a_qso / best_mu)))

print("")
print("=== ⑤ 統一模型なら、Webb らの Δα 主張はどうなるか ===")
webb = 0.6e-5          # 報告された |Δα/α| の代表値
print("  クエーサー多重項法で報告された Δα/α ≈ %.1e（存在自体が論争中）" % webb)
for R in (7, 35, 50):
    pred = R * webb
    print("    R = %-3d → 予言される Δμ/μ = %.2e   対 観測上限 %.0e   → **%.0f 倍超過（%.1f ビット）**" %
          (R, pred, best_mu, pred / best_mu, math.log2(pred / best_mu)))
print("  ★ **統一的な変化だと仮定するかぎり、Δα の主張は μ の測定で殺される。**")
print("     ── 第30回で作った『増幅率で見る』作法が、そのまま効く。")
print("  ※ 逆に言えば、Δα が本物であるためには**統一していない**必要がある。")
print("     つまり『どの結合が動くか』を指定しないと、主張が文になっていない（第3回）。")

print("")
print("=== ⑥ そして c·t = 一定 には、これは効かない ===")
print("  ①のとおり μ はウェイト 0。共形変換では動かない。")
print("  → **μ の制限は、このシリーズの主題を一切傷つけない。**")
print("  ★ 傷つけないのは強いからではなく、**主張していないから**（第1・3回）。")
print("     一方 VSL（第28回）は Δα ≠ 0 を主張したので、⑤がそのまま追加の負債になる。")

print("")
print("=== ⑦ 核心の言い直し ── 測れば分かる、ただし別のことが ===")
print("  このシリーズは繰り返し『空間が膨張したのか原子が縮んだのかは区別できない』と書いた。")
print("  それは正しい ── **二つは同じ計量を別の座標で読んだだけ**だから。")
print("  では何なら区別できるのか：")
print("    ・全部の質量が**同じ重みで**動く          → 共形変換 ＝ 記法（区別できない）")
print("    ・質量が**別々の重みで**動く              → スカラー場が媒介する物理（区別できる）")
print("  ★ その分かれ目を測る量が、**まさに μ**。")
print("     アノマリー起源とヒッグス起源をまたぐ唯一の比だから。")
print("  現在の上限 |Δμ/μ| < %.0e = **%.1f ビット**" % (best_mu, -math.log2(best_mu)))
print("  → **『質量の変化が普遍的であること』は、23 ビットで確かめられている。**")

print("")
