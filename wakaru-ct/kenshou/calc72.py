    ("共形変換（Ω 一つ）", "L → ΩL、t → Ωt", "c → **c**", "**記法**"),
    ("**c·t = 一定 ゲージ**", "Ω = 1/(ct)", "c → **c**", "**記法**（本シリーズ）"),
    ("**非等方な取り替え**", "L → Ω_L L、t → Ω_T t（Ω_L ≠ Ω_T）",
     "c → **(Ω_L/Ω_T) c**", "**ローレンツ不変性を壊す**"),
