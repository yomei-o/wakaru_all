c = 2.99792458e8
a0 = 5.29177210903e-11
yr = 3.1557e7

print("=== ① まず、間違いの所在 ===")
bad = [
    ("深掘り⑯ ⑤", "SI 2019 で c は定義値。だから動かない",
     "**c = 一定 系の取り決め**", "**この系では論拠にならない**"),
    ("深掘り⑯ ②③④", "単位の取り替え／時計の比／四通りの帰属",
     "系に依らない", "**有効**"),
]
print("  %-14s %-34s %-24s %s" % ("箇所", "使った論拠", "それは何か", "判定"))
for a, b, cc, d in bad:
    print("  %-14s %-34s %-24s %s" % (a, b, cc, d))
print("")
print("  ★ SI は『c を定数と決める』という**一つのゲージ固定**であって、")
print("     『c は動かない』の**証明ではない**。循環していた。")
print("  ★ 正しい論拠は、SI ではなく **重み**。以下でやり直す。")

print("")
print("=== ② 重みで見る ── 何がゲージで動かせて、何が動かせないか ===")
w = [
    ("長さ  L", "+1", "動かせる", "Ω を掛ける"),
    ("時間  t", "+1", "動かせる", "Ω を掛ける"),
    ("質量  m", "−1", "動かせる", "Ω⁻¹ を掛ける"),
    ("**c = L/t**", "**0**", "**動かせない**", "**1 − 1 = 0**"),
    ("**c·t**", "**+1**", "**動かせる**", "長さだから"),
    ("**α**", "**0**", "**動かせない**", "無次元"),
    ("**a₀/(c·t)**", "**0**", "**動かせない**", "長さ ÷ 長さ"),
]
print("  %-18s %-10s %-16s %s" % ("量", "重み w", "ゲージで", "理由"))
for a, b, cc, d in w:
    print("  %-18s %-10s %-16s %s" % (a, b, cc, d))
print("")
print("  ★ **ここが答えの全部。**")
print("     **c·t は重み +1 だから、ゲージで一定にできる。**")
print("     **c は重み 0 だから、どのゲージでも動かせない。**")
print("  ★ 『c·t = 一定』と『c = 一定』は**矛盾しない**。")
print("     前者は**選べる**。後者は**選ぶ余地がない**。")

print("")
print("=== ③ c·t = 一定 のゲージを、実際に取ってみる ===")
print("  Ω(t) = 1/(c t) を選ぶ。すると：")
gauge = [
    ("c̃·t̃", "Ω × (c t) = **1**", "定義どおり一定"),
    ("c̃", "Ω⁰ × c = **c**", "**変わらない**（重み 0）"),
    ("ã₀", "Ω × a₀ = **a₀/(c t)**", "**これが動く**"),
    ("α̃", "Ω⁰ × α = **α**", "**変わらない**（重み 0）"),
]
print("  %-14s %-30s %s" % ("量", "このゲージでの値", ""))
for a, b, cc in gauge:
    print("  %-14s %-30s %s" % (a, b, cc))
print("")
print("  ★ **c·t = 一定 の系でも、c は動かない。**")
print("     動くのは **ã₀ ── 原子の大きさそのもの**。")
print("  ★ このゲージの良さはここ ── **原子の大きさが、そのまま無次元量になる**。")
print("     a₀/(c t) は測れる量で、ゲージを取ってもこれは変わらない。")

print("")
print("=== ④ その ã₀ が、実際どれだけ動いたか ===")
eras = [
    ("ビッグバン元素合成", 180.0),
    ("再結合（CMB）", 3.8e5 * yr),
    ("最古のクェーサー吸収線 (z≈3)", 2.1e9 * yr),
    ("オクロ天然原子炉 (18 億年前)", 1.2e10 * yr),
    ("現在", 1.38e10 * yr),
]
print("  %-30s %-16s %-16s %s" % ("時期", "t [s]", "c·t [m]", "ã₀ = a₀/(c t)"))
vals = []
for nm, t in eras:
    ct = c * t
    r = a0 / ct
    vals.append(r)
    print("  %-30s %-16.2e %-16.2e %.3e" % (nm, t, ct, r))
chg = vals[1] / vals[-1]
print("")
print("  ★ 再結合から現在まで、**ã₀ は %.2e 分の 1 に縮んだ**（%.1f ビット）。" %
      (chg, math.log2(chg)))
print("  ★ c = 一定 系での言い方：**宇宙が %.0f 倍に膨らんだ**。" % chg)
print("     c·t = 一定 系での言い方：**原子が %.0f 分の 1 に縮んだ**。" % chg)
print("     **同じ一つの数（%.2e）の、二つの言い方。0 ビットの差。**" % chg)

print("")
print("=== ⑤ そして、同じ期間に α はどれだけ動いたか ===")
da = 1.0e-5
print("  ã₀ の変化（再結合以降）  ： **%.1e**（%.0f 倍）" % (chg, chg))
print("  α の変化の上限（同期間） ： **< %.0e**" % da)
sep = chg / da
print("")
print("  ★ **比 %.1e（%.1f ビット）。**" % (sep, math.log2(sep)))
print("  ★ **同じ宇宙の同じ期間に、片方は 4 万倍動き、片方は 10⁻⁵ も動かなかった。**")
print("     → **この二つが同じ量であるはずがない。**")
print("  ★ これが、c·t = 一定 の系の中だけで書いた答え：")
print("     **『c·t が動く』ことと『α が動く』ことは、まったく別の話。**")
print("     SI も定義値も、一度も使っていない。")

print("")
print("=== ⑥ では、c を動かすゲージは本当に無いのか ===")
print("  ある。ただし**共形変換ではなくなる**：")
