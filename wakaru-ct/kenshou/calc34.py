# -*- coding: utf-8 -*-
# 第30回：変わる定数を、実際に測る ── 原子時計・オクロ・クエーサー吸収線
import math

tP = 5.391247e-44
t0 = 4.3536e17
NSTEP = math.log(t0 / tP)

def step(t):
    return math.log(t / tP)

print("=== ① 三つの測り方、三つの時間尺度 ===")
# (名前, 対応する宇宙年齢[s], 増幅率 K, 観測量の精度, |Δα/α| 上限)
PROBES = [
    ("原子時計（Yb+ E3 対 Sr）", t0,        7.0,   1e-18, 1.4e-8,
     "二つの遷移の α 感度差 ΔK≈7 を使う。周波数比を 1e-18 で監視"),
    ("オクロ天然原子炉",          3.786e17,  1.0e7, 2e-2,  1.1e-8,
     "¹⁴⁹Sm の 97.3 meV 共鳴。MeV 級の量の差なので 10⁷ 倍に増幅される"),
    ("クエーサー吸収線",          1.038e17,  0.3,   3e-6,  1.0e-5,
     "多重項法。多数の線を束ねて統計を稼ぐ"),
    ("CMB",                   1.2e13,    1.0,   4e-3,  4.0e-3,
     "再結合の時期が α に依存する"),
    ("元素合成",                1.0,       1.0,   1e-2,  1.0e-2,
     "⁴He 収量の α 依存性"),
]
print("  %-24s %-10s %-10s %-10s %s" % ("測り方", "宇宙年齢", "増幅率 K", "観測精度", "|Δα/α| 上限"))
for n, t, K, prec, b, note in PROBES:
    ts = ("%.1e s" % t) if t < 1e15 else ("%.2f Gyr" % (t / 3.156e16))
    print("  %-24s %-10s %-10.1e %-10.0e %.1e" % (n, ts, K, prec, b))

print("")
print("=== ② 増幅率という考え方 ===")
print("  どの方法も同じ形をしている：")
print("    観測量の変化 = K × (Δα/α)      → |Δα/α| < 観測精度 / K")
print("  K が大きいほど、同じ測定精度から強い上限が出る。")
for n, t, K, prec, b, note in PROBES:
    print("  %-24s K=%-9.1e 精度 %-8.0e → 上限 %.1e   %s" % (n, K, prec, prec / K, note))
print("  ※ 原子時計だけは形が違う：K×精度は【1 回の比較の感度】で、")
print("     上限 1.4e-8 はその変化率 1e-18/yr を 138 億年ぶん外挿した値。")
print("  ★ オクロが強いのは測定が精密だからではない ── **増幅率が 10⁷ ある**から。")
print("     97.3 meV という共鳴は MeV 級の量どうしの差なので、α のわずかな変化が桁で効く。")

print("")
print("=== ③ ビットに直す（第19回の作法）===")
for n, t, K, prec, b, note in PROBES:
    print("  %-24s %.1f bit" % (n, -math.log2(b)))
print("  実験室での α そのものの精度（CODATA 2022, 1.6e-10）: %.1f bit" % (-math.log2(1.6e-10)))

print("")
print("=== ④ 対数ステップのどこに、データがあるか ===")
print("  宇宙の全歴史 = %.2f 対数ステップ（第2回）" % NSTEP)
rows = []
for n, t, K, prec, b, note in PROBES:
    rows.append((step(t), n, -math.log2(b)))
rows.sort()
print("  %-24s %-10s %s" % ("測り方", "ステップ", "縛ったビット"))
for s, n, bits in rows:
    print("  %-24s %-10.2f %.1f bit" % (n, s, bits))
s_bbn = step(1.0)
print("")
print("  データが存在する範囲： ステップ %.2f 〜 %.2f" % (s_bbn, NSTEP))
cover = (NSTEP - s_bbn) / NSTEP
print("  → 全歴史の %.1f%%（残りの %.1f%% には α のデータが一つも無い）" %
      (100 * cover, 100 * (1 - cover)))
s_oklo = step(3.786e17)
hi = (NSTEP - s_oklo) / NSTEP
print("  20 ビット以上の精度がある範囲： ステップ %.2f 〜 %.2f = 全歴史の %.2f%%" %
      (s_oklo, NSTEP, 100 * hi))
print("  ★ α を 26 ビットで知っているのは、宇宙の対数的な歴史の 0.1 パーセントだけ。")

print("")
print("=== ⑤ 空白の期間 ===")
gaps = [
    ("元素合成 → CMB", s_bbn, step(1.2e13)),
    ("CMB → クエーサー", step(1.2e13), step(1.038e17)),
]
for n, a, b in gaps:
    print("  %-22s ステップ %.2f 〜 %.2f （%.2f ステップぶんの空白）" % (n, a, b, b - a))
print("  → データは三つの島に分かれていて、そのあいだは推定でしかない。")

print("")
print("=== ⑥ この営みは、共形変換で動かない ===")
print("  増幅率 K：無次元（比の比）        → ウェイト 0")
print("  Δα/α：無次元                    → ウェイト 0")
print("  縛ったビット数：無次元            → ウェイト 0")
print("  ★ 定数の測定は、まるごと第16回のウェイトの地図の【0 の列】にある。")
print("     このシリーズの道具が一切触れられない場所 ── だからこそ審判になれる。")

print("")
print("=== ⑦ もし α が 1 桁動いていたら、何が起きたか ===")
eff = [
    ("原子核が束縛しなくなる（炭素の 7.65 MeV 共鳴）", 4e-2, "恒星内の三重α過程が止まる"),
    ("⁴He 収量が観測とずれる", 1e-2, "元素合成"),
    ("再結合の時期がずれる", 4e-3, "CMB の音響ピークの位置"),
    ("分子の遷移がずれる", 1e-5, "クエーサー吸収線"),
]
print("  %-42s %-10s %s" % ("効いてくる場所", "必要な |Δα/α|", "観測"))
for n, v, o in eff:
    print("  %-42s %-10.0e %s" % (n, v, o))
print("  → 生命に関わる制約（三重α過程）が 4 パーセントで、いちばん緩い。")
print("     観測の上限 1e-8 は、それより 6 桁きつい ── **人間原理より観測のほうが強い**。")
