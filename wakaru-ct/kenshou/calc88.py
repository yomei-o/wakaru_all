def betas(g1, g2, g3, yt, lam):
    k = 1.0 / (16 * math.pi ** 2)
    return (k * (41 / 10.) * g1 ** 3, k * (-19 / 6.) * g2 ** 3, k * (-7.) * g3 ** 3,
            k * yt * (4.5 * yt ** 2 - 8 * g3 ** 2 - 2.25 * g2 ** 2 - 0.85 * g1 ** 2),
            k * (24 * lam ** 2 - 6 * yt ** 4
                 + 0.375 * (2 * g2 ** 4 + (g2 ** 2 + 0.6 * g1 ** 2) ** 2)
                 + lam * (12 * yt ** 2 - 9 * g2 ** 2 - 1.8 * g1 ** 2)))


def run(lam0, yt0=0.94, n=40000, mu_end=MP):
    y = [math.sqrt(4 * math.pi / inv1), math.sqrt(4 * math.pi / inv2),
         math.sqrt(4 * math.pi / inv3), yt0, lam0]
    h = (math.log(mu_end) - math.log(MZ)) / n

    def add(a, b, s):
        return [x + s * z for x, z in zip(a, b)]
    for _ in range(n):
        k1 = betas(*y); k2 = betas(*add(y, k1, h / 2))
        k3 = betas(*add(y, k2, h / 2)); k4 = betas(*add(y, k3, h))
        y = [y[i] + h / 6 * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i]) for i in range(5)]
    return y


