# -*- coding: utf-8 -*-
# 深掘り⑮：電子と陽子は同じくらい単純に見えた。どこで分かれたのか
import math

alpha = 1 / 137.035999
print("=== ① 1928 年の時点では、二つは完全に対等だった ===")
same = [
    ("電荷", "−e", "+e", "**同じ大きさ**"),
    ("スピン", "1/2", "1/2", "**同じ**"),
    ("統計", "フェルミ", "フェルミ", "**同じ**"),
    ("従う式", "ディラック方程式", "ディラック方程式", "**同じ**"),
    ("大きさ", "点", "点", "**同じ（と思われていた）**"),
    ("質量", "1", "1836.15", "ここだけ違う"),
]
print("  %-12s %-18s %-18s %s" % ("性質", "電子", "陽子", ""))
for a, b, c, d in same:
    print("  %-12s %-18s %-18s %s" % (a, b, c, d))
print("")
print("  ★ **違いは質量比 1836 だけ**。それも『重い電子』で済む話に見えた。")
print("     『急に複雑になる』のは、この時点では**まだ起きていない**。")

print("")
print("=== ② 分かれ目は 1933 年。しかも一発で分かる数だった ===")
print("  ディラック方程式は、点状のスピン 1/2 粒子に **g = 2 ちょうど**を要求する。")
print("")
g_e, g_p = 2.00231930436, 5.5856946893
mu_n = -1.91304273       # 核磁子単位。ディラックなら中性粒子は 0
a_e, a_p = (g_e - 2) / 2, (g_p - 2) / 2
print("  %-14s %-16s %-16s %s" % ("粒子", "g（実測）", "|g−2|/2", "ディラックからのずれ"))
print("  %-14s %-16.9f %-16.9f %s" % ("電子", g_e, a_e, "**0.12 %**"))
print("  %-14s %-16.7f %-16.7f %s" % ("陽子", g_p, a_p, "**179 %**"))
print("  %-14s %-16s %-16s %s" % ("中性子", "μ = %.5f" % mu_n, "—",
                                  "**0 のはずが 0 でない**"))
print("")
print("  ★ ずれの比 ＝ %.4f / %.9f = **%.0f 倍**。" % (a_p, a_e, a_p / a_e))
print("  ★ そして中性子が決定的 ── **電荷ゼロの粒子が磁石になっている**。")
print("     点電荷でないどころか、**中に電荷が回っている**としか読めない。")
print("  ★ つまり『複雑になった』のは 1964 年でも 1968 年でもなく、**1933 年**。")
print("     クォークより 31 年、スケーリングより 35 年前に、答えは出ていた。")

print("")
print("=== ③ そして、クォーク模型が最初に当てたのが、まさにこの数 ===")
print("  陽子 = uud、中性子 = udd。u と d の質量が同じなら、")
print("  磁気能率の比は**電荷と組み合わせだけで決まる**：")
pred = -2.0 / 3.0
obs = mu_n / 2.7928473446
print("    予言  μ_n/μ_p = **−2/3 = %.5f**" % pred)
print("    実測  μ_n/μ_p = **%.5f**" % obs)
print("    ずれ **%.1f %%**" % (abs(obs - pred) / abs(pred) * 100))
print("  ★ **パラメータを一つも使っていない。** 電荷 2/3, −1/3 と組み合わせだけ。")
print("     1933 年に見つかった『複雑さ』が、**そのまま構造の指紋だった**。")

print("")
print("=== ④ では『急に複雑になる』の正体は何か ===")
print("  仮説 A：陽子の**記述**が長い")
print("  仮説 B：陽子の**計算**が重い")
print("  ── 深掘り⑫の二つの『簡単』。どちらか測る。")
print("")
print("  ラグランジアンを並べる：")
lag = [
    ("QED", "L = ψ̄(iγ·D − m)ψ − ¼F_μν F^μν",
     "F = ∂A − ∂A", "**項の数 3**"),
    ("QCD", "L = ψ̄(iγ·D − m)ψ − ¼F^a_μν F^{a,μν}",
     "F^a = ∂A^a − ∂A^a **+ g f^{abc}A^b A^c**", "**項の数 4**"),
]
print("  %-8s %-40s %-42s %s" % ("", "本体", "場の強さ", ""))
for a, b, c, d in lag:
    print("  %-8s %-40s %-42s %s" % (a, b, c, d))
print("")
print("  ★ **記述の差は、たった 1 項**（f^{abc}A A ── グルーオンが自分と結合する項）。")
print("  ★ → **仮説 A は外れ。** 陽子が複雑なのは、書くのが長いからではない。")

print("")
print("=== ⑤ 仮説 B を測る ── 摂動論が到達できる精度の上限 ===")
print("  漸近級数は最良打ち切りで止まる。展開変数 a のとき：")
print("    最適次数 n ≈ 1/a、そこでの誤差 ≈ e^(−1/a)  ── **これ以上は原理的に無理**")
print("")
cases = [
    ("電子（QED）", alpha / math.pi, "α/π"),
    ("クォーク @ 100 GeV", 0.12 / math.pi, "α_s/π"),
    ("クォーク @ 2 GeV", 0.30 / math.pi, "α_s/π"),
    ("陽子の中 @ 0.5 GeV", 0.80 / math.pi, "α_s/π"),
    ("陽子の中 @ 0.2 GeV", 1.20 / math.pi, "α_s/π"),
]
print("  %-24s %-14s %-14s %-18s %s" %
      ("場面", "展開変数 a", "最適次数", "到達できる誤差", "ビット"))
for nm, a, lbl in cases:
    nopt = 1 / a
    err = math.exp(-1 / a)
    print("  %-24s %-14.5f %-14.0f %-18.2e %.0f" %
          (nm, a, nopt, err, -math.log2(err)))
print("")
print("  ★ **電子では 620 ビットまで行ける。陽子の中では 4 ビットで止まる。**")
print("     どれだけ計算機を回しても、摂動論では**数 % より良くならない**。")
print("  ★ → **仮説 B が当たり。** 差は記述ではなく、**到達可能性**。")

print("")
print("=== ⑥ その差を作っているのは、たった一つの数 ===")
print("  電子のスケール（コンプトン波長）での結合   α   = %.6f" % alpha)
print("  陽子のスケール（1 fm ≈ 0.2 GeV）での結合 α_s ≈ 1.2")
print("  ★ **比 %.0f 倍。これだけが『単純』と『複雑』を分けている。**" % (1.2 / alpha))
print("  ★ 中身の複雑さではない。**同じ形の理論の、結合定数の値**。")
print("     ⑤の表の 1 行目と 5 行目は、**同じ公式に違う数を入れただけ**。")

print("")
print("=== ⑦ だから『単純さ』は物の性質ではなく、見る場所の性質 ===")
scale = [
    ("陽子を 0.2 GeV で見る", "α_s ≈ 1.2", "**ぐちゃぐちゃ**", "ハドロン、閉じ込め"),
    ("陽子を 100 GeV で見る", "α_s ≈ 0.12", "**電子並みに単純**", "自由な点、ジェット"),
    ("電子を 1/137 の世界で見る", "α = 0.0073", "**単純**", "1 ループで 3 桁"),
    ("電子を α ≈ 1 の世界で見たら", "（仮想）", "**ハドロン並みに複雑**", "束縛状態だらけ"),
]
print("  %-28s %-16s %-20s %s" % ("見方", "結合", "見え方", "何が見えるか"))
for a, b, c, d in scale:
    print("  %-28s %-16s %-20s %s" % (a, b, c, d))
print("")
print("  ★ **同じ陽子が、エネルギーを上げると電子と同じくらい単純になる。**")
print("     漸近自由性とは、**『単純さ』が観測条件だったという主張**。")
print("  ★ 本シリーズの言い方でいえば ── **『何と比べて単純なのか』を言えということ**。")
print("     単純さも、比を取らないと文にならない。")

print("")
print("=== ⑧ ついでに ── 電子も本当は単純ではない ===")
me = 0.51099895
landau = me * math.exp(3 * math.pi / (2 * alpha))
print("  QED の結合も走る。1 ループで外挿すると、発散する（ランダウ極）：")
print("    μ = m_e × exp(3π/2α) ≈ **10^%.0f GeV**" % math.log10(landau / 1000))
print("    プランク質量は 10^%.1f GeV ── **極はその %.0f 桁も先**。" %
      (math.log10(1.22e19), math.log10(landau / 1000) - 19.1))
print("  ★ **電子が単純に見えるのは、極が遠すぎて届かないから。**")
print("     構造が無いのではなく、**構造が見える場所まで行けていない**。")
print("")
comp = [
    ("陽子", "10⁻¹⁵ m", "**構造が見えた**", "1968 SLAC"),
    ("電子", "< 10⁻¹⁹ m", "まだ点", "LEP／LHC の接触相互作用の下限"),
]
print("  %-10s %-16s %-18s %s" % ("粒子", "調べた距離", "結果", "根拠"))
for a, b, c, d in comp:
    print("  %-10s %-16s %-18s %s" % (a, b, c, d))
print("  ★ 差は **4 桁**。『電子は単純』は、**4 桁ぶんしか保証されていない**。")

print("")
print("=== ⑨ まとめ ===")
print("  ・『急に複雑になる』は 1964 年ではなく **1933 年**に起きていた（μ_p = 2.79）。")
print("  ・複雑さの正体は **記述長ではなく計算量**（ラグランジアンの差は 1 項）。")
print("  ・その計算量を決めているのは **結合定数の値ひとつ**（α 対 α_s、160 倍）。")
print("  ・だから**同じ陽子が、100 GeV で見れば電子並みに単純**になる。")
print("  ・そして**電子が単純なのは 4 桁ぶんの保証**でしかない。")
print("")
print("  ★ **単純／複雑は、物についた札ではなく、**")
print("    **『どの結合定数の値で見ているか』という座標の話だった。**")

print("")
print("=== ⑩ 正直な線 ===")
print("  ・⑤の e^(−1/a) は最良打ち切りの目安であって、厳密な下限ではない。")
print("    実際の QCD には和の取り直し（ボレル和、OPE）があり、少し良くできる。")
print("  ・α_s @ 0.2 GeV ≈ 1.2 は定義（スキーム）に依る。1 を超える所では")
print("    そもそも『結合定数の値』という言い方自体が便宜的。")
print("  ・⑥の『160 倍だけが違い』は言い過ぎ寄り。非可換性（1 項の差）が")
print("    **その 160 倍を作っている**ので、原因と結果を並べている面がある。")
print("  ・⑧のランダウ極は 1 ループ外挿。実際には途中で他の物理が入るので、")
print("    **10^277 GeV は文字通りには受け取れない**。")
print("  ・③の μ_n/μ_p = −2/3 は、u と d の質量が等しいという近似込み。")
