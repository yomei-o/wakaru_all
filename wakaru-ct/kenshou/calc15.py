# -*- coding: utf-8 -*-
# 第10回：熱と情報に入れてみる ── 消去コストは、温度を言うまで決まらない
import math
c=299792458.0; hbar=1.054571817e-34; G=6.67430e-11; kB=1.380649e-23; eV=1.602176634e-19
lP=math.sqrt(hbar*G/c**3); mP=math.sqrt(hbar*c/G)
t0=4.3536e17; T0=2.7255; RH=c*t0; H0=1/t0; ln2=math.log(2)
TP=mP*c*c/kB
E=c**4*RH/(2*G)                      # 地平面内の全エネルギー
N=math.pi*(RH/lP)**2/ln2             # メモリ（bit）
TH=hbar*H0/(2*math.pi*kB)            # ハッブル（地平面）温度

print("=== この絵では、温度が動かない ===")
print(f"  T̃ = aT = 一定 = {T0} K")
print(f"  1ビット消去のコスト k_B T₀ ln2 = {kB*T0*ln2:.4e} J = {kB*T0*ln2/eV:.4e} eV")
print("  → 宇宙の全歴史を通じて一定。標準の絵では ∝1/a で下がる同じ量。")
print("  どちらが『本当の消去コスト』か？ → 比較相手（と温度）を言うまで、問いになっていない。")

print("\n=== 宇宙の全エネルギーで、何ビット消せるか ===")
print(f"  地平面内の全エネルギー E = c⁴R_H/2G = {E:.4e} J")
print(f"  メモリ（書ける量）      N = {N:.4e} bit")
rows=[("ハッブル（地平面）温度", TH),
      ("CMB 温度", T0),
      ("室温 300 K", 300.0),
      ("プランク温度", TP)]
print(f"\n  {'どの温度で消すか':22s} {'T [K]':>12} {'k_BT ln2 [J]':>14} {'消せるビット数':>14}  {'N との比'}")
for n,T in rows:
    cost=kB*T*ln2; nb=E/cost
    print(f"  {n:22s} {T:12.4e} {cost:14.4e} {nb:14.4e}  {nb/N:.4e}")
print(f"\n  ★ ハッブル温度で消すと、ちょうど N になる（番外編②の恒等式 E = T_H S）")
print(f"  ★ CMB 温度で消すと、メモリの {E/(kB*T0*ln2)/N:.2e} しか消せない ── 30 桁足りない")

print("\n=== 実機と比べる ===")
c300=kB*300*ln2
print(f"  室温のランダウアー限界 = {c300:.3e} J = {c300/eV:.4f} eV")
cpu=1e-15
print(f"  現代のCPUの1演算あたり ~{cpu:.0e} J → 限界の {cpu/c300:.2e} 倍")

print("\n=== 比較相手を変えると、値段が変わる ===")
me=9.1093837015e-31
pairs=[("粒子質量 m_e c² と比べる", kB*T0/(me*c*c), "∝1/t（時代とともに安くなる）"),
       ("CMB 光子 1 個と比べる", 1.0, "一定（同じウェイト）"),
       ("プランクエネルギーと比べる", kB*T0/(mP*c*c), "共形不変だが、時間とともに変わる"),
       ("地平面の全エネルギーと比べる", kB*T0/E*eV/eV, "──")]
for n,v,note in pairs[:3]:
    print(f"  {n:28s} {v:.3e}   {note}")

print("\n=== エントロピーは無次元 ===")
print("  S/k_B はビット数 → ウェイト0 → 共形変換で不変")
print("  熱力学第二法則も、そのまま。第6回で数えた 3.1e104 も動かない。")
