# -*- coding: utf-8 -*-
# 深掘り㉙：微細構造定数の諸仮説を、一斉に検定する
#   物差し：①実験誤差で頭打ち ②探索空間 log₂M ③狙う値の単純さ
import math
import itertools

# CODATA 2018
INV = 137.035999084
SIG = 0.000000021          # 標準不確かさ（絶対）
REL = SIG / INV

print("=== ① 検定の規則を、先に決めておく ===")
rules = [
    ("(1) 実験値と何 σ 離れているか", "**これが第一の関門**", "σ = %.1e（絶対）" % SIG),
    ("(2) 探索空間 log₂M を引く", "後から探した式は値段を払う", "族を列挙して数える"),
    ("(3) 狙う値の単純さも払う", "2/3 と 513/8 は同じではない", "log₂(分子×分母)"),
    ("(4) どのスケールの α か言えるか", "**α は走る**（深掘り㉒）", "137 は零運動量だけ"),
    ("(5) 機構があるか", "式が当たるだけでは足りない", "なぜその式なのか"),
]
print("  %-34s %-30s %s" % ("規則", "中身", "根拠"))
for a, b, c in rules:
    print("  %-34s %-30s %s" % (a, b, c))

print("")
print("=== ② まず、標的の精度を確認する ===")
print("  1/α(0) = **%.9f ± %.9f**（CODATA 2018）" % (INV, SIG))
print("  相対精度 **%.1e** ── **%.0f ビット**" % (REL, -math.log2(REL)))
print("")
print("  ★ **これが第一の関門です。**")
print("     どんな式も、**相対 %.1e 以内**で当てなければ「合っている」と言えません。" % REL)
print("     つまり **10 桁**。ここで大半の仮説が落ちます。")

print("")
print("=== ③ 仮説カタログ ── 実際に計算する ===")
pi = math.pi
cands = [
    ("エディントン（整数）", 137.0, "自由度の数え上げ", "**機構あり**"),
    ("4π³ + π² + π", 4 * pi ** 3 + pi ** 2 + pi, "π の多項式", "機構なし"),
    ("(8π⁴/9)(2/(45π))^(1/4)", (8 * pi ** 4 / 9) * (2 / (45 * pi)) ** 0.25,
     "Wyler 型の体積比", "機構は主張されたが未確立"),
    ("137 + 1/(2·137)", 137 + 1 / 274., "小さな補正", "機構なし"),
    ("π²·(π²+1)/(π−1)", pi ** 2 * (pi ** 2 + 1) / (pi - 1), "適当な有理式", "機構なし"),
    ("2^7 + 3^2", 128 + 9.0, "整数の和", "機構なし"),
    ("(2π)^(5/2)·π/√(2π)", (2 * pi) ** 2.5 * pi / math.sqrt(2 * pi), "適当な冪", "機構なし"),
]
print("  %-30s %-18s %-14s %-16s %s" %
      ("仮説", "値", "相対差", "何 σ", "機構"))
rows = []
for nm, v, kind, mech in cands:
    rel = abs(v - INV) / INV
    nsig = abs(v - INV) / SIG
    rows.append((nm, v, rel, nsig, mech))
    print("  %-30s %-18.9f %-14.2e %-16.3g %s" % (nm, v, rel, nsig, mech))
print("")
best = min(rows, key=lambda r: r[3])
print("  ★ **いちばん近いのは「%s」で、それでも %.0f σ**。" % (best[0], best[3]))
print("  ★ **全部、実験値から数千〜数億 σ 離れています。**")
print("     つまり ── **候補はすべて、第一の関門で落ちます**。")

print("")
print("=== ④ 「4π³+π²+π」を、きちんと採点する ===")
v = 4 * pi ** 3 + pi ** 2 + pi
rel = abs(v - INV) / INV
print("  値 %.9f、実測 %.9f" % (v, INV))
print("  相対差 **%.2e** → 素朴な「買い」は %.1f ビット" % (rel, -math.log2(rel)))
print("")
print("  ところが規則 (1) により、買いは**実験誤差で頭打ち**になりません ── ")
print("  **むしろ逆で、誤差より大きくずれているので「外れ」です**。")
print("    ずれ %.2e ＝ 実験精度 %.1e の **%.0f 倍**" % (rel, REL, rel / REL))
print("    → **%.0f σ の不一致**" % (abs(v - INV) / SIG))

print("")
print("=== ⑤ 族を列挙して、M を数える ===")
print("  a·π^p + b·π^q + c·π^r の形（a,b,c ∈ −4…4、p,q,r ∈ 0…4）を全部試す。")
coefs = range(-4, 5)
pows = range(0, 5)
tol = 3e-4          # 「4π³+π²+π」と同程度の近さ
hits, trials = [], 0
seen = set()
for (a, p) in itertools.product(coefs, pows):
    for (b, q) in itertools.product(coefs, pows):
        for (cc, r) in itertools.product(coefs, pows):
            if (a, p) > (b, q) or (b, q) > (cc, r):
                continue                      # 並べ替えの重複を除く
            val = a * pi ** p + b * pi ** q + cc * pi ** r
            if not (100 < val < 200):
                continue
            key = round(val, 9)
            if key in seen:
                continue
            seen.add(key)
            trials += 1
            if abs(val - INV) / INV < tol:
                hits.append((a, p, b, q, cc, r, val, abs(val - INV) / INV))
print("  100〜200 に落ちた式： **%d 通り**" % trials)
print("  実測から相対 %.0e 以内： **%d 個**" % (tol, len(hits)))
for a, p, b, q, cc, r, val, e in sorted(hits, key=lambda x: x[7])[:8]:
    print("    %+d·π^%d %+d·π^%d %+d·π^%d = %.6f（ずれ %.1e、%.0f σ）" %
          (a, p, b, q, cc, r, val, e, abs(val - INV) / SIG))
print("")
if trials:
    exp_hits = trials * 2 * tol * INV / 100.0     # 幅 100 の区間に一様と仮定
    print("  偶然の期待値 ≈ %d × 2×%.0e×137/100 = **%.1f 個**" % (trials, tol, exp_hits))
    print("  実測 **%d 個** → **偶然と同程度**。" % len(hits))
print("  ★ **π の多項式で 137.036 の近くを狙うのは、簡単すぎます。**")
print("     族の値段 log₂(%d) = **%.1f ビット**を払わなければなりません。" %
      (trials, math.log2(trials)))

print("")
print("=== ⑥ 決定的なのは、規則 (4) ── どのスケールの α か ===")
run = [("零運動量", 137.036), ("M_Z", 128.95), ("1 TeV", 125.8), ("10¹⁶ GeV", 42.0)]
print("  %-16s %s" % ("スケール", "1/α"))
for a, b in run:
    print("  %-16s %.2f" % (a, b))
print("")
print("  ★ **『137.036』が出るのは零運動量極限だけです。**")
print("  ★ そして深掘り㉒で見たとおり、**零運動量の 1/α には ln(m_e) が入っています**。")
print("     → **π だけで書ける式が当たるのは、原理的におかしい**。")
print("       電子質量という別のパラメータが混ざっているのだから。")
print("  ★ **これが、π の公式が全滅する構造的な理由**でした。")
print("     数値が合わないだけでなく、**合ってはいけない**。")

print("")
print("=== ⑦ 機構のある仮説だけを、別枠で見る ===")
mech = [
    ("エディントン（1929）", "自由度の数え上げ", "**137 ちょうど**",
     "**%.0f σ で棄却**" % (abs(137.0 - INV) / SIG)),
    ("大統一（深掘り㉒）", "sin²θ_W = 3/8 ＋ 走り", "**α_U 1 個は残る**", "**部分的に成功**"),
    ("漸近安全性（深掘り㉘）", "固定点 β(g*) = 0", "**f_g が決まれば α も**", "**未確定・筋は通る**"),
    ("弦理論のフラックス", "整数のフラックス量子数", "原理的には整数比", "**10^500 で情報ゼロ**"),
    ("人間原理", "窓の中にいるから", "**±4 % の窓**（深掘り㉔）", "**予言力ゼロ**"),
]
print("  %-26s %-26s %-24s %s" % ("仮説", "機構", "何を言うか", "判定"))
for a, b, c, d in mech:
    print("  %-26s %-26s %-24s %s" % (a, b, c, d))
print("")
print("  ★ **数値を当てにいく仮説は全滅。**")
print("  ★ **機構を持つ仮説だけが生き残っています** ── そして生き残った二つは、")
print("     **どちらも α の値そのものは言わず、「α_U 1 個に還元する」と言う**。")

print("")
print("=== ⑧ 判定 ===")
print("  %-34s %s" % ("仮説の型", "判定"))
print("  %-34s %s" % ("整数（エディントン）", "**棄却**（1.7×10⁶ σ）"))
print("  %-34s %s" % ("π の多項式", "**棄却**（数千〜数万 σ、しかも族が大きすぎる）"))
print("  %-34s %s" % ("幾何学的体積比（Wyler 型）", "**棄却**（数値が合わない）"))
print("  %-34s %s" % ("自己言及型（Gilson 型）", "**検定以前**（α を含む式で α を定義）"))
print("  %-34s %s" % ("**大統一**", "**部分的に成功**（3/8 と b_i は当たる）"))
print("  %-34s %s" % ("**漸近安全性**", "**未確定・唯一の前進中の道**"))
print("  %-34s %s" % ("人間原理", "**予言力ゼロ**（窓を言うだけ）"))
print("")
print("  ★ **結論：数値を当てる仮説は、一つも生き残りません。**")
print("     理由は三つ ── ")
print("       ① 実測が **10 桁**あるので、偶然の一致では届かない")
print("       ② π の族は大きすぎて、**当たっても情報がゼロ**")
print("       ③ **137.036 は純粋な数ではない**（m_e が混ざっている）")
print("")
print("  ★ **生き残るのは「還元する」仮説だけ**でした。")
print("     α の値を言うのではなく、**α を別の 1 個に還元する**。")
print("     ── 深掘り㉒の結論（狙いは α ではなく α_U）と、同じ場所です。")

print("")
print("=== ⑨ 正直な線 ===")
print("  ・③の候補は筆者が選んだもので、**網羅的ではありません**。")
print("    ただし ② の 10 桁という関門は、どんな候補にも同じようにかかります。")
print("  ・⑤の族（a·π^p の三項和）も一つの選び方です。族を広げれば当たる式は")
print("    増えますが、**同時に log₂M も増える**ので、正味は改善しません。")
