# -*- coding: utf-8 -*-
# 第47回：無次元量の地図 ── 何が物理で、何が帳簿か
import math

G = 6.67430e-11
c = 2.99792458e8
hbar = 1.054571817e-34
mp = 1.67262192369e-27
me = 9.1093837015e-31
bic = 0.5 * math.log2(1701)      # 第5回：パラメータ 1 個の値段

print("=== ① 2019 年、国際単位系が線を引き直した ===")
print("  2019 年 5 月 20 日から、SI は**七つの定数の値を厳密に固定して**単位を定義する。")
fixed = [
    ("Δν_Cs", "9 192 631 770 Hz", "秒"),
    ("c", "299 792 458 m/s", "メートル"),
    ("h", "6.626 070 15e−34 J·s", "**キログラム**"),
    ("e", "1.602 176 634e−19 C", "アンペア"),
    ("k_B", "1.380 649e−23 J/K", "ケルビン"),
    ("N_A", "6.022 140 76e23 /mol", "モル"),
    ("K_cd", "683 lm/W", "カンデラ"),
]
print("  %-10s %-26s %s" % ("定数", "固定された値（厳密）", "定義される単位"))
for a, b, d in fixed:
    print("  %-10s %-26s %s" % (a, b, d))
print("  → **キログラム原器は廃止された**。質量は h から作られる。")
print("  ★ これは、**次元付きの量が帳簿であることの、国際的な公式宣言**。")
print("     第3回でこのシリーズが手で引いた線を、世界の度量衡が同じ場所に引いていた。")

print("")
print("=== ② ところが α は固定できなかった ===")
alpha_inv, alpha_err = 137.035999177, 0.000000021
print("  微細構造定数 α = e²/(4πε₀ħc)。e、ħ、c はいま**厳密に固定**されている。")
print("  では α も決まるのか？ → **決まらない**。ε₀ が測定量になったから。")
print("  1/α = %.9f(%d)  ── いまも**測る**しかない（CODATA 2022）" %
      (alpha_inv, alpha_err * 1e9))
print("  ★ **無次元だから、法令では決められない。**")
print("     c は決められて α は決められない ── これが第3回の線の、いちばん鮮明な形。")

print("")
print("=== ③ 単位を決めるのに、いくつ要るか ===")
print("  力学の世界には次元が三つ（長さ・時間・質量）。")
print("  c、ħ、G の三つで**ちょうど使い切れる** ── プランク単位系。")
print("  → **プランク単位で書けば、すべての量は無次元になる**。")
print("  ★ 『基本定数はいくつあるか』は決着していない問い ──")
print("     3 個（次元の数だけ）／2 個／1 個／0 個 と、立場が分かれる")
print("     （Duff–Okun–Veneziano 2002 の三者鼎談）。")
print("     ★ ただしどの立場でも一致していること：")
print("       **物理の中身は、無次元量の側にある。**")

print("")
print("=== ④ 無次元量の地図 ===")
alpha = 1 / alpha_inv
aG = G * mp ** 2 / (hbar * c)
v_over_MP = 246.22 / 1.220890e19
rho_ratio = 1.13e-123
N24 = 3.107e122
mp_me = mp / me
table = [
    ("宇宙が処理した情報 N（第24回）", N24, "物理", "第40・41回と同じ数"),
    ("陽子と電子の質量比 m_p/m_e", mp_me, "物理", "説明されていない"),
    ("微細構造定数の逆数 1/α", alpha_inv, "物理", "説明されていない"),
    ("スペクトル指数 n_s", 0.9649, "物理", "インフレーションが説明を主張"),
    ("Ω_Λ", 0.685, "物理", "説明されていない"),
    ("微細構造定数 α", alpha, "物理", "説明されていない"),
    ("ヒッグス真空期待値 / プランク質量", v_over_MP, "物理", "**階層性問題**"),
    ("重力の微細構造定数 α_G = Gm_p²/ħc", aG, "物理", "説明されていない"),
    ("ρ_Λ / ρ_Planck（第32回）", rho_ratio, "物理", "**宇宙定数問題**"),
]
print("  %-38s %-16s %-8s %s" % ("量", "値", "列", "説明はあるか"))
for a, b, d, e in table:
    print("  %-38s %-16.4g %-8s %s" % (a, b, d, e))
span = math.log2(N24 / rho_ratio)
print("")
print("  いちばん大きい %.2e から いちばん小さい %.2e まで ── **%.0f ビットの幅**" %
      (N24, rho_ratio, span))
print("  ★ すべて同じ列（ウェイト 0）にある。**共形変換はどれ一つ動かせない**。")

print("")
print("=== ⑤ いくつあって、いくつ説明されているか ===")
counts = [
    ("標準模型（ニュートリノ質量を除く）", 19, "うち次元を持つのは μ²（＝ヒッグスの v）**1 個だけ**"),
    ("ニュートリノの質量と混合", 7, "3 質量 ＋ 3 角 ＋ 1 位相（マヨラナ位相を除く）"),
    ("ΛCDM の基本パラメータ", 6, "**6 個すべてが無次元**（Ω_b h²、Ω_c h²、θ*、τ、A_s、n_s）"),
]
tot = 0
print("  %-36s %-6s %s" % ("枠組み", "個数", "内訳"))
for a, n, d in counts:
    tot += n
    print("  %-36s %-6d %s" % (a, n, d))
print("  合計 **%d 個**。" % tot)
print("  ★ 標準模型のラグランジアンで**次元を持つ定数は μ² ただ一つ**。")
print("     残りは全部が無次元 ── そして ΛCDM の 6 個も全部が無次元。")
print("     **現代物理はすでに、パラメータを物理の列に書いている。**")
print("")
print("  第一原理から導かれているものは？ → **ほぼゼロ**。")
print("    n_s だけがインフレーションによる説明を主張している（第27回、4.8 ビット）。")
print("  第5回の値段で言えば： %d 個 × %.2f = **%.1f ビット**が説明されていない。" %
      (tot, bic, tot * bic))

print("")
print("=== ⑥ 手続きを、自分に当てる ===")
step2 = 140.24
val = tot * bic
print("  ここで、いま出した %.1f ビットと、第2回の『全歴史 = %.2f 対数ステップ』が" % (val, step2))
print("  なんとなく似た桁に見える。これは何か意味があるのか。")
print("  → **第19回の手続きに掛ける**：")
d = abs(val - step2)
print("    差 = %.1f、相対差 = %.0f パーセント" % (d, 100 * d / step2))
print("    『一致した』と言うには、たとえば ±5 パーセント以内に落ちる必要がある。")
print("    実際は %.0f パーセント外れている。" % (100 * d / step2))
print("    → 命中していないので、**驚きは 0 ビット。一致していない。**")
print("  ★ しかも仮に近かったとしても、驚きは小さかった：")
lo, hi = 15 * 5.0, 30 * 6.0
print("    パラメータの個数は 15〜30 個、1 個の値段は 5〜6 ビットともっともらしい")
print("    → 積の事前範囲はおよそ %.0f〜%.0f（幅 %.0f）" % (lo, hi, hi - lo))
print("    ±5 パーセント（幅 %.0f）に落ちる驚き = **%.1f ビット** ── 偶然の帯の下端。" %
      (0.1 * step2, -math.log2(0.1 * step2 / (hi - lo))))
print("  ★ **これが手続きを持っていることの値打ち**：")
print("     『似ている』という印象を、その場で数字にして棄却できる。")
print("     第36回で『偶然の帯は選択効果』と書いたが、")
print("     **選択の網に掛からないものは、こうやって落ちていく。**")

print("=== ⑦ 第48回への引き継ぎ ===")
print("  今回：物理のパラメータ %d 個はすべて無次元の列にあり、" % tot)
print("        そのほぼ全部が説明されていない（%.1f ビット）。" % val)
print("        そして SI 2019 は『次元付きは帳簿』を公式に宣言していた。")
