# -*- coding: utf-8 -*-
# 第13回：流体と乱流に入れてみる ── ウェイトの足し算を機械的に検算する
# 規約：X̃ = a^(-w) X。 長さ・時間 w=+1（÷a）、質量・エネルギー w=−1（×a）
from fractions import Fraction as F
L=F(1); T=F(1); M=F(-1)          # 基本のウェイト
def w(nl,nt,nm): return nl*L+nt*T+nm*M    # 長さ^nl 時間^nt 質量^nm のウェイト

Q={
 "長さ L"                 : w(1,0,0),
 "時間 t"                 : w(0,1,0),
 "速度 v = L/T"           : w(1,-1,0),
 "質量 m"                 : w(0,0,1),
 "質量密度 ρ = M/L³"      : w(-3,0,1),
 "圧力 p = M/(L T²)"      : w(-1,-2,1),
 "粘性率 η = M/(L T)"     : w(-1,-1,1),
 "動粘性率 ν = L²/T"      : w(2,-1,0),
 "エネルギー散逸率 ε=L²/T³": w(2,-3,0),
 "角速度 Ω = 1/T"         : w(0,-1,0),
 "重力加速度 g = L/T²"     : w(1,-2,0),
 "表面張力 σ = M/T²"      : w(0,-2,1),
 "熱拡散率 κ = L²/T"       : w(2,-1,0),
}
print("=== 各量のウェイト（+1 は ÷a、−1 は ×a）===")
for k,v in Q.items(): print(f"  {k:26s} w = {str(v):>5}")

print("\n=== 無次元数を、機械的に検算する ===")
tests=[
 ("レイノルズ数 Re = ρvL/η",      Q["質量密度 ρ = M/L³"]+Q["速度 v = L/T"]+Q["長さ L"]-Q["粘性率 η = M/(L T)"]),
 ("マッハ数 Ma = v/c_s",          Q["速度 v = L/T"]-Q["速度 v = L/T"]),
 ("プラントル数 Pr = ν/κ",        Q["動粘性率 ν = L²/T"]-Q["熱拡散率 κ = L²/T"]),
 ("フルード数 Fr = v/√(gL)",      Q["速度 v = L/T"]-(Q["重力加速度 g = L/T²"]+Q["長さ L"])/2),
 ("ウェーバー数 We = ρv²L/σ",     Q["質量密度 ρ = M/L³"]+2*Q["速度 v = L/T"]+Q["長さ L"]-Q["表面張力 σ = M/T²"]),
 ("ストローハル数 St = ΩL/v",     Q["角速度 Ω = 1/T"]+Q["長さ L"]-Q["速度 v = L/T"]),
 ("コルモゴロフ長 η_K=(ν³/ε)^¼",  (3*Q["動粘性率 ν = L²/T"]-Q["エネルギー散逸率 ε=L²/T³"])/4),
]
for n,v in tests:
    tag = "不変 ✓" if v==0 else ("長さと同じ（÷a）✓" if v==1 else f"w={v}")
    print(f"  {n:30s} w = {str(v):>5}   {tag}")

print("\n=== レイノルズ数：四つの量は全部ちがうウェイトで動く ===")
parts=[("ρ",Q["質量密度 ρ = M/L³"],+1),("v",Q["速度 v = L/T"],+1),
       ("L",Q["長さ L"],+1),("η",Q["粘性率 η = M/(L T)"],-1)]
s=0
for n,v,sg in parts:
    s+=sg*v
    print(f"    {n}: w={str(v):>5}  （{'×a^'+str(-v) if v!=0 else '不変'}）")
print(f"    合計 = {s}  → Re は不変")

print("\n=== 指数は全部ただの数 ===")
for n in ["コルモゴロフの −5/3 則 E(k)∝ε^(2/3)k^(-5/3)",
          "臨界指数 ν, η, β, γ, δ",
          "フラクタル次元 D",
          "リアプノフ指数 × 経過時間 λt",
          "クライバー則の指数 3/4"]:
    print(f"    {n:44s} 無次元 → 不変")

print("\n=== 結論 ===")
print("  共形変換は『大きさ』にしか触れない。")
print("  構造・複雑さ・情報を測る指標は、ひとつ残らず無次元なので、手が届かない。")
print("  → 第6回『使われているメモリに手が届かない』の、複雑系版。")
