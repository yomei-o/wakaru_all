import math

ln2 = math.log(2)

def bits_from_sigma(n):
    """n σ のずれを、第19回の作法でビットに直す（両側 p 値）"""
    if n > 8:
        # erfc がアンダーフローする領域は漸近形で
        return (n * n / 2) / ln2 + math.log2(n * math.sqrt(2 * math.pi))
    p = math.erfc(n / math.sqrt(2))
    return -math.log2(p)

