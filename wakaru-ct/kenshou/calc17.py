# 第12回：真空に入れてみる ── 「定数」という名前が、帳簿だった
import math
c=299792458.0; hbar=1.054571817e-34; G=6.67430e-11; eV=1.602176634e-19
mP=math.sqrt(hbar*c/G); MPl_eV=mP*c*c/eV
Om,OL,Or=0.315,0.685,9.2e-5
rho_crit=1.878e-26*0.674**2
print("=== ρ̃ = a⁴ρ を三成分に当てる ===")
rows=[("放射","a^-4","一定"),("物質","a^-3","∝ a ∝ t"),("宇宙定数 Λ","一定","∝ a⁴ ∝ t⁴")]
print(f"  {'成分':14s} {'標準の絵':>10}  {'この絵（×a⁴）'}")
for n,a,b in rows: print(f"  {n:14s} {a:>10}  {b}")
print("\n  ★ 順序が完全に逆転する。")
print("    標準：いちばん速く薄まるのが放射、いちばん動かないのが Λ")
print("    この絵：いちばん動かないのが放射、いちばん速く育つのが Λ")
print("  → 『宇宙定数』という名前は、絵の取り方に依存している。")

print("\n=== 無次元にすると、どちらの絵でも同じ ===")
rho_L=rho_crit*OL
E_L=(rho_L*c*c*(hbar*c)**3)**0.25/eV
print(f"  ρ_Λ^(1/4) = {E_L*1e3:.3f} meV")
print(f"  ρ_Λ^(1/4)/M_Pl = {E_L/MPl_eV:.4e}   ← 不変")
print(f"  ρ_Λ/M_Pl⁴      = {(E_L/MPl_eV)**4:.4e}   ← 有名な 10^-123（宇宙定数問題）")
print("  → 宇宙定数問題は、絵を変えても一ミリも動かない（比は無次元だから）")

print("\n=== 『なぜ今？』問題も、動かない ===")
print(f"  今日の ρ_Λ/ρ_m = {OL/Om:.3f}   ← 無次元、不変")
a_eq=(Om/OL)**(1/3.)
print(f"  Λ と物質が等しくなる a = (Ω_m/Ω_Λ)^(1/3) = {a_eq:.4f}  →  z = {1/a_eq-1:.3f}")
print("  標準の絵： ρ_Λ/ρ_m ∝ a³")
print("  この絵  ： ρ̃_Λ/ρ̃_m = a⁴/a = a³   ← 同じ")
print("  → 比の時間変化まで同じ。『なぜ今か』は絵を変えても消えない。")

print("\n=== この絵で本当に『定数』なのは、放射だった ===")
print(f"  ρ̃_r = a⁴·ρ_r = 一定")
print(f"  今日の値 ρ_r = {rho_crit*Or*c*c:.4e} J/m³ が、宇宙の全歴史で不変")
print("  第11回で見た『光子ガスは完全に静止』の、エネルギー密度版")

print("\n=== おまけ：二つの小さいスケール ===")
mnu=0.05  # eV
print(f"  ρ_Λ^(1/4)/M_Pl = {E_L/MPl_eV:.3e}")
print(f"  m_ν/M_Pl       = {mnu/MPl_eV:.3e}")
print(f"  比 = {mnu/(E_L):.1f}   ← 自然界で最も小さい二つのスケールが 22 倍しか離れていない")
