# -*- coding: utf-8 -*-
# 第15回：化学と生物に入れてみる
import math
from fractions import Fraction as F
L=F(1); T=F(1); M=F(-1)
def w(nl,nt,nm): return nl*L+nt*T+nm*M
print("=== 化学：無次元で書かれているものは、全部そのまま ===")
for n,note in [("アレニウス因子 exp(−E_a/k_BT)","指数が無次元 → 不変"),
               ("平衡定数 K = exp(−ΔG/RT)","同上 → 不変"),
               ("pH = −log[H⁺]/[標準]","濃度比 → 不変"),
               ("結合エネルギー / k_BT","無次元 → 不変"),
               ("反応の活性化エネルギー比","無次元 → 不変")]:
    print(f"    {n:34s} {note}")
print("  → 化学反応の起きやすさは、この絵で一切変わらない（第8回のトンネル効果と同じ理由）")

print("\n=== 生物：クライバー則を分解する ===")
wB=w(2,-3,1)     # 代謝率 = エネルギー/時間 = M L²/T³
wM=w(0,0,1)      # 質量
print(f"  代謝率 B（M L²/T³）のウェイト = {wB}   → ×a^{-wB}")
print(f"  質量 M のウェイト             = {wM}   → ×a^{-wM}")
print(f"  B ∝ M^(3/4) が形を保つには、係数が ×a^{-(wB - F(3,4)*wM)} で動く必要がある")
print(f"    係数のウェイト = {wB - F(3,4)*wM}")
print("  → 指数 3/4 は不変。係数は次元付きなので動く（帳簿）。")
print("  ★ ゲージ不変な言い方：『二匹の代謝率の比 = （質量比)^(3/4)』── 比どうしなので不変")

print("\n=== 一生の心拍数は、無次元 ===")
print("  心拍数 ∝ M^(-1/4)、寿命 ∝ M^(+1/4) → 積は M^0")
beats=1.5e9
print(f"  哺乳類の一生の心拍数 ≈ {beats:.1e} 回（体重に依らない）→ 無次元 → 不変")

print("\n=== DNA の情報量 ===")
bp=3.1e9
print(f"  ヒトゲノム {bp:.1e} 塩基対 × 2 bit = {2*bp:.2e} bit = {2*bp/8/1e6:.0f} MB")
print("  ビットは無次元 → この絵でも同じ")

print("\n=== 生命が測れるものを、全部並べる ===")
for n in ["濃度比","反応速度の比","心拍数（回数）","世代数","塩基配列（情報）",
          "体長 ÷ 細胞の大きさ","代謝率の比","温度差 ÷ 温度"]:
    print(f"    {n:24s} 無次元 → 不変")
print("  → 生命は、宇宙が『膨張している』のか『質量が育っている』のかを、")
print("     原理的に知ることができない。第9回の原子の話を、生物まで押し上げた形。")

print("\n=== おまけ：二つの『歩数』を比べる ===")
t0=4.3536e17; tP=5.391247e-44
print(f"  宇宙の対数クロック ln(t₀/t_P) = {math.log(t0/tP):.1f} 歩")
print(f"  人間の一生の心拍          = {beats:.1e} 回")
print(f"  → 人間のほうが、宇宙より {beats/math.log(t0/tP):.1e} 倍多くステップを刻んでいる")
print("  （もちろん数え方が違う。だが、どちらも無次元であることは同じ）")
