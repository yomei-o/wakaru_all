def surprise(lo_a, hi_a, amin, amax):
    """\u5bfe\u6570\u4e00\u69d8\u306e\u4e8b\u524d [amin, amax] \u306e\u3082\u3068\u3067\u3001[lo_a, hi_a] \u306b\u5165\u308b\u9a5a\u304d"""
    lo = max(lo_a, amin)
    hi = min(hi_a, amax)
    if hi <= lo:
        return None
    P = (math.log10(hi) - math.log10(lo)) / (math.log10(amax) - math.log10(amin))
    P = min(P, 1.0)
    return -math.log2(P), P


