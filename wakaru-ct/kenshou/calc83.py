def root(deg, jmax=400.0):
    """\u03a3 deg(j) exp(\u22122\u03c0\u03b3\u221a(j(j+1))) = 1 \u3092 \u03b3 \u306b\u3064\u3044\u3066\u89e3\u304f"""
    def f(g):
        s, j = 0.0, 0.5
        while j <= jmax:
            s += deg(j) * math.exp(-2 * math.pi * g * math.sqrt(j * (j + 1)))
            j += 0.5
        return s - 1.0
    lo, hi = 0.01, 3.0
    for _ in range(300):
        mid = (lo + hi) / 2
        if f(mid) > 0:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


