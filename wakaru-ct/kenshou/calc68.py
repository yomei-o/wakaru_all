# -*- coding: utf-8 -*-
# 深掘り⑬：「陽子はクォークでできている」は、どうやって決まったのか
#           ── 三つの別々の主張が、いつ溶接されたかを数字で追う
import math

bic = 0.5 * math.log2(1701)

print("=== ① まず、主張が三つあることに気づく ===")
claims = [
    ("(1) 分類できる", "ハドロンは 3 種類の何かで**整理できる**", "1961", "**(A) 記法**"),
    ("(2) 中に何かある", "陽子の中に**点状の粒**がある", "1968", "**(B) 主張**"),
    ("(3) 同じものだ", "(1) の 3 種類と (2) の粒が**同一**", "1972", "**溶接**"),
]
print("  %-16s %-38s %-8s %s" % ("主張", "中身", "年", "第36回の分類"))
for a, b, c, d in claims:
    print("  %-16s %-38s %-8s %s" % (a, b, c, d))
print("")
print("  ★ ふつう『クォークの発見』と一括りにされるが、**別の話が三つある**。")
print("     (1) だけならクォークは**記法**でよく、実在しなくてよい。")
print("     ゲルマン自身が当初『数学的な道具』と言っていたのは、そのため。")

print("")
print("=== ② (1) 分類 ── ただし、これだけでは実在の証拠にならない ===")
print("  3 種類（u, d, s）で qqq と qq̄ を作ると：")
print("    中間子： 3 × 3 = 9 状態（ノネット）")
print("    バリオン： 3 ⊗ 3 ⊗ 3 = 27 = **10 + 8 + 8 + 1**")
print("  ★ 出てくるべき状態が**全部見つかり**、出てこないはずの状態が**一つも無い**。")
print("")
# Ω⁻：分類が空席を予言した
pred, obs = 1685.0, 1672.45
rel = abs(pred - obs) / obs
print("  Ω⁻ の予言（1962）： %.0f MeV → 実測（1964） %.2f MeV" % (pred, obs))
print("    相対差 %.3f %% → **%.1f ビット**" % (rel * 100, -math.log2(rel)))
print("  ★ しかしこれは **SU(3) の表現論**が当てただけ。")
print("     『3 つの数で分類できる』ことしか言っていない。**中身の話ではない**。")

print("")
print("=== ③ (2) 中に点状のものがある ── ラザフォードの再演 ===")
print("  硬い衝突（大きな Q²）で、二つの実験を比べる：")
print("")
print("  弾性散乱（陽子が壊れない）：形状因子 G = (1 + Q²/0.71)⁻²、断面積 ∝ G²")
print("  %-14s %-16s %s" % ("Q² [GeV²]", "G²（相対）", "── 広がった物の振る舞い"))
gs = []
for q2 in [1.0, 2.0, 4.0, 8.0]:
    g = (1 + q2 / 0.71) ** -2
    gs.append(g * g)
    print("  %-14.1f %-16.2e" % (q2, g * g))
drop = gs[0] / gs[-1]
print("  → Q² が 8 倍になると、**%.0f 倍に落ちる**（%.1f ビット）" % (drop, math.log2(drop)))
print("")
print("  非弾性散乱（陽子が壊れる）：構造関数 F₂(x, Q²)")
print("  → x を固定すると **Q² にほとんど依らない**（ビョルケン・スケーリング、1968 SLAC）")
print("     同じ Q² 範囲で変化は**十数 % 以内**")
print("")
print("  ★ **同じ的を同じように殴って、片方は %.0f 倍落ち、片方は落ちない。**" % drop)
print("     落ちない ＝ **殴っている相手に大きさが無い**。")
print("     ラザフォードが原子核を見つけたときと、まったく同じ論法。")
print("  ★ ここで初めて『中に何かある』が **(B) 主張の側**の話になった。")

print("")
print("=== ④ その『何か』のスピンは 1/2 ===")
print("  縦偏極と横偏極の比 R = σ_L/σ_T を測る：")
spins = [
    ("スピン 1/2", "R → 0", "**カラン–グロス関係** F₂ = 2xF₁"),
    ("スピン 0", "R → ∞", "σ_T が消える"),
    ("実測", "R = 0.18 ± 0.03", "**スピン 1/2 で決まり**"),
]
print("  %-16s %-20s %s" % ("仮定", "予言", "根拠"))
for a, b, c in spins:
    print("  %-16s %-20s %s" % (a, b, c))
print("  ★ **点状**（③）で **スピン 1/2**（④）。ここまでは電荷の話が出ていない。")

print("")
print("=== ⑤ (3) 溶接 ── 電荷が 2/3 と −1/3 であることを、どう示したか ===")
print("  電子で叩くと、粒の**電荷の 2 乗**に比例して見える。")
print("  ニュートリノで叩くと、弱い相互作用なので**電荷に依らず**全部見える。")
print("  → **二つの実験の比を取れば、⟨Q²⟩ がそのまま出る。**")
print("")
q_u, q_d = 2.0 / 3.0, -1.0 / 3.0
pred_ratio = (q_u ** 2 + q_d ** 2) / 2
obs_ratio, obs_err = 0.29, 0.02
print("  クォーク模型の予言： ⟨Q²⟩ = (({:.4f})² + ({:.4f})²)/2 = 5/18 = **{:.4f}**".format(
    q_u, q_d, pred_ratio))
print("  実測（CERN Gargamelle、1973）： **%.2f ± %.2f**" % (obs_ratio, obs_err))
print("  ずれ %.1f σ" % (abs(pred_ratio - obs_ratio) / obs_err))
print("")
alt = [
    ("整数電荷（Q = 1, 0）", (1 ** 2 + 0 ** 2) / 2),
    ("クォーク模型（2/3, −1/3）", pred_ratio),
]
print("  %-30s %-12s %s" % ("仮定", "⟨Q²⟩", "実測 0.29 と合うか"))
for a, v in alt:
    ok = "**合う**" if abs(v - obs_ratio) < 3 * obs_err else "**外れ**"
    print("  %-30s %-12.4f %s" % (a, v, ok))
print("")
print("  ★ **これが溶接の瞬間。** 分類の 3 種類（u, d, s）と、")
print("     中にある点状の粒が、**電荷という別の量で一致した**。")
print("  ★ 分数電荷は当時いちばん嫌がられた仮定で、")
print("     それが**独立な実験で当たった**ことが決定打になった。")

print("")
print("=== ⑥ 色が 3 つあることは、二つの経路で決まった ===")
print("  経路 A：Δ⁺⁺ = uuu、スピン全部そろえて対称 → **フェルミ統計に反する**")
print("    → 反対称にする自由度が要る → **色**。強制された追加（第66回の分類でいう ◎）。")
print("")
alpha = 1 / 137.035999
mpi, fpi = 134.9768, 92.28
gamma3 = alpha ** 2 * mpi ** 3 / (64 * math.pi ** 3 * fpi ** 2) * 1e6   # eV
obs_g, err_g = 7.80, 0.12
print("  経路 B：π⁰ → γγ の崩壊幅は **N_c² に比例**する")
for nc in [1, 2, 3, 4]:
    g = gamma3 * (nc / 3.0) ** 2
    print("    N_c = %d → Γ = %8.2f eV   （実測 %.2f ± %.2f）" % (nc, g, obs_g, err_g))
nc_fit = 3.0 * math.sqrt(obs_g / gamma3)
print("  ★ 実測から逆算すると **N_c = %.2f**。" % nc_fit)
print("     N_c = 1 なら %.2f eV ── **9 分の 1**。桁で外れる。" % (gamma3 / 9))
print("")
Rpred = 3 * (4 / 9 + 1 / 9 + 1 / 9)
print("  経路 B の別版： e⁺e⁻ → ハドロン の R 比")
print("    N_c = 3 の予言（チャーム閾値の下）： R = 3 × (4/9+1/9+1/9) = **%.2f**" % Rpred)
print("    実測 ≈ 2.1〜2.3（QCD 補正込み）  N_c = 1 なら R = %.2f ── **外れ**" % (Rpred / 3))

print("")
print("=== ⑦ そして、足りない半分が『次に来るもの』を予言した ===")
q_mom, g_mom = 0.54, 0.46
print("  運動量和則： 陽子の運動量を、中の粒が全部持っているはず。")
print("    ところが測ると、クォークが持っているのは **%.0f %%** だけ。" % (q_mom * 100))
print("    残り **%.0f %% が電気的に見えない何か**に持ち去られている。" % (g_mom * 100))
print("  ★ → グルーオンの予言。**1979 年、3 ジェット事象として発見**。")
print("  ★ これが決定的なのは ── **模型が『まだ足りない』と自分で言った**こと。")
print("     合わせ込みなら、足りない分は出てこない。")

print("")
print("=== ⑧ 反証もされている（＝ちゃんとした主張である証拠）===")
print("  クォーク模型は qqq と qq̄ しか**許さない**。だから禁じるものがある：")
forb = [
    ("電荷 ±2 の中間子", "見つかっていない"),
    ("ストレンジネス +1 のバリオン（Θ⁺）", "2003 年に『発見』報告 → **高統計で消滅**"),
    ("アイソスピン 2 の中間子", "見つかっていない"),
]
print("  %-34s %s" % ("模型が禁じるもの", "その後"))
for a, b in forb:
    print("  %-34s %s" % (a, b))
print("  ★ Θ⁺ は複数の実験が有意に見たと報告した ── それが**消えた**。")
print("     禁止が守られている。**当たるだけでなく、外れうる**主張になっている。")

print("")
print("=== ⑨ 帳簿 ===")
pay = 3 * bic
print("  払い（1964 年時点で新しく置いたもの）：")
print("    u, d, s の 3 種類 …… %.2f × 3 = **%.1f ビット**" % (bic, pay))
print("    ＋『電荷が分数』という、当時ゼロ点の仮定")
buys = [
    ("Ω⁻ の質量（発見前）", -math.log2(rel)),
    ("⟨Q²⟩ = 5/18（ν 対 e）", math.log2(0.5 / obs_err)),
    ("π⁰ → γγ の幅（N_c²）", math.log2(gamma3 / err_g)),
    ("R 比（色 3 色）", math.log2(10.0 / 0.3)),
    ("スケーリング（点状）", math.log2(drop)),
]
tot = 0.0
print("")
print("  %-30s %s" % ("買い", "ビット"))
for a, b in buys:
    tot += b
    print("  %-30s %.1f" % (a, b))
print("  %-30s **%.1f**" % ("合計（部分的）", tot))
print("")
print("  ★ **払い %.1f に対して、買い %.1f。** 差し引き **%+.1f ビット**。" % (pay, tot, tot - pay))
print("     しかもハドロン百数十個の量子数が全部生成される分を**数えていない**。")
print("  ★ 第66回の分類でいう **『矛盾に強制された追加』── 5 戦 5 勝の側**。")

print("")
print("=== ⑩ ただし ── 『できている』が曲者 ===")
mu, md, mp = 2.16, 4.67, 938.272
qmass = 2 * mu + md
print("  u クォーク %.2f MeV × 2 ＋ d クォーク %.2f MeV = **%.2f MeV**" % (mu, md, qmass))
print("  陽子の質量　　　　　　　　　　　　　　　　　　 = **%.2f MeV**" % mp)
print("  → クォークの質量が占める割合 **%.2f %%**" % (qmass / mp * 100))
print("")
print("  ★ **陽子の質量の 99 % は、クォークの質量ではない。**")
print("     グルーオン場と運動エネルギー、つまり**閉じ込めのエネルギー**。")
print("  ★ だから『クォークでできている』が正しいのは、")
print("     **電荷・バリオン数・スピン・フレーバー**について。")
print("     **質量については、ほとんど間違い**。")
print("  ★ 第3回の作法どおり ── **『何と比べて』を言わないと文にならない**。")
print("     『できている』も、何の話かを言って初めて真偽が決まる。")

print("")
print("=== ⑪ なぜ『取り出せないのに実在する』と言えるのか ===")
print("  漸近自由性（1973）： 距離が近いほど結合が弱くなる。")
print("    → **近くで見れば自由な点、離すと無限のエネルギーが要る**。")
print("  ★ つまり『取り出せない』ことは模型の**弱点ではなく予言**。")
print("     取り出せてしまったら、その方が理論の危機だった。")
print("  ★ これも ③ と同じ構造 ── **『見えない』を『こう見えないはず』に変えた**。")

print("")
print("=== ⑫ 正直な線 ===")
print("  ・⑨の『買い』のビットは事前範囲の取り方に依る（第66回と同じ弱点）。")
print("    ただし ⑤ の 5/18 と ⑥ の N_c = %.2f は、事前範囲をほとんど使わない。" % nc_fit)
print("  ・③の『十数 % 以内』は SLAC のスケーリング窓（x ≈ 0.25 付近）での話。")
print("    x が小さい所では **scaling violation** が実際にあり、それは QCD の予言どおり。")
print("  ・⑥の π⁰ の式はカイラル極限の主要項。実測との差 %.1f %% は高次補正の範囲。" %
      (abs(gamma3 - obs_g) / obs_g * 100))
print("  ・⑩の『99 %』はカレントクォーク質量での話。構成子クォーク（〜330 MeV）で")
print("    数えれば 100 % になるが、それは**閉じ込めの効果を質量に繰り込んだ記法**。")
print("    どちらが正しいかではなく、**どちらの帳簿かを言え**というのが第3回の要求。")
