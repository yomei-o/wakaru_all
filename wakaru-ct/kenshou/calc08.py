# 第4回：c*t=一定 の記法に入れると、宇宙論が「質量ひとつ」に潰れる
import math
kB=1.380649e-23; eV=1.602176634e-19
T0=2.7255
kT0=kB*T0/eV                      # eV
print(f"固定された物差し: k_B T0 = {kT0:.4e} eV  （この絵では温度は一定）")
print()
print("=== 育っていく閾値が、この一本を追い越す時刻 ===")
print(f"  {'できごと':22s} {'閾値 (今日の値)':>16} {'比':>10} {'t/t0':>12} {'1+z':>12}")
events=[
 ("中性子‐陽子質量差 Q", 1.293e6, 1.616),   # Q/kT = 1.616 で凍結 (T_f=0.8MeV)
 ("電子質量 m_e c^2",    0.511e6, 1.0),
 ("重水素の束縛 2.22MeV", 2.22e6, 22.2),     # T~0.1MeV
 ("水素のリュードベリ",    13.6,    52.6),    # 再結合
]
for name,E_today,ratio in events:
    # 質量の絵: E(t) = E_today * (t/t0),  条件 E(t)/kT0 = ratio
    tt = ratio*kT0/E_today
    print(f"  {name:22s} {E_today:16.4g} {ratio:10.4g} {tt:12.4e} {1/tt:12.4e}")

print()
print("  検算：再結合の 1+z が 1101 になるか ->", f"{1/(52.6*kT0/13.6):.1f}")
print("  検算：中性子凍結の T は 0.8 MeV か  ->", f"{1.293e6/1.616*1e-6:.3f} MeV")

print()
print("=== 距離の式：積分が要るか、閉じた式か ===")
print("  ΛCDM   : H0 d_C/c = ∫0^z dz'/sqrt(Ωr(1+z')^4+Ωm(1+z')^3+ΩΛ)   ← 数値積分")
print("  c*t=一定: H0 d_C/c = ln(1+z)                                   ← 閉じた式")
print()
rows=[("共動距離 d_C","∫dz/E","ln(1+z)"),
      ("光度距離 d_L","(1+z)∫dz/E","(1+z)ln(1+z)"),
      ("角径距離 d_A","∫dz/E /(1+z)","ln(1+z)/(1+z)"),
      ("ハッブル率 H(z)","H0 E(z)","H0 (1+z)"),
      ("そのときの年齢 t(z)","∫dz/[(1+z)E]","t0/(1+z)"),
      ("ルックバック時間","∫dz/[(1+z)E]","t0 z/(1+z)"),
      ("地平半径 R_H(z)","c/(H0 E)","c t0/(1+z)")]
