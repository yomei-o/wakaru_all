# Koide
me, mmu, mtau = 0.51099895000, 105.6583755, 1776.86
K = (me + mmu + mtau) / (math.sqrt(me) + math.sqrt(mmu) + math.sqrt(mtau)) ** 2
rel = abs(K - 2.0 / 3.0) / (2.0 / 3.0)
koide_buy = math.log2((1.0 - 1.0 / 3.0) / ((2.0 / 3.0) * rel))

# 量子レプトン相補性
thC, th12 = 13.04, 33.44
qlc_dev = abs(thC + th12 - 45.0)
qlc_buy = math.log2(90.0 / (2 * qlc_dev))

# θ13 ≈ θC/√2
th13 = 8.57
t13_pred = thC / math.sqrt(2)
t13_dev = abs(th13 - t13_pred)
t13_buy = math.log2(90.0 / (2 * t13_dev))

# b–τ 統一（GUT スケールで m_b/m_τ ≈ 1）
bt_dev = 0.10
bt_buy = math.log2(3.0 / (2 * bt_dev))

cands = [
    ("**小出の関係**（荷電レプトン）", koide_buy, 1000,
     "(Σm)/(Σ√m)² = 2/3、ずれ %.1e" % rel),
    ("b–τ 統一", bt_buy, 30, "GUT で m_b/m_τ → 1、10 % 以内"),
    ("θ₁₃ ≈ θ_C/√2", t13_buy, 300, "予言 %.2f°、実測 %.2f°" % (t13_pred, th13)),
    ("量子レプトン相補性", qlc_buy, 100, "θ_C + θ₁₂ = %.1f°（45° から %.1f°）" %
     (thC + th12, qlc_dev)),
]
