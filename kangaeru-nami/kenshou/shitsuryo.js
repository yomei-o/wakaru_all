// 質量は重力の積分か、光速は情報の積分か ── 二つの推測を検証する
'use strict';
const E=x=>x.toExponential(3);
const G=6.67430e-11, c=2.99792458e8, hbar=1.054571817e-34, kB=1.380649e-23;
const H0=67.4*1000/(3.0857e22);            // s^-1（67.4 km/s/Mpc）
const lP=Math.sqrt(hbar*G/(c*c*c));
const tUniv=13.8e9*3.155760e7;

console.log('##################################################################');
console.log('# 1. 「質量は宇宙の重力の積分」── マッハ原理');
console.log('##################################################################\n');
console.log('  これは思いつきではなく、150 年の歴史がある考えです。\n');
console.log('  マッハ（1883）：慣性は、宇宙の全物質との関係で決まる。');
console.log('  シャマ（1953）：それを式にすると ── \n');
console.log('      Σ_i  G m_i / (r_i c²)  ≈  1\n');
console.log('  「宇宙のすべての質量からの重力ポテンシャルの和が、ちょうど c² 程度」。');
console.log('  実際に計算してみます。\n');
const RH=c/H0;
const rhoC=3*H0*H0/(8*Math.PI*G);
const M=rhoC*(4/3)*Math.PI*Math.pow(RH,3);
console.log(`  ハッブル定数 H₀ = ${E(H0)} /s`);
console.log(`  ハッブル半径 R = c/H₀ = ${E(RH)} m = ${(RH/9.461e15/1e8).toFixed(0)} 億光年`);
console.log(`  臨界密度 ρ_c = 3H₀²/8πG = ${E(rhoC)} kg/m³`);
console.log(`  その中の質量 M = ρ_c·(4/3)πR³ = ${E(M)} kg\n`);
const sciama=G*M/(RH*c*c);
console.log(`  ★ GM/(Rc²) = ${sciama.toFixed(6)}`);
console.log('\n  ── ぴったり 1/2 です。偶然でしょうか。');

console.log('\n##################################################################');
console.log('# 2. 答え ── 偶然ではなく、恒等式でした');
console.log('##################################################################\n');
console.log('  代入して整理すると：\n');
console.log('      M = ρ_c ·(4/3)πR³');
console.log('        = [3H²/(8πG)] · (4/3)π (c/H)³');
console.log('        = c³ / (2GH)\n');
console.log('      GM/(Rc²) = G·[c³/(2GH)] / [(c/H)·c²]');
console.log('               = [c³/(2H)] · [H/c³]');
console.log('               = 1/2         ★ 厳密に\n');
console.log('  ★ G も c も H も消えます。');
console.log('    「臨界密度の宇宙」と定義した時点で、この比は 1/2 に決まっている。\n');
console.log('  ⇒ つまり ── シャマの一致は、マッハ原理の証拠ではありません。');
console.log('    平坦な宇宙であることの言い換えにすぎない。恒等式です。\n');
console.log('  ただし空振りでもありません。');
console.log('  「宇宙がちょうど臨界密度である（平坦である）」こと自体は観測事実で、');
console.log('  それがこの一致を成立させています。');

console.log('\n##################################################################');
console.log('# 3. では、マッハ原理は検証できるのか ── できます');
console.log('##################################################################\n');
console.log('  「慣性質量が宇宙の物質分布で決まる」を具体的な理論にしたのが');
console.log('  ブランス＝ディッケ理論です。G を場 φ に置き換え、φ が物質分布で決まる。\n');
console.log('      1/G  →  φ,    □φ = 8π/(3+2ω) · T\n');
console.log('  ω は理論のパラメータで、ω → ∞ で一般相対論に戻ります。');
console.log('  ★ ω が有限なら「質量は重力の積分」── マッハ的。\n');
const omega=40000;
console.log(`  カッシーニ探査機による測定（2003）: ω > ${E(omega)}`);
console.log(`  → 一般相対論からのずれ ∝ 1/(2+ω) < ${E(1/(2+omega))}\n`);
console.log('  ★ つまり ── 「質量は重力の積分である」という考えは、');
console.log(`    実際に定式化して測ると、10⁻⁵ の精度で否定されています。`);
console.log('\n  ⇒ 発想としては正しい方向でしたが、自然はそう作られていなかった。');
console.log('    重力定数は、宇宙の物質分布から「計算される量」ではないようです。');

console.log('\n##################################################################');
console.log('# 4. 「光速は情報量の積分」── まず何が計算できるか');
console.log('##################################################################\n');
console.log('  これも由緒のある方向です。ホログラフィック原理を使うと、');
console.log('  宇宙が保持できる情報量が計算できます。\n');
const A=4*Math.PI*RH*RH;
const bits=A/(4*lP*lP)/Math.LN2;
console.log(`  プランク長 l_P = ${E(lP)} m`);
console.log(`  ハッブル地平の面積 A = 4πR² = ${E(A)} m²`);
console.log(`  最大の情報量 = A/(4 l_P² ln2) = ${E(bits)} ビット\n`);
console.log(`  ★ 約 10^${Math.log10(bits).toFixed(0)} ビット。よく引かれる 10^122 と一致します。\n`);
const Etot=M*c*c;
const ops=2*Etot*tUniv/(Math.PI*hbar);
console.log('  そして計算回数の上限（マーゴラス＝レヴィティン限界）：\n');
console.log('      演算速度 ≤ 2E/(πħ)\n');
console.log(`  宇宙のエネルギー E = Mc² = ${E(Etot)} J`);
console.log(`  宇宙年齢 ${E(tUniv)} s`);
console.log(`  → 総演算回数 ≤ ${E(ops)} = 10^${Math.log10(ops).toFixed(0)}\n`);
console.log('  ★ 宇宙は 10^122 ビットに対して 10^121 回の演算をした ── ロイドの評価。');
console.log('    ここまでは、きちんと計算できます。');

console.log('\n##################################################################');
console.log('# 5. しかし ── 「c は情報の積分」にはならない');
console.log('##################################################################\n');
console.log('  第 3 回で見たとおり、c は定義値です。測る対象ではない。');
