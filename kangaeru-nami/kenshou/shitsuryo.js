console.log('  ★ これは発見ではありません。プランク単位の定義がそうなっているだけ。');
console.log('    仮に時空が計算格子だとしても、c は「1 刻みで何マス進むか」── ');
console.log('    格子の目盛りの読み替えであって、積分される量ではありません。\n');
