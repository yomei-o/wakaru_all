def best_rational(x, qmax=10):
    f = Fraction(x).limit_denominator(qmax)
    return f, abs(float(f) - x) / x


def allratios(ms):
    out = []
    for i in range(len(ms)):
        for j in range(i + 1, len(ms)):
            out.append(max(ms[i], ms[j]) / min(ms[i], ms[j]))
    return out


def score(ms):
    rs = allratios(ms)
    e = [best_rational(r)[1] for r in rs]
    return sum(e) / len(e), sum(1 for x in e if x < 0.002), len(rs)


