print("     『パラメータいくつ』しか数えていなくて、『計算いくら』を数えていない。")
print("     同じ精度を出す二つの理論でも、**片方が 10¹⁹ flops 要るなら同じではない**。")
print("  ★ そして今回の答え：")
print("     **計算が『わけわかんない』のは、それがいちばん安い通貨だから。**")
print("     簡単にした分は、必ずパラメータか精度で払う。")

print("")
