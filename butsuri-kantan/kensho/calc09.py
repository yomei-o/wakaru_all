# -*- coding: utf-8 -*-
# 第9回「生の実数の厳密値は一件もない」に、反例を探す
import math

print("=== ① 第9回の主張を、正確に書き直す ===")
print("  主張：厳密値は**整数・小さい有理数・π の有理数倍**しかない。")
print("  これに反例があるか ── **π 以外の名前つき定数**が厳密値に出る例を探す。")

print("")
print("=== ② 反例その一：黒体輻射の光子数密度に ζ(3) が出る ===")
print("  ζ(3) = Σ 1/n³ （アペリーの定数）。厳密に：")
print("    n_γ = (2ζ(3)/π²)·(k_BT/ħc)³")
z3 = sum(1.0 / n ** 3 for n in range(1, 4000000))
print("")
print("  数値で確認（Σ 1/n³ を 400 万項）：")
print("    ζ(3) = **%.9f**" % z3)
print("    参考値 1.202056903…  → 一致 %.1e" % abs(z3 - 1.2020569032) )
print("")
print("  ★ **これは厳密値です。** 自由場のボーズ積分から出る。")
print("  ★ しかし ζ(3) は **π の有理数倍ではありません**。")
print("     （ζ(2)=π²/6、ζ(4)=π⁴/90 は π の冪だが、**奇数の ζ は違う**。")
print("      ζ(3) が無理数であることは 1978 年アペリーが証明。")
print("      π との閉じた関係は**知られていない**。）")
print("")
for k, v, lab in [(2, math.pi ** 2 / 6, "π²/6"),
                  (3, z3, "**閉じた形なし**"),
                  (4, math.pi ** 4 / 90, "π⁴/90")]:
    print("    ζ(%d) = %.9f   %s" % (k, v, lab))
print("  ★ **偶数だけ π の冪になる。奇数は名前つきの新しい定数。**")

print("")
print("=== ③ 反例その二：2 次元イジングの臨界自由エネルギーにカタラン定数 ===")
print("  オンサーガーの厳密解（正方格子、臨界点 sinh 2K = 1）：")
print("    −βf = ln2 + (1/8π²)∬ ln[2 − cosθ₁ − cosθ₂] dθ₁dθ₂")
print("  これを数値積分する：")

N = 3000
tot = 0.0
for i in range(N):
    t1 = 2 * math.pi * (i + 0.5) / N
    c1 = math.cos(t1)
    s = 0.0
    for j in range(N):
        t2 = 2 * math.pi * (j + 0.5) / N
        v = 2.0 - c1 - math.cos(t2)
        s += math.log(v) if v > 1e-14 else math.log(1e-14)
    tot += s
integ = tot * (2 * math.pi / N) ** 2 / (8 * math.pi ** 2)
f_num = math.log(2.0) + integ   # 定数項は ln2（ln2/2 ではない）

# カタラン定数
G = 0.0
for n in range(0, 2000000):
    G += (-1.0) ** n / (2.0 * n + 1) ** 2
f_cat = 0.5 * math.log(2.0) + 2 * G / math.pi

print("    数値積分（%d×%d 点）　　 −βf = **%.6f**" % (N, N, f_num))
print("    ln2/2 + 2G/π（G＝カタラン）−βf = **%.6f**" % f_cat)
print("    差 = %.2e" % abs(f_num - f_cat))
print("")
print("    カタラン定数 G = **%.9f**" % G)
print("  ★ **7 桁一致します。**（残差 %.0e は数値積分の限界）" % abs(f_num - f_cat))
print("  ★ カタラン定数も、**π の有理数倍ではありません**。")
print("     無理数かどうかすら**証明されていない**。")

print("")
print("=== ④ 他にも同じ型がある ===")
more = [
    ("黒体の光子数", "2ζ(3)/π²", "ζ(3)", "自由場のボーズ積分"),
    ("黒体のエントロピー", "∝ ζ(4)=π⁴/90", "π の冪", "同上（偶数なので π）"),
    ("2 次元イジング臨界自由エネルギー", "ln2/2 + 2G/π", "カタラン G", "可解模型"),
    ("2 次元イジング自発磁化", "(1−k²)^(1/8)", "**有理数の冪**", "可解模型"),
    ("ドゥバイ模型の低温比熱", "∝ π⁴/5", "π の冪", "自由場"),
    ("3 ループの β 関数係数", "ζ(3) を含む", "ζ(3)", "**多ループ積分**"),
]
print("  %-34s %-22s %-14s %s" % ("量", "厳密値", "含む定数", "出どころ"))
for a, b, c, d in more:
    print("  %-34s %-22s %-14s %s" % (a, b, c, d))
print("")
print("  ★ **多ループのファインマン積分にも ζ(3), ζ(5) が出ます**（多重ゼータ値）。")
print("     つまり反例は例外ではなく、**一つの族**でした。")

print("")
print("=== ⑤ だから、主張はこう直る ===")
print("  × 「厳密値は整数・有理数・π の有理数倍しかない」")
print("  ○ **「厳密値は必ず閉じた形を持つ」**")
print("")
kinds = [
    ("整数・有理数", "数え上げ・群論・位相", "N_c=3, C_F=4/3, b₀=9"),
    ("π の有理数倍", "自由場のガウス積分", "A/4, −π/12, π²/60"),
    ("**名前つきの定数**", "**自由場でも高次／可解模型**", "**ζ(3), カタラン G**"),
    ("代数的数", "可解模型の指数", "(1−k²)^(1/8)"),
    ("── ここから先 ──", "", ""),
    ("**閉じた形なし**", "**相互作用を実際に解いた答え**", "**m_p/√σ, 3D イジング ν**"),
]
print("  %-24s %-32s %s" % ("値の型", "出どころ", "例"))
for a, b, c in kinds:
    print("  %-24s %-32s %s" % (a, b, c))

print("")
print("=== ⑥ 境目は動かなかった ===")
print("  ★ 反例は、**境目の上側を広げただけ**でした。")
print("     ζ(3) もカタラン G も、**式で書ける**（無限級数として定義される）。")
print("  ★ 一方 m_p/√σ = 2.13… は、**数値でしか知られていません**。")
print("     級数も積分も、それを与える式が一つも書かれていない。")
print("  ★ → **第9回の分類の境目（相互作用を解いたかどうか）は、そのまま生きています。**")
print("     直すべきは『整数と π しかない』という**言い方の方**。")

print("")
